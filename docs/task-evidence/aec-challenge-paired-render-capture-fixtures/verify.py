"""Read-only strict verifier for the AEC paired-fixture evidence package.

Usage::

    PYTHONDONTWRITEBYTECODE=1 python3 verify.py

Fails closed on non-canonical or duplicate-key/nonfinite JSON, stale digests,
stale pins, a non-evidence profile, a promoted missing result, a qualified or
approved claim, a pooled partition, an unblocked release gate, license gaps,
README digest drift, out-of-scope worktree changes, whitespace damage or a
dirty ``git diff --check``.  Never writes.
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path
from typing import Any, Dict, List

sys.dont_write_bytecode = True

import reference  # noqa: E402

HERE = Path(__file__).resolve().parent
SDK_ROOT = HERE.parents[2]
SOURCE_ROOT = SDK_ROOT.parents[2]
REPORT = HERE / "report.json"
SIDECAR = HERE / "report.json.sha256"
CONTRACT = HERE / "contract.json"
PINS = HERE / "SOURCES.sha256"
README = HERE / "README.md"

SPDX_LICENSE = "SPDX" "-License-Identifier: Apache-2.0"
SPDX_COPYRIGHT = "SPDX" "-FileCopyrightText: 2026 Tsakanyan Hovhannes"
LICENSE_SIDECARS = (
    "SOURCES.sha256.license",
    "contract.json.license",
    "report.json.license",
    "report.json.sha256.license",
)
REQUIRED_REPORT_KEYS = {
    "schema_id", "task", "title", "component", "repository", "branch",
    "base_commit", "status", "evidence_status", "proposal_only", "decision",
    "defer_before", "scope", "acceptance_profile", "format",
    "source_and_metadata", "fixture_partitions", "pair_structure",
    "presence_probe", "admission_controls", "adverse_rejections",
    "adverse_all_rejected", "rights", "exact_blockers", "release_gates",
    "qualification", "boundary", "board_row", "source_pins", "boundary_pins",
    "repeatability", "negative_claims", "reopen_condition",
}
REQUIRED_CONTRACT_KEYS = {
    "schema_id", "task", "title", "component", "repository", "branch",
    "base_commit", "status", "evidence_status", "proposal_only", "decision",
    "defer_before", "qualification_status", "verification_profile", "scope",
    "format", "public_boundary", "reference", "board_row", "exact_blockers",
    "release_gates", "source_pins", "boundary_pins", "artifact_pins",
    "negative_claims", "reopen_condition",
}


def strict_json(path: Path) -> Any:
    return reference.load_strict_json(path)


def check_json_files(errors: List[str]) -> Dict[str, Any]:
    try:
        report = strict_json(REPORT)
        contract = strict_json(CONTRACT)
    except (OSError, ValueError) as error:
        errors.append("strict JSON failed: " + str(error))
        return {}
    if not isinstance(report, dict) or not isinstance(contract, dict):
        errors.append("report or contract root is not an object")
        return {}
    if REPORT.read_bytes() != (reference.canonical_text(report) + "\n").encode("utf-8"):
        errors.append("report.json is not canonical byte output")
    if CONTRACT.read_bytes() != (reference.canonical_text(contract) + "\n").encode("utf-8"):
        errors.append("contract.json is not canonical byte output")
    _, digest = reference.canonical_report(report)
    if SIDECAR.read_text(encoding="ascii") != digest + "\n":
        errors.append("report.json.sha256 is stale")
    return {"report": report, "contract": contract}


def check_pins(errors: List[str]) -> int:
    count = 0
    for raw in PINS.read_text(encoding="utf-8").splitlines():
        if not raw or raw.startswith("#"):
            continue
        count += 1
        parts = raw.split("  ", 1)
        if len(parts) != 2 or len(parts[0]) != 64:
            errors.append("malformed pin line: " + repr(raw))
            continue
        digest, raw_path = parts
        if raw_path.startswith("source:"):
            path = SOURCE_ROOT / raw_path.split(":", 1)[1]
        else:
            path = SDK_ROOT / raw_path
        if not path.is_file():
            errors.append("pinned file missing: " + raw_path)
        elif reference.sha256_bytes(path.read_bytes()) != digest:
            errors.append("pinned bytes changed: " + raw_path)
    if PINS.read_bytes() != reference.sources_bytes():
        errors.append("SOURCES.sha256 is not the deterministic generated bytes")
    return count


def check_artifact_pins(errors: List[str], contract: Dict[str, Any]) -> None:
    pins = contract.get("artifact_pins")
    if not isinstance(pins, dict):
        errors.append("contract artifact_pins is not an object")
        return
    expected_names = {reference.TASK_PREFIX + name
                      for name in reference.ARTIFACT_FILES}
    if set(pins) != expected_names:
        errors.append("artifact pin set mismatch")
    for path, digest in pins.items():
        full = SDK_ROOT / path
        if not full.is_file():
            errors.append("artifact pin missing: " + path)
        elif reference.file_digest(full) != digest:
            errors.append("artifact pin stale: " + path)
    for forbidden in ("contract.json", "SOURCES.sha256"):
        if reference.TASK_PREFIX + forbidden in pins:
            errors.append("self-referential artifact pin: " + forbidden)


def check_board(errors: List[str], report: Dict[str, Any],
                contract: Dict[str, Any]) -> None:
    live = reference.board_row()
    if report.get("board_row") != live:
        errors.append("report board identity is stale")
    if contract.get("board_row") != live:
        errors.append("contract board identity is stale")
    row = report.get("board_row", {})
    if row.get("full_tasks_json_hashed") is not False:
        errors.append("full task board is hashed")
    stable = row.get("stable_fields", {})
    if reference.object_digest(stable) != row.get("stable_sha256"):
        errors.append("stable board hash mismatch")
    if stable.get("id") != reference.TASK_ID:
        errors.append("stable board task id mismatch")
    for section in ("source_pins", "boundary_pins"):
        for path in report.get(section, {}):
            if path.endswith("TASKS.json"):
                errors.append("mutable task board is pinned in " + section)


def check_source_pins(errors: List[str], report: Dict[str, Any],
                      contract: Dict[str, Any]) -> None:
    if report.get("source_pins") != reference.SOURCE_PINS:
        errors.append("report source pins differ from the frozen table")
    if report.get("boundary_pins") != reference.BOUNDARY_PINS:
        errors.append("report boundary pins differ from the frozen table")
    if contract.get("source_pins") != reference.SOURCE_PINS:
        errors.append("contract source pins differ from the frozen table")
    if contract.get("boundary_pins") != reference.BOUNDARY_PINS:
        errors.append("contract boundary pins differ from the frozen table")


def check_profile(errors: List[str], report: Dict[str, Any]) -> None:
    profile = report["acceptance_profile"]
    if profile.get("profile") != "evidence":
        errors.append("evidence acceptance profile not recorded")
    items = profile.get("required_items", {})
    if len(items) != 6:
        errors.append("evidence profile item set mismatch")
    for name, item in items.items():
        if item.get("status") not in {"declared_only", "recorded", "blocked"}:
            errors.append("evidence profile item promoted: " + name)
    if items.get("representative_valid_result_validated", {}).get(
            "status") != "blocked":
        errors.append("representative valid result is not blocked")
    if items.get("invalid_or_missing_case_validated", {}).get(
            "status") != "recorded":
        errors.append("invalid/missing control is not recorded")
    if items.get("pinned_scorer_corpus_and_cohort", {}).get(
            "status") != "blocked":
        errors.append("scorer/cohort item is not blocked")


def check_partitions(errors: List[str], report: Dict[str, Any]) -> None:
    partitions = report["fixture_partitions"]
    synthetic = partitions["synthetic_train"]
    recorded = partitions["recorded_train"]
    if synthetic["scenario_count"] != 12 or synthetic["item_count"] != 48:
        errors.append("synthetic partition counts changed")
    if recorded["group_count"] != 12 or recorded["item_count"] != 108:
        errors.append("recorded partition counts changed")
    for partition in (synthetic, recorded):
        if partition["items_present"] != 0 or partition["items_verified"] != 0:
            errors.append("a fixture item claims presence or verification")
        if not reference.SHA256_PATTERN.fullmatch(
                str(partition.get("ledger_sha256", ""))):
            errors.append("missing partition ledger digest")
        if len(partition["items"]) != partition["item_count"]:
            errors.append("partition item ledger is incomplete")
    if synthetic["ledger_sha256"] == recorded["ledger_sha256"]:
        errors.append("partitions share a ledger")
    if synthetic["rights_status"] != \
            "provisional_source_family_mapping_not_approved":
        errors.append("synthetic rights status is promoted")
    if recorded["rights_status"] != "not_cleared_no_participant_terms":
        errors.append("recorded rights status is promoted")
    if partitions["pooling"]["subsets_pooled"] is not False:
        errors.append("fixture subsets are pooled")
    if synthetic["declared_audio_parameters"] is not None:
        errors.append("invented synthetic audio parameters")
    if recorded["blind_test_data_used"] is not False:
        errors.append("recorded subset uses blind test data")
    synthetic_names = {item["name"] for item in synthetic["items"]}
    recorded_names = {item["name"] for item in recorded["items"]}
    if not synthetic_names.isdisjoint(recorded_names):
        errors.append("synthetic and recorded items overlap")


def check_pair_structure(errors: List[str], report: Dict[str, Any]) -> None:
    pairs = report["pair_structure"]
    if pairs["synthetic_all_roles_complete"] is not True:
        errors.append("synthetic roles are incomplete")
    if pairs["synthetic_max_byte_spread"] != 0:
        errors.append("synthetic declared lengths differ")
    if pairs["recorded_pair_count"] != 48:
        errors.append("recorded pair count changed")
    if pairs["recorded_unequal_pair_count"] != 33:
        errors.append("recorded unequal pair count changed")
    if pairs["recorded_max_pair_delta_frames"] != 1760:
        errors.append("recorded max pair delta changed")
    if any(pair["equal_length"] is not (pair["delta_frames"] == 0)
           for pair in pairs["recorded_pairs"]):
        errors.append("recorded pair equality flag is inconsistent")


def check_presence(errors: List[str], report: Dict[str, Any]) -> None:
    probe = report["presence_probe"]
    if probe["bounded"] is not True:
        errors.append("presence probe is not bounded")
    if probe["synthetic"]["directory_present"] is not False:
        errors.append("synthetic fixture directory is present")
    if probe["synthetic"]["declared_files_present"] != 0:
        errors.append("a declared synthetic fixture is present")
    if probe["recorded"]["declared_files_present"] != 0:
        errors.append("a declared recorded fixture is present")
    if probe["upstream_source_metadata"]["present"] is not False:
        errors.append("upstream source metadata is present")
    if probe["upstream_source_metadata"]["verified"] is not False:
        errors.append("upstream source metadata is claimed verified")
    if any(entry["present"] for entry in probe["probed_paths"]):
        errors.append("a probed fixture or metadata path is present")


def check_controls(errors: List[str], report: Dict[str, Any]) -> None:
    controls = report["admission_controls"]
    live = controls["recorded_declaration_live"]
    if live["decision"] != "DEFER" or live["qualifies"] is not False:
        errors.append("live recorded declaration is admitted")
    if live["item_count"] != 108 or live["missing_count"] != 108:
        errors.append("live missing-byte control changed")
    if live["verified"] != 0 or live["bytes_verified"] is not False:
        errors.append("live control claims verified bytes")
    gap = controls["synthetic_declaration_gap"]
    if gap["status"] != "rejected" or gap["rejected_code"] != \
            "unsupported_sample_rate":
        errors.append("synthetic metadata gap is not rejected")
    representative = controls["representative_valid_result"]
    if representative["status"] != "absent" or representative["present"] is not False:
        errors.append("representative valid result is promoted")
    policy = controls["admission_policy"]
    if policy["admitting_branch_exists"] is not False:
        errors.append("an admitting branch is declared")
    if policy["always_defer"] is not True:
        errors.append("the gate does not always defer")
    if policy["metadata_only_can_qualify"] is not False:
        errors.append("metadata-only qualification is allowed")


def check_report(errors: List[str], report: Dict[str, Any]) -> None:
    if not REQUIRED_REPORT_KEYS <= set(report):
        errors.append("report missing sections: "
                      + ", ".join(sorted(REQUIRED_REPORT_KEYS - set(report))))
        return
    if report["schema_id"] != reference.REPORT_SCHEMA:
        errors.append("unexpected report schema")
    if report["status"] != "proposal_only_incomplete":
        errors.append("report is not proposal-only incomplete")
    if report["proposal_only"] is not True:
        errors.append("report is not proposal-only")
    if report["evidence_status"] != "incomplete" or report["decision"] != "DEFER":
        errors.append("missing incomplete/DEFER disposition")
    if report["defer_before"] != "optional_evidence_adapter_exposure":
        errors.append("unexpected defer point")
    if report["branch"] != reference.BRANCH:
        errors.append("report branch mismatch")
    if report["base_commit"] != reference.BASE_COMMIT:
        errors.append("report base commit mismatch")

    qualification = report["qualification"]
    if qualification.get("status") != "not_qualified":
        errors.append("qualification status is not not_qualified")
    for flag in ("qualifies", "all_required_results_present",
                 "missing_result_promoted", "fixture_bytes_verified",
                 "rights_approved", "paired_cohort_frozen", "scorer_pinned",
                 "representative_valid_result", "provider_intake",
                 "release_claim"):
        if qualification.get(flag) is not False:
            errors.append("qualification flag promoted: " + flag)
    if qualification.get("invalid_or_missing_control") is not True:
        errors.append("invalid/missing control is not recorded")

    gates = report["release_gates"]
    if len(gates) != 8:
        errors.append("expected exactly eight release gates")
    gate_ids = [gate.get("id") for gate in gates]
    if gate_ids != [f"RG-{index:02d}" for index in range(1, 9)]:
        errors.append("release gate IDs are not RG-01..RG-08")
    if any(gate.get("status") != "blocked" for gate in gates):
        errors.append("a release gate is not blocked")

    check_profile(errors, report)
    check_partitions(errors, report)
    check_pair_structure(errors, report)
    check_presence(errors, report)
    check_controls(errors, report)

    source = report["source_and_metadata"]
    if source["source_revision"] != reference.SOURCE_REVISION:
        errors.append("source revision mismatch")
    if source["source_metadata_present"] is not False:
        errors.append("source metadata presence is claimed")
    if source["source_metadata_verified"] is not False:
        errors.append("source metadata verification is claimed")
    prior = source["prior_reported_aggregates"]
    if prior["reexecuted"] is not False or prior["adopted"] is not False:
        errors.append("prior pilot aggregates are adopted")

    adverse = report["adverse_rejections"]
    if len(adverse) < 40 or report.get("adverse_all_rejected") is not True:
        errors.append("adverse rejection count/flag mismatch")
    for item in adverse:
        if item.get("status") != "rejected":
            errors.append("adverse case not rejected: " + item["case_id"])
        if item.get("state_unchanged") is not True:
            errors.append("adverse case mutated state: " + item["case_id"])

    rights = report["rights"]
    if rights["status"] != "not_approved":
        errors.append("rights status is promoted")
    for subset in ("synthetic_subset", "recorded_subset"):
        if rights[subset].get("approval") is not False:
            errors.append("rights approval claimed: " + subset)
    if rights["acceptance_use"] is not False or rights["redistribution"] is not False:
        errors.append("acceptance or redistribution is claimed")
    if rights["approval_record"] is not None:
        errors.append("an approval record is claimed")

    boundary = report["boundary"]
    if not boundary or any(value is not False for value in boundary.values()):
        errors.append("a boundary flag claims a change")

    repeat = report["repeatability"]
    if repeat.get("runs") != 3 or repeat.get("byte_identical") is not True:
        errors.append("repeatability is not three byte-identical runs")
    digests = repeat.get("core_digests", [])
    if len(digests) != 3 or len(set(digests)) != 1:
        errors.append("core repeat digests differ")

    text = reference.canonical_text(report)
    for forbidden in ('"qualifies":true', '"status":"qualified"',
                      '"approval":true', '"rights_approved":true',
                      '"fixture_bytes_verified":true', '"release_claim":true',
                      '"adopted":true', '"reexecuted":true'):
        if forbidden in text:
            errors.append("canonical report contains a promoted claim: "
                          + forbidden)


def check_contract(errors: List[str], contract: Dict[str, Any],
                   report: Dict[str, Any]) -> None:
    if not REQUIRED_CONTRACT_KEYS <= set(contract):
        errors.append("contract missing sections: "
                      + ", ".join(sorted(REQUIRED_CONTRACT_KEYS - set(contract))))
        return
    if contract["schema_id"] != reference.CONTRACT_SCHEMA:
        errors.append("unexpected contract schema")
    if contract["task"] != reference.TASK_ID or contract["component"] != reference.COMPONENT:
        errors.append("contract task or component mismatch")
    if contract["base_commit"] != reference.BASE_COMMIT:
        errors.append("contract base commit mismatch")
    if contract["branch"] != reference.BRANCH:
        errors.append("contract branch mismatch")
    if contract["decision"] != "DEFER" or contract["evidence_status"] != "incomplete":
        errors.append("contract disposition is not DEFER/incomplete")
    if contract["qualification_status"] != "not_qualified":
        errors.append("contract qualification is not not_qualified")
    if contract["verification_profile"] != "evidence":
        errors.append("contract verification profile mismatch")
    if contract.get("release_gates") != report.get("release_gates"):
        errors.append("contract/report release gates differ")
    if contract.get("exact_blockers") != report.get("exact_blockers"):
        errors.append("contract/report blockers differ")
    boundary = contract.get("public_boundary", {})
    for key in ("c_provider_added", "public_api_abi_changed",
                "installed_v0_behavior_changed", "shared_build_or_ci_changed"):
        if boundary.get(key) is not False:
            errors.append("contract boundary flag is not false: " + key)
    scope = contract.get("scope", {})
    if scope.get("synthetic_only") is not True or scope.get("task_local_only") is not True:
        errors.append("contract scope must be synthetic-only and task-local")
    for key, value in scope.items():
        if key in {"synthetic_only", "task_local_only"}:
            continue
        if value is not False:
            errors.append("contract scope flag is not false: " + key)
    check_artifact_pins(errors, contract)


def check_repeats(errors: List[str], report: Dict[str, Any]) -> None:
    if not report:
        return
    texts = []
    for _ in range(3):
        built = reference.build_report()
        text, _ = reference.canonical_report(built)
        texts.append(text)
    if len(set(texts)) != 1:
        errors.append("three fresh report builds differ")
    if texts[0].encode("utf-8") != REPORT.read_bytes():
        errors.append("fresh build does not match report.json")


def _table_rows(text: str, start: str, end: str) -> List[List[str]]:
    if start not in text or end not in text:
        return []
    section = text.split(start, 1)[1].split(end, 1)[0]
    rows: List[List[str]] = []
    for line in section.splitlines():
        stripped = line.strip()
        if not stripped.startswith("|"):
            continue
        cells = [cell.strip().strip("`") for cell in stripped.strip("|").split("|")]
        if len(cells) < 2 or cells[0] in {"Key", "Path"} \
                or set(cells[0]) <= {"-", ":"}:
            continue
        rows.append(cells)
    return rows


def check_readme_tables(errors: List[str]) -> None:
    text = README.read_text(encoding="utf-8")
    source_rows = _table_rows(text, "<!-- digest-table: source -->",
                              "<!-- digest-table: end -->")
    if not source_rows:
        errors.append("README source pin table is missing")
    else:
        expected = {f"source:{path}": digest
                    for path, digest in reference.SOURCE_PINS.items()}
        observed = {row[0]: row[1] for row in source_rows}
        if observed != expected:
            errors.append("README source pin table is stale")

    boundary_text = text.split("<!-- digest-table: boundary -->", 1)
    if len(boundary_text) != 2:
        errors.append("README boundary pin table is missing")
    else:
        boundary_rows = _table_rows(
            "<!-- digest-table: boundary -->" + boundary_text[1],
            "<!-- digest-table: boundary -->", "<!-- digest-table: end -->")
        expected_boundary = {path: digest
                             for path, digest in reference.BOUNDARY_PINS.items()}
        observed_boundary = {row[0]: row[1] for row in boundary_rows}
        if observed_boundary != expected_boundary:
            errors.append("README boundary pin table is stale")

    if "<!-- DIGEST_TABLE_ARTIFACTS_START -->" not in text:
        return
    artifact_rows = _table_rows(
        text, "<!-- DIGEST_TABLE_ARTIFACTS_START -->",
        "<!-- DIGEST_TABLE_ARTIFACTS_END -->")
    expected_artifacts = {
        name: (reference.file_digest(HERE / name),
               str((HERE / name).stat().st_size))
        for name in reference.PIN_FILES
        if name not in {"README.md", "SOURCES.sha256"}
    }
    observed_artifacts = {row[0]: (row[1], row[2]) for row in artifact_rows
                          if len(row) >= 3}
    if observed_artifacts != expected_artifacts:
        errors.append("README artifact digest table is stale")


def check_licensing(errors: List[str]) -> None:
    for path in sorted(HERE.glob("*.py")):
        head = "\n".join(path.read_text(encoding="utf-8").splitlines()[:4])
        if SPDX_LICENSE not in head or SPDX_COPYRIGHT not in head:
            errors.append("missing SPDX header: " + path.name)
    readme_head = "\n".join(README.read_text(encoding="utf-8").splitlines()[:4])
    if SPDX_LICENSE not in readme_head or SPDX_COPYRIGHT not in readme_head:
        errors.append("README.md is missing its SPDX header")
    for name in LICENSE_SIDECARS:
        path = HERE / name
        if not path.is_file():
            errors.append("missing license sidecar: " + name)
            continue
        content = path.read_text(encoding="utf-8")
        if SPDX_LICENSE not in content or SPDX_COPYRIGHT not in content:
            errors.append("invalid license sidecar: " + name)
    reuse = (SDK_ROOT / "REUSE.toml").read_text(encoding="utf-8")
    if '"docs/**"' not in reuse or ('SPDX' "-License-Identifier = \"Apache-2.0\"") not in reuse:
        errors.append("REUSE.toml no longer covers docs/** as Apache-2.0")


def check_scope(errors: List[str]) -> List[str]:
    result = subprocess.run(
        ["git", "-C", str(SDK_ROOT), "status", "--porcelain=v1",
         "--untracked-files=all"],
        capture_output=True, text=True, check=True)
    changed: List[str] = []
    for line in result.stdout.splitlines():
        raw = line[3:] if line[:2].strip() else line
        if " -> " in raw:
            raw = raw.split(" -> ", 1)[1]
        path = raw.strip()
        changed.append(path)
        if not path.startswith(reference.TASK_PREFIX):
            errors.append("change outside task scope: " + path)
    diff_check = subprocess.run(
        ["git", "-C", str(SDK_ROOT), "diff", "--check"],
        capture_output=True, text=True)
    if diff_check.returncode != 0:
        errors.append("git diff --check failed: " + diff_check.stdout.strip())
    return changed


def main() -> int:
    errors: List[str] = []
    loaded = check_json_files(errors)
    report = loaded.get("report", {})
    contract = loaded.get("contract", {})
    pin_count = check_pins(errors)
    if report:
        check_report(errors, report)
        check_source_pins(errors, report, contract)
        check_board(errors, report, contract)
    if contract:
        check_contract(errors, contract, report)
    check_repeats(errors, report)
    check_readme_tables(errors)
    check_licensing(errors)
    changed = check_scope(errors)
    if errors:
        for error in errors:
            print("FAIL: " + error)
        return 1
    print(f"pins_ok={pin_count} json_ok=2 report_sha256="
          f"{reference.file_digest(REPORT)} repeats_ok=3 "
          f"licensing_ok=1 scope_ok=1 changed_files={len(changed)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
