"""Regenerate the canonical granular-TSM report, sidecar and C parity header."""

from __future__ import annotations

import argparse
from pathlib import Path

import reference

TASK_DIR = Path(__file__).resolve().parent
REPORT_FILE = TASK_DIR / "report.json"
SIDECAR_FILE = TASK_DIR / "report.json.sha256"
HEADER_FILE = TASK_DIR / "provider" / "expected_vectors.h"


def header_text(expected: dict) -> str:
    counts = ", ".join(str(value) for value in expected["valid_counts"])
    lines = [
        "/* SPDX-FileCopyrightText: 2026 Tsakanyan Hovhannes",
        " * SPDX" "-License-Identifier: Apache-2.0",
        " */",
        "/* Generated by run.py from the deterministic Python model. Do not edit. */",
        "#ifndef GRANULAR_TSM_EXPECTED_VECTORS_H",
        "#define GRANULAR_TSM_EXPECTED_VECTORS_H",
        "",
        f'#define GRANULAR_EXPECTED_CONTENT_DIGEST "{expected["content_digest"]}"',
        f'#define GRANULAR_EXPECTED_CONTENT_SAMPLES {expected["content_samples"]}',
        f'#define GRANULAR_EXPECTED_FRAME_COUNT {expected["frames"]}',
        f'#define GRANULAR_EXPECTED_DRAIN_NON_CONTENT_SAMPLES {expected["drain_non_content_samples"]}',
        f'#define GRANULAR_EXPECTED_PROVIDER_SOURCE_DIGEST "{expected["provider_source_digest"]}"',
        f'#define GRANULAR_EXPECTED_CONFIG_DIGEST "{expected["config_digest"]}"',
        "",
        f"static const unsigned short kExpectedValidCounts[GRANULAR_EXPECTED_FRAME_COUNT] = {{{counts}}};",
        "",
        "#endif /* GRANULAR_TSM_EXPECTED_VECTORS_H */",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--report", action="store_true",
                        help="write report.json, report.json.sha256 and the C parity header")
    parser.add_argument("--install-location", default=None,
                        help="override the recorded absolute install location")
    options = parser.parse_args()

    report = reference.build_report(options.install_location)
    text, digest = reference.canonical_report(report)
    if options.report:
        REPORT_FILE.write_text(text + "\n", encoding="utf-8")
        SIDECAR_FILE.write_text(digest + "\n", encoding="ascii")
        HEADER_FILE.write_text(header_text(report["c_boundary_expected"]), encoding="utf-8")
    print(f"report_digest={digest}")
    print(f"report_file_digest={reference.sha256_bytes((text + chr(10)).encode('utf-8'))}")
    print(f"content_digest={report['c_boundary_expected']['content_digest']}")
    print(f"provider_source_digest={report['c_boundary_expected']['provider_source_digest']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
