"""Read-only strict verification for the FastEnhancer source-linked wrapper evidence.

Usage::

    PYTHONDONTWRITEBYTECODE=1 python3 verify.py

Checks canonical bytes, duplicate-key-free JSON, all pins, three byte-identical
cold-start regenerations, invalid-case rejection, licensing, source identity,
acceptance-profile structure, scope and ``git diff --check``. Never writes.
"""

from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path
from typing import Any, Dict, List

import reference
import scorer

HERE = Path(__file__).resolve().parent
REPORT = HERE / "report.json"
SIDECAR = HERE / "report.json.sha256"
PINS = HERE / "SOURCES.sha256"
CONTRACT = HERE / "contract.json"
ADAPTER = HERE / "adapter.json"
PROVIDER = HERE / "provider.json"
PRIOR_SCORER = reference.SDK_ROOT / "docs/task-evidence/online-multichannel-wpe/scorer.py"
LICENSE_SIDECARS = ("report.json.license", "report.json.sha256.license", "SOURCES.sha256.license")
LICENSE_TEXT = "SPDX-FileCopyrightText: 2026 Tsakanyan Hovhannes\nSPDX-License-Identifier: Apache-2.0\n"
REQUIRED_KEYS = {
    "schema_id", "task_id", "component_id", "reference_family", "base_commit", "profile",
    "status", "qualification_status", "decision", "evidence_status", "scope", "boundary",
    "format", "source_pins", "boundary_pins", "artifact_pins", "acceptance_profile",
    "conditions", "controls", "adverse", "repeatability", "regressions", "gates",
    "independent_timing_evidence", "rights_gap", "scorer", "missing_evidence",
    "negative_claims", "evidence_classes",
}


def _errors_to_text(errors: List[str]) -> str:
    return "\n".join("FAIL: " + error for error in errors)


def check_pins(errors: List[str]) -> int:
    try:
        text = PINS.read_text(encoding="utf-8")
    except OSError as error:
        errors.append("manifest unreadable: " + str(error))
        return 0
    try:
        pins = reference.parse_pin_lines(text)
    except ValueError as error:
        errors.append("strict pin rejection: " + str(error))
        return 0
    if PINS.read_bytes() != reference.sources_bytes():
        errors.append("SOURCES.sha256 is not deterministic generated bytes")
    for digest, raw in pins:
        path = reference.pin_path(raw)
        if not path.is_file():
            errors.append("pinned file missing: " + raw)
            continue
        if reference.sha256(path.read_bytes()) != digest:
            errors.append("pinned bytes changed: " + raw)
    return len(pins)


def check_json(errors: List[str]) -> Dict[str, Any]:
    reports: Dict[str, Any] = {}
    for name, path in (("report", REPORT), ("contract", CONTRACT),
                       ("adapter", ADAPTER), ("provider", PROVIDER)):
        try:
            reports[name] = reference.strict_json(path)
        except (OSError, ValueError) as error:
            errors.append(f"strict JSON failed for {name}: {error}")
            return {}
    report = reports["report"]
    if not REQUIRED_KEYS <= set(report):
        errors.append("report missing keys: " + ", ".join(sorted(REQUIRED_KEYS - set(report))))
        return report
    if REPORT.read_bytes() != reference.canonical_report_bytes(report):
        errors.append("report.json is not canonical byte output")
    expected_sidecar = reference.sha256(REPORT.read_bytes()) + "  report.json\n"
    if SIDECAR.read_text(encoding="utf-8") != expected_sidecar:
        errors.append("report.json.sha256 is stale")
    for name in ("adapter", "provider"):
        expected = reference.canonical_bytes(reports[name]) + b"\n"
        if (HERE / (name + ".json")).read_bytes() != expected:
            errors.append(name + ".json is not canonical byte output")
    return reports


def check_report_content(errors: List[str], report: Dict[str, Any],
                         contract: Dict[str, Any], adapter: Dict[str, Any],
                         provider: Dict[str, Any]) -> None:
    if report.get("base_commit") != reference.BASE_COMMIT:
        errors.append("base_commit mismatch")
    if report.get("profile") != reference.PROFILE or contract.get("verification_profile") != "enhancement":
        errors.append("enhancement acceptance profile not recorded")
    if report.get("status") != reference.STATUS or report.get("qualification_status") != reference.QUALIFICATION_STATUS:
        errors.append("status is not proposal-only/not_qualified")
    if report.get("decision") != reference.DECISION or contract.get("decision") != reference.DECISION:
        errors.append("decision is not DEFER")
    if report.get("evidence_status") != "incomplete" or report.get("defer_before") != "processor_exposure":
        errors.append("incomplete/DEFER disposition missing")
    boundary = report.get("boundary", {})
    for key in ("registered", "enabled_by_default", "default_selected", "public_api_abi_change",
                "provider_registration", "processor_exposure", "c_public_boundary"):
        if boundary.get(key) is not False:
            errors.append("boundary is not fail-closed: " + key)
    if boundary.get("descriptor_settings") != {}:
        errors.append("descriptor_settings is not empty")
    fmt = report.get("format", {})
    expected_format = {"sample_rate_hz": 16000, "channels": 1, "sample_format": "f32",
                       "frame_samples": 160, "hop_samples": 160, "content_delay_samples": 0}
    for key, value in expected_format.items():
        if fmt.get(key) != value:
            errors.append("v0 geometry mismatch: " + key)
    if report.get("reference_family") != reference.REFERENCE_FAMILY:
        errors.append("public reference family identity changed")
    if report.get("component_id") != reference.COMPONENT_ID:
        errors.append("component identity changed")
    if contract.get("source_identity", {}).get("sha256") != reference.SOURCE_PINS[
            "source:cpp-library/src/stages/fastenhancer.cpp"]:
        errors.append("pinned source identity mismatch")
    if adapter.get("source_sha256") != reference.SOURCE_PINS[
            "source:cpp-library/src/stages/fastenhancer.cpp"]:
        errors.append("adapter source identity mismatch")
    if adapter.get("registered") is not False or adapter.get("default_enabled") is not False:
        errors.append("adapter is not opt-in/unregistered/disabled")
    if provider.get("registered") is not False or provider.get("default_enabled") is not False:
        errors.append("provider is not opt-in/unregistered/disabled")
    if provider.get("descriptor_settings") != {} or provider.get("public_api_abi_changed") is not False:
        errors.append("provider claims a descriptor or ABI change")
    acceptance = report.get("acceptance_profile", {})
    if acceptance.get("profile") != "enhancement":
        errors.append("acceptance profile is not enhancement")
    mapped = acceptance.get("mapped_cases", {})
    for case in ("identity_noisy_control", "established_task_matched_baseline",
                 "paired_si_sdr_stoi", "clean_speech_preservation",
                 "peaks_and_invalid_outputs", "unpaired_speech",
                 "alignment_state_memory_timing"):
        if case not in mapped:
            errors.append("acceptance case missing: " + case)
    if not report.get("gates") or any(gate.get("status") != "blocked" for gate in report["gates"]):
        errors.append("a remaining gate is not blocked")
    if report.get("rights_gap", {}).get("blocked") is not True:
        errors.append("rights gap is not explicitly blocked")
    timing = report.get("independent_timing_evidence", {})
    if (timing.get("used_for_qualification") is not False
            or timing.get("measured_here") is not False
            or timing.get("target_device") is not False):
        errors.append("independent timing evidence is claimed as qualifying")
    negatives = report.get("negative_claims", {})
    if any(negatives.get(key) is not False for key in (
            "real_model_weights", "real_media", "device_timing", "listening_result",
            "benchmark_claim", "release_claim", "onnx_runtime_invoked")):
        errors.append("a prohibited claim is present")
    if report.get("repeatability", {}).get("byte_identical") is not True:
        errors.append("three reported repeats are not byte-identical")
    if report.get("scorer", {}).get("scorer_id") != scorer.SCORER_ID:
        errors.append("scorer identity mismatch")
    if report.get("scorer", {}).get("used_as_oracle") is not False:
        errors.append("scorer cross-check used as an oracle")


def check_all_pins(errors: List[str], report: Dict[str, Any], contract: Dict[str, Any]) -> None:
    if PINS.is_file():
        manifest = {raw: digest for digest, raw in
                    reference.parse_pin_lines(PINS.read_text(encoding="utf-8"))}
    else:
        manifest = {}
    report_pins = {**report.get("source_pins", {}), **report.get("boundary_pins", {}),
                   **report.get("artifact_pins", {})}
    for raw, digest in report_pins.items():
        path = reference.pin_path(raw)
        if not path.is_file() or reference.sha256(path.read_bytes()) != digest:
            errors.append("report pin stale: " + raw)
        if manifest.get(raw) != digest:
            errors.append("report pin missing from manifest: " + raw)
    for raw, digest in contract.get("source_pins", {}).items():
        expected = "source:" + raw
        if report.get("source_pins", {}).get(expected) != digest:
            errors.append("contract source pin differs from report: " + raw)
        if manifest.get(expected) != digest:
            errors.append("contract source pin missing from manifest: " + raw)
    for raw, digest in contract.get("boundary_pins", {}).items():
        if report.get("boundary_pins", {}).get(raw) != digest or manifest.get(raw) != digest:
            errors.append("contract boundary pin mismatch: " + raw)
    for raw, digest in contract.get("artifact_pins", {}).items():
        if report.get("artifact_pins", {}).get(raw) != digest or manifest.get(raw) != digest:
            errors.append("contract artifact pin mismatch: " + raw)
    if report.get("artifact_pins", {}) != reference.artifact_pins():
        errors.append("artifact pins are not recomputed from current files")
    if not PRIOR_SCORER.is_file():
        errors.append("prior pinned scorer is missing")
    else:
        prior = PRIOR_SCORER.read_text(encoding="utf-8")
        expected = prior.replace(
            'SCORER_ID = "audio-sdk/online-multichannel-wpe-scoring/0.1"',
            f'SCORER_ID = "{scorer.SCORER_ID}"')
        if (HERE / "scorer.py").read_text(encoding="utf-8") != expected:
            errors.append("scorer is not byte-identical to the pinned algorithm apart from SCORER_ID")


def check_invalid_cases(errors: List[str]) -> None:
    for bad in ("not-a-line", "Z" * 64 + "  docs/x", "a" * 64 + "  ../escape",
                "a" * 64 + "  unknown/x"):
        try:
            reference.parse_pin_lines(bad)
            errors.append("invalid pin line accepted: " + repr(bad))
        except ValueError:
            pass
    duplicate = "\n".join([f"{'a' * 64}  docs/x", f"{'a' * 64}  docs/x"])
    try:
        reference.parse_pin_lines(duplicate)
        errors.append("duplicate pin accepted")
    except ValueError:
        pass
    adverse = reference.adverse()
    for name, value in adverse["config_rejections"].items():
        if not value["status"].startswith("rejected") or value["controller_created"]:
            errors.append("config rejection failed closed: " + name)
    for name, status in adverse["frame_rejections"].items():
        if name != "dsp_state_unchanged" and not status.startswith("rejected"):
            errors.append("frame rejection failed closed: " + name)
    if adverse["frame_rejections"]["dsp_state_unchanged"] is not True:
        errors.append("invalid frame advanced DSP state")


def check_reproduction(errors: List[str]) -> str:
    code = (
        "import sys; sys.path.insert(0, " + repr(str(HERE)) + "); "
        "import reference; sys.stdout.write(reference.sha256("
        "reference.canonical_report_bytes(reference.build_report())))"
    )
    env = dict(os.environ, PYTHONDONTWRITEBYTECODE="1")
    digests = []
    for _ in range(3):
        result = subprocess.run([sys.executable, "-c", code], cwd=HERE, env=env,
                                capture_output=True, text=True, check=False)
        if result.returncode != 0:
            errors.append("cold-start regeneration failed: " + result.stderr.strip())
            return ""
        digests.append(result.stdout.strip())
    if len(set(digests)) != 1:
        errors.append("three cold-start regenerations are not byte-identical")
    actual = reference.sha256(REPORT.read_bytes())
    if digests and digests[0] != actual:
        errors.append("cold-start digest differs from report.json")
    return actual


def check_licensing(errors: List[str]) -> None:
    for path in sorted(HERE.glob("*.py")):
        head = "\n".join(path.read_text(encoding="utf-8").splitlines()[:4])
        if reference.SPDX_LICENSE_LINE not in head or reference.SPDX_COPYRIGHT_LINE not in head:
            errors.append("missing SPDX header: " + path.name)
    readme = (HERE / "README.md").read_text(encoding="utf-8")
    if (f"<!-- {reference.SPDX_COPYRIGHT_LINE} -->" not in readme
            or f"<!-- {reference.SPDX_LICENSE_LINE} -->" not in readme):
        errors.append("README.md lacks SPDX provenance")
    for name in LICENSE_SIDECARS:
        if (HERE / name).read_text(encoding="utf-8") != LICENSE_TEXT:
            errors.append("license sidecar content mismatch: " + name)
    reuse = (reference.SDK_ROOT / "REUSE.toml").read_text(encoding="utf-8")
    if '"docs/**"' not in reuse or 'SPDX-License-Identifier = "Apache-2.0"' not in reuse:
        errors.append("REUSE.toml no longer covers docs/** as Apache-2.0")


def check_scope(errors: List[str]) -> int:
    result = subprocess.run(
        ["git", "-C", str(reference.SDK_ROOT), "status", "--porcelain=v1", "--untracked-files=all"],
        capture_output=True, text=True, check=True)
    changed = []
    for line in result.stdout.splitlines():
        path = line[3:] if len(line) > 3 else line
        if " -> " in path:
            path = path.split(" -> ", 1)[1]
        changed.append(path)
        if path and not path.startswith(reference.TASK_REL + "/"):
            errors.append("change outside task scope: " + path)
    diff_check = subprocess.run(["git", "-C", str(reference.SDK_ROOT), "diff", "--check"],
                                capture_output=True, text=True, check=False)
    if diff_check.returncode != 0:
        errors.append("git diff --check failed: " + diff_check.stdout.strip())
    return len(changed)


def main() -> int:
    errors: List[str] = []
    pins = check_pins(errors)
    payloads = check_json(errors)
    if payloads:
        check_report_content(errors, payloads["report"], payloads["contract"],
                             payloads["adapter"], payloads["provider"])
        check_all_pins(errors, payloads["report"], payloads["contract"])
    else:
        check_report_content(errors, {}, {}, {}, {})
    check_invalid_cases(errors)
    digest = check_reproduction(errors)
    check_licensing(errors)
    changed = check_scope(errors)
    if errors:
        print(_errors_to_text(errors))
        print(f"pins_ok={bool(pins)} reproduction_ok={bool(digest)} report_sha256={digest}")
        return 1
    print(f"pins_ok={pins} json_ok=4 strict_reproduction_ok=3 invalid_cases_ok=1 "
          f"licensing_ok=1 scope_ok=1 changed_files={changed} report_sha256={digest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
