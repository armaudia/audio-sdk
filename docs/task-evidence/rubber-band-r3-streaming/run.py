"""Regenerate the canonical report, sidecar, source manifest and C vectors."""

from __future__ import annotations

import argparse
from pathlib import Path

import fixture
import reference
import scorer

TASK_DIR = Path(__file__).resolve().parent
REPORT_FILE = TASK_DIR / "report.json"
SIDECAR_FILE = TASK_DIR / "report.json.sha256"
SOURCES_FILE = TASK_DIR / "SOURCES.sha256"
HEADER_FILE = TASK_DIR / "provider" / "expected_vectors.h"


def header_text(expected: dict) -> str:
    """Render the byte-exact C parity header from the Python model."""
    counts = ", ".join(str(value) for value in expected["valid_counts"])
    lines = [
        "/* SPDX-FileCopyrightText: 2026 Tsakanyan Hovhannes",
        " * SPDX" "-License-Identifier: Apache-2.0",
        " */",
        "/* Generated by run.py from the deterministic Python model. Do not edit. */",
        "#ifndef RUBBER_BAND_R3_STREAMING_EXPECTED_VECTORS_H",
        "#define RUBBER_BAND_R3_STREAMING_EXPECTED_VECTORS_H",
        "",
        f'#define RB3_EXPECTED_CONTENT_DIGEST "{expected["content_digest"]}"',
        f'#define RB3_EXPECTED_CONTENT_SAMPLES {expected["content_samples"]}',
        f'#define RB3_EXPECTED_FRAME_COUNT {expected["frames"]}',
        f'#define RB3_EXPECTED_FIRST_OUTPUT_FRAME {expected["first_output_frame"]}',
        f'#define RB3_EXPECTED_PROVIDER_SOURCE_DIGEST "{expected["provider_source_digest"]}"',
        f'#define RB3_EXPECTED_CONFIG_DIGEST "{expected["config_digest"]}"',
        "",
        f"static const unsigned short kExpectedValidCounts[RB3_EXPECTED_FRAME_COUNT] = {{{counts}}};",
        "",
        "#endif /* RUBBER_BAND_R3_STREAMING_EXPECTED_VECTORS_H */",
        "",
    ]
    return "\n".join(lines)


def write_report() -> tuple[dict, str]:
    report = scorer.build_report()
    text, digest = reference.canonical_report(report)
    REPORT_FILE.write_text(text + "\n", encoding="utf-8")
    SIDECAR_FILE.write_text(digest + "\n", encoding="ascii")
    HEADER_FILE.parent.mkdir(parents=True, exist_ok=True)
    HEADER_FILE.write_text(header_text(report["c_boundary_expected"]),
                           encoding="utf-8")
    return report, digest


def write_sources() -> str:
    document = fixture.sources_document()
    lines = [f"{digest}  {relative}"
             for relative, digest in sorted(document["task_local_files"].items())]
    text = "\n".join(lines) + "\n"
    SOURCES_FILE.write_text(text, encoding="ascii")
    return reference.sha256_bytes(text.encode("ascii"))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--report", action="store_true",
                        help="write report.json, report.json.sha256 and the C parity header")
    parser.add_argument("--sources", action="store_true",
                        help="write SOURCES.sha256 from the current task-local tree")
    options = parser.parse_args()
    do_report = options.report or not (options.report or options.sources)
    do_sources = options.sources or not (options.report or options.sources)

    digest = None
    report = None
    if do_report:
        report, digest = write_report()
    else:
        digest = SIDECAR_FILE.read_text(encoding="ascii").strip()

    sources_digest = None
    if do_sources:
        sources_digest = write_sources()

    content_digest = (report["c_boundary_expected"]["content_digest"]
                      if report else
                      fixture.strict_load(REPORT_FILE)["c_boundary_expected"][
                          "content_digest"])
    manifest_digest = sources_digest
    if manifest_digest is None and SOURCES_FILE.is_file():
        manifest_digest = reference.sha256_file(SOURCES_FILE)
    print(f"report_digest={digest}")
    print(f"report_file_digest={reference.sha256_file(REPORT_FILE)}")
    print(f"sources_manifest_digest={manifest_digest or 'not_generated'}")
    print(f"content_digest={content_digest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
