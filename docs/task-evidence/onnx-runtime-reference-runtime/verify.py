"""Read-only strict verification for the ONNX Runtime reference-runtime evidence.

Usage::

    PYTHONDONTWRITEBYTECODE=1 python3 verify.py

Checks canonical bytes, duplicate-key-free JSON, all pins, source/model identity,
three byte-identical cold-start regenerations, every documented rejection,
licensing, scope and ``git diff --check``. Never writes.
"""

from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path
from typing import Any, Dict, List

import reference

HERE = Path(__file__).resolve().parent
REPORT = HERE / "report.json"
SIDECAR = HERE / "report.json.sha256"
PINS = HERE / "SOURCES.sha256"
CONTRACT = HERE / "contract.json"
ADAPTER = HERE / "adapter.json"
PROVIDER = HERE / "provider.json"
MODEL = HERE / "synthetic_model.json"
LICENSE_SIDECARS = (
    "contract.json.license",
    "adapter.json.license",
    "provider.json.license",
    "synthetic_model.json.license",
    "report.json.license",
    "report.json.sha256.license",
    "SOURCES.sha256.license",
)
LICENSE_TEXT = (reference.SPDX_COPYRIGHT_LINE + "\n"
                + reference.SPDX_LICENSE_LINE + "\n")
REQUIRED_KEYS = {
    "schema_id", "task_id", "component_id", "reference_family", "base_commit", "profile",
    "status", "qualification_status", "decision", "evidence_status", "scope", "boundary",
    "format", "adapter_contract", "model_asset", "runtime_readiness", "conditions",
    "tool_profile", "boundary_checks", "adverse", "repeatability", "gates", "rights_gap",
    "negative_claims", "source_pins", "boundary_pins", "artifact_pins", "missing_evidence",
    "evidence_classes", "invariants",
}


def _errors_to_text(errors: List[str]) -> str:
    return "\n".join("FAIL: " + error for error in errors)


def check_pins(errors: List[str]) -> int:
    try:
        text = PINS.read_text(encoding="utf-8")
    except OSError as error:
        errors.append("manifest unreadable: " + str(error))
        return 0
    try:
        pins = reference.parse_pin_lines(text)
    except ValueError as error:
        errors.append("strict pin rejection: " + str(error))
        return 0
    if PINS.read_bytes() != reference.sources_bytes():
        errors.append("SOURCES.sha256 is not deterministic generated bytes")
    for digest, raw in pins:
        path = reference.pin_path(raw)
        if not path.is_file():
            errors.append("pinned file missing: " + raw)
            continue
        if reference.sha256(path.read_bytes()) != digest:
            errors.append("pinned bytes changed: " + raw)
    return len(pins)


def check_json(errors: List[str]) -> Dict[str, Any]:
    reports: Dict[str, Any] = {}
    for name, path in (("report", REPORT), ("contract", CONTRACT),
                       ("adapter", ADAPTER), ("provider", PROVIDER),
                       ("model", MODEL)):
        try:
            reports[name] = reference.strict_json_file(path)
        except (OSError, ValueError) as error:
            errors.append(f"strict JSON failed for {name}: {error}")
            return {}
    report = reports["report"]
    if not REQUIRED_KEYS <= set(report):
        errors.append("report missing keys: " + ", ".join(sorted(REQUIRED_KEYS - set(report))))
        return report
    if REPORT.read_bytes() != reference.canonical_report_bytes(report):
        errors.append("report.json is not canonical byte output")
    expected_sidecar = reference.sha256(REPORT.read_bytes()) + "  report.json\n"
    if SIDECAR.read_text(encoding="utf-8") != expected_sidecar:
        errors.append("report.json.sha256 is stale")
    if ADAPTER.read_bytes() != reference.canonical_bytes(reports["adapter"]) + b"\n":
        errors.append("adapter.json is not canonical byte output")
    if PROVIDER.read_bytes() != reference.canonical_bytes(reports["provider"]) + b"\n":
        errors.append("provider.json is not canonical byte output")
    if MODEL.read_bytes() != reference.model_bytes():
        errors.append("synthetic_model.json is not the deterministic fixture bytes")
    if CONTRACT.read_bytes() != reference.contract_bytes():
        errors.append("contract.json is not the deterministic contract bytes")
    return reports


def check_report_content(errors: List[str], report: Dict[str, Any],
                         contract: Dict[str, Any], adapter: Dict[str, Any],
                         provider: Dict[str, Any], model: Dict[str, Any]) -> None:
    if report.get("base_commit") != reference.BASE_COMMIT:
        errors.append("base_commit mismatch")
    if report.get("profile") != "tool" or contract.get("verification_profile") != "tool":
        errors.append("tool acceptance profile not recorded")
    if report.get("status") != reference.STATUS:
        errors.append("status is not synthetic_boundary_incomplete")
    if report.get("qualification_status") != reference.QUALIFICATION_STATUS:
        errors.append("qualification_status is not not_qualified")
    if report.get("decision") != reference.DECISION or contract.get("decision") != reference.DECISION:
        errors.append("decision is not DEFER")
    if report.get("evidence_status") != "incomplete":
        errors.append("evidence_status is not incomplete")
    if report.get("defer_before") != reference.DEFER_BEFORE:
        errors.append("defer_before is not runtime_integration")
    boundary = report.get("boundary", {})
    for key in ("registered", "enabled_by_default", "default_selected",
                "public_api_abi_change", "provider_registration", "processor_exposure",
                "c_public_boundary"):
        if boundary.get(key) is not False:
            errors.append("boundary is not fail-closed: " + key)
    if boundary.get("descriptor_settings") != {}:
        errors.append("descriptor_settings is not empty")
    fmt = report.get("format", {})
    expected_format = {"sample_rate_hz": 16000, "channels": 1, "sample_format": "f32",
                       "frame_samples": 160, "hop_samples": 160,
                       "content_delay_samples": 0}
    for key, value in expected_format.items():
        if fmt.get(key) != value:
            errors.append("v0 geometry mismatch: " + key)
    adapter_contract = report.get("adapter_contract", {})
    if adapter_contract.get("runtime_id") != reference.RUNTIME_ID:
        errors.append("runtime id changed")
    if adapter_contract.get("tensors") != reference.TENSORS:
        errors.append("tensor geometry changed")
    if model != reference.MODEL_SPEC:
        errors.append("synthetic model document changed")
    asset = report.get("model_asset", {})
    if asset.get("sha256") != reference.model_digest():
        errors.append("model digest mismatch")
    if asset.get("byte_count") != len(reference.model_bytes()):
        errors.append("model byte count mismatch")
    if asset.get("real_onnx_graph") is not False or asset.get("real_model_weights") is not False:
        errors.append("model asset claims a real graph or weights")
    if asset.get("storage") != "external_caller_supplied":
        errors.append("model asset is not caller-supplied")
    readiness = report.get("runtime_readiness", {})
    if readiness.get("blocked") is not True:
        errors.append("runtime readiness is not blocked")
    if readiness.get("module_spec_found") is not False or readiness.get("importable") is not False:
        errors.append("a runtime module is unexpectedly available")
    if readiness.get("exact_error") != "ModuleNotFoundError: No module named 'onnxruntime'":
        errors.append("runtime exact error changed")
    if readiness.get("interpreter") != "3.12.16":
        errors.append("runtime probe did not use pinned CPython 3.12.16")
    if readiness.get("sdk_runtime_pin_present") is not False:
        errors.append("an SDK runtime pin is unexpectedly present")
    if readiness.get("candidate_used") is not False:
        errors.append("the unpinned candidate runtime is used")
    if len(readiness.get("reopen_conditions", [])) < 4:
        errors.append("runtime reopen conditions are incomplete")
    conditions = report.get("conditions", {})
    for name in ("impulse", "constant_one", "constant_negative_one", "silence",
                 "lcg_three_frames", "explicit_state_and_bindings"):
        if name not in conditions:
            errors.append("synthetic condition missing: " + name)
    for name in ("impulse", "constant_one", "constant_negative_one", "silence"):
        checks = conditions.get(name, {}).get("exact_checks", {})
        if not checks or not all(value is True for value in checks.values()):
            errors.append("golden exact check failed: " + name)
    if conditions.get("explicit_state_and_bindings", {}).get("binding_path_matches") is not True:
        errors.append("I/O binding path differs from unbound path")
    if conditions.get("lcg_three_frames", {}).get("reset_replay_matches") is not True:
        errors.append("reset replay differs")
    if conditions.get("lcg_three_frames", {}).get("reset_state_zero") is not True:
        errors.append("reset state is not zero")
    if conditions != reference.measure_conditions():
        errors.append("reported conditions differ from a fresh execution")
    probe = report.get("boundary_checks", {}).get("typical_api_use", {})
    expected_probe = reference.typical_probe()
    if probe != expected_probe:
        errors.append("typical probe differs from a fresh execution")
    if probe.get("sequence") != list(reference.TYPICAL_PROBE_SEQUENCE):
        errors.append("typical probe sequence is incomplete")
    if probe.get("capability", {}).get("called") is not True:
        errors.append("capability() was not called in the typical probe")
    if probe.get("reset", {}).get("called") is not True:
        errors.append("reset() was not called in the typical probe")
    if probe.get("run_after_reset", {}).get("replay_matches_first_frame") is not True:
        errors.append("run after reset does not replay the first frame")
    if probe.get("close", {}).get("run_after_close_rejected") is not True:
        errors.append("run after close was not rejected in the typical probe")
    if probe.get("create_capability_run_reset_close") is not True:
        errors.append("create-capability-run-reset-close was not exercised")
    if probe.get("all_steps_passed") is not True:
        errors.append("typical probe did not pass every step")
    adverse = report.get("adverse", {})
    expected_groups = {
        "model_rejections": 18,
        "config_rejections": 8,
        "feed_rejections": 9,
        "binding_rejections": 6,
        "rights_rejections": 3,
        "runtime_rejections": 2,
    }
    counts = adverse.get("counts", {})
    if counts.get("rejection_groups") != expected_groups:
        errors.append("rejection group counts do not match the enumerated cases")
    for group, expected in expected_groups.items():
        if len(adverse.get(group, {})) != expected:
            errors.append(f"enumerated {group} length is not {expected}")
    if counts.get("rejection_cases") != sum(expected_groups.values()):
        errors.append("rejection_cases total is not 46")
    if counts.get("lifecycle_checks") != 5:
        errors.append("lifecycle_checks is not 5")
    if counts.get("lifecycle_rejected") != 3 or counts.get("lifecycle_accepted") != 2:
        errors.append("lifecycle accepted/rejected counts are not 3/2")
    if counts.get("total_checks") != 51:
        errors.append("total_checks is not 51")
    if counts.get("failed_open") != 0:
        errors.append("a documented rejection failed open")
    if counts.get("all_rejections_closed") is not True:
        errors.append("adverse cases are not all rejected")
    if adverse != reference.adverse():
        errors.append("reported adverse matrix differs from a fresh execution")
    malformed = report.get("boundary_checks", {}).get("malformed_inputs", {})
    if malformed.get("cases") != 46 or malformed.get("rejection_cases") != 46:
        errors.append("malformed_inputs case total is not 46")
    if malformed.get("lifecycle_checks") != 5 or malformed.get("total_checks") != 51:
        errors.append("malformed_inputs lifecycle/total counts are not 5/51")
    if adverse.get("state", {}).get("unchanged_by_feed_rejections") is not True:
        errors.append("feed rejection advanced state")
    if adverse.get("state", {}).get("unchanged_by_binding_rejections") is not True:
        errors.append("binding rejection advanced state")
    readme = (HERE / "README.md").read_text(encoding="utf-8")
    for line in (
            "model_rejections=18",
            "config_rejections=8",
            "feed_rejections=9",
            "binding_rejections=6",
            "rights_rejections=3",
            "runtime_rejections=2",
            "rejection_cases=46",
            "lifecycle_checks=5 (3 rejected, 2 accepted)",
            "total_checks=51"):
        if line not in readme:
            errors.append("README case count disagrees: " + line)
    profile = report.get("tool_profile", {})
    mapped = profile.get("mapped_cases", {})
    expected_status = {
        "version_install_and_provenance": "blocked",
        "clean_checkout_or_extracted_package": "not_run",
        "typical_cli_or_api_use": "passed_synthetic",
        "caller_owned_inputs": "passed_synthetic",
        "malformed_inputs": "passed_synthetic",
        "missing_optional_selection": "passed_synthetic",
        "compile_and_build_evidence": "not_run",
        "synthetic_runtime_evidence": "passed_synthetic",
        "measured_workload_support": "not_reported",
    }
    for case, status in expected_status.items():
        if mapped.get(case, {}).get("status") != status:
            errors.append("tool profile case mismatch: " + case)
    for gate in report.get("gates", []):
        if gate.get("status") != "blocked" or not gate.get("reopen"):
            errors.append("a remaining gate is not blocked: " + str(gate.get("id")))
    if not report.get("gates"):
        errors.append("no remaining gates recorded")
    if report.get("rights_gap", {}).get("blocked") is not True:
        errors.append("rights gap is not explicitly blocked")
    for key, value in report.get("negative_claims", {}).items():
        if value is not False:
            errors.append("a prohibited claim is present: " + key)
    if report.get("repeatability", {}).get("byte_identical") is not True:
        errors.append("three reported repeats are not byte-identical")
    if report.get("repeatability", {}).get("count") != 3:
        errors.append("repeat count is not three")
    if report.get("artifact_pins") != reference.artifact_pins():
        errors.append("artifact pins are not recomputed from current files")
    if adapter.get("registered") is not False or adapter.get("default_enabled") is not False:
        errors.append("adapter is not opt-in/unregistered/disabled")
    if adapter.get("runtime_invoked") is not False:
        errors.append("adapter claims runtime invocation")
    if provider.get("registered") is not False or provider.get("default_enabled") is not False:
        errors.append("provider is not opt-in/unregistered/disabled")
    if provider.get("descriptor_settings") != {} or provider.get("public_api_abi_changed") is not False:
        errors.append("provider claims a descriptor or ABI change")
    if provider.get("vendor_runtime_invoked") is not False:
        errors.append("provider claims vendor runtime invocation")
    if contract.get("model_fixture", {}).get("real_onnx_graph") is not False:
        errors.append("contract model fixture claims a real graph")
    if contract.get("rights_gap", {}).get("blocked") is not True:
        errors.append("contract rights gap is not blocked")
    if report.get("no_missing_result_qualifies_candidate") is not True:
        errors.append("missing-result qualification guard missing")


def check_all_pins(errors: List[str], report: Dict[str, Any], contract: Dict[str, Any]) -> None:
    try:
        manifest = {raw: digest for digest, raw in
                    reference.parse_pin_lines(PINS.read_text(encoding="utf-8"))}
    except (OSError, ValueError) as error:
        errors.append("manifest unreadable for pin comparison: " + str(error))
        return
    report_pins = {**report.get("source_pins", {}), **report.get("boundary_pins", {}),
                   **report.get("artifact_pins", {})}
    for raw, digest in report_pins.items():
        path = reference.pin_path(raw)
        if not path.is_file() or reference.sha256(path.read_bytes()) != digest:
            errors.append("report pin stale: " + raw)
        if manifest.get(raw) != digest:
            errors.append("report pin missing from manifest: " + raw)
    for raw, digest in reference.SOURCE_PINS.items():
        if report.get("source_pins", {}).get(raw) != digest or manifest.get(raw) != digest:
            errors.append("source pin mismatch: " + raw)
    for raw, digest in reference.BOUNDARY_PINS.items():
        if report.get("boundary_pins", {}).get(raw) != digest or manifest.get(raw) != digest:
            errors.append("boundary pin mismatch: " + raw)


def check_invalid_cases(errors: List[str]) -> None:
    for bad in ("not-a-line", "Z" * 64 + "  docs/x", "a" * 64 + "  ../escape",
                "a" * 64 + "  unknown/x"):
        try:
            reference.parse_pin_lines(bad)
            errors.append("invalid pin line accepted: " + repr(bad))
        except ValueError:
            pass
    duplicate = "\n".join([f"{'a' * 64}  docs/x", f"{'a' * 64}  docs/x"])
    try:
        reference.parse_pin_lines(duplicate)
        errors.append("duplicate pin accepted")
    except ValueError:
        pass
    adverse = reference.adverse()
    if (adverse["counts"]["failed_open"] != 0
            or not adverse["counts"]["all_rejections_closed"]):
        errors.append("adverse boundary cases are not fail-closed")
    for name, value in adverse["feed_rejections"].items():
        if not value["state_unchanged"]:
            errors.append("feed rejection advanced state: " + name)
    for name, value in adverse["binding_rejections"].items():
        if value["code"] == "accepted":
            errors.append("binding rejection accepted: " + name)
    if adverse["lifecycle"]["run_after_close"]["code"] != "closed":
        errors.append("run after close was not rejected")
    if adverse["lifecycle"]["valid_reset"]["code"] != "accepted":
        errors.append("valid reset was rejected")
    if not adverse["state"]["unchanged_by_feed_rejections"]:
        errors.append("feed rejection changed adapter state")


def check_reproduction(errors: List[str]) -> str:
    code = (
        "import sys; sys.path.insert(0, " + repr(str(HERE)) + "); "
        "import reference; sys.stdout.write(reference.sha256("
        "reference.canonical_report_bytes(reference.build_report())))"
    )
    env = dict(os.environ, PYTHONDONTWRITEBYTECODE="1")
    digests = []
    for _ in range(3):
        result = subprocess.run([sys.executable, "-c", code], cwd=HERE, env=env,
                                capture_output=True, text=True, check=False)
        if result.returncode != 0:
            errors.append("cold-start regeneration failed: " + result.stderr.strip())
            return ""
        digests.append(result.stdout.strip())
    if len(set(digests)) != 1:
        errors.append("three cold-start regenerations are not byte-identical")
    actual = reference.sha256(REPORT.read_bytes())
    if digests and digests[0] != actual:
        errors.append("cold-start digest differs from report.json")
    return actual


def check_licensing(errors: List[str]) -> None:
    for path in sorted(HERE.glob("*.py")):
        head = "\n".join(path.read_text(encoding="utf-8").splitlines()[:4])
        if reference.SPDX_LICENSE_LINE not in head or reference.SPDX_COPYRIGHT_LINE not in head:
            errors.append("missing SPDX header: " + path.name)
    readme = (HERE / "README.md").read_text(encoding="utf-8")
    if (f"<!-- {reference.SPDX_COPYRIGHT_LINE} -->" not in readme
            or f"<!-- {reference.SPDX_LICENSE_LINE} -->" not in readme):
        errors.append("README.md lacks SPDX provenance")
    for name in LICENSE_SIDECARS:
        path = HERE / name
        if not path.is_file() or path.read_text(encoding="utf-8") != LICENSE_TEXT:
            errors.append("license sidecar content mismatch: " + name)
    reuse = (reference.SDK_ROOT / "REUSE.toml").read_text(encoding="utf-8")
    if '"docs/**"' not in reuse or 'SPDX-License-Identifier = "Apache-2.0"' not in reuse:
        errors.append("REUSE.toml no longer covers docs/** as Apache-2.0")


def check_scope(errors: List[str]) -> int:
    result = subprocess.run(
        ["git", "-C", str(reference.SDK_ROOT), "status", "--porcelain=v1",
         "--untracked-files=all"],
        capture_output=True, text=True, check=True)
    changed = []
    for line in result.stdout.splitlines():
        path = line[3:] if len(line) > 3 else line
        if " -> " in path:
            path = path.split(" -> ", 1)[1]
        changed.append(path)
        if path and not path.startswith(reference.TASK_REL + "/"):
            errors.append("change outside task scope: " + path)
    diff_check = subprocess.run(["git", "-C", str(reference.SDK_ROOT), "diff", "--check"],
                                capture_output=True, text=True, check=False)
    if diff_check.returncode != 0:
        errors.append("git diff --check failed: " + diff_check.stdout.strip())
    return len(changed)


def main() -> int:
    errors: List[str] = []
    pins = check_pins(errors)
    payloads = check_json(errors)
    if payloads:
        check_report_content(errors, payloads["report"], payloads["contract"],
                             payloads["adapter"], payloads["provider"],
                             payloads["model"])
        check_all_pins(errors, payloads["report"], payloads["contract"])
    else:
        check_report_content(errors, {}, {}, {}, {}, {})
    check_invalid_cases(errors)
    digest = check_reproduction(errors)
    check_licensing(errors)
    changed = check_scope(errors)
    if errors:
        print(_errors_to_text(errors))
        print(f"pins_ok={bool(pins)} reproduction_ok={bool(digest)} report_sha256={digest}")
        return 1
    print(f"pins_ok={pins} json_ok=5 strict_reproduction_ok=3 invalid_cases_ok=1 "
          f"licensing_ok=1 scope_ok=1 changed_files={changed} report_sha256={digest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
