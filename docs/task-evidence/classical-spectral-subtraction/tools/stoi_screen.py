#!/usr/bin/env python3
"""Pinned synthetic-scoped STOI-style scorer.

This is a deterministic, dependency-free envelope-correlation screen at the
native 16 kHz rate. It is NOT a certified pystoi implementation and is not
comparable with historical pilot STOI numbers: standard STOI resamples to
10 kHz and uses 15 1/3-octave bands and a specific chunking rule. The scope
here is only paired synthetic fixtures with clean references generated by
tools/generate_fixtures.py.
"""
from __future__ import annotations

import math

RATE = 16000
FRAME = 256
HOP = 160
CENTERS_HZ = (150.0, 212.0, 300.0, 425.0, 600.0, 850.0,
              1200.0, 1700.0, 2400.0, 3400.0, 4800.0, 6800.0)
BANDS = len(CENTERS_HZ)
BINS = FRAME // 2 + 1
CLIP_RELATIVE = 0.01

_TWIDDLE = [(math.cos(-2.0 * math.pi * k / FRAME),
             math.sin(-2.0 * math.pi * k / FRAME)) for k in range(FRAME // 2)]
_WINDOW = [0.5 - 0.5 * math.cos(2.0 * math.pi * n / FRAME) for n in range(FRAME)]


def _fft(real: list[float], imag: list[float]) -> None:
    j = 0
    for i in range(1, FRAME):
        bit = FRAME >> 1
        while j & bit:
            j ^= bit
            bit >>= 1
        j ^= bit
        if i < j:
            real[i], real[j] = real[j], real[i]
            imag[i], imag[j] = imag[j], imag[i]
    length = 2
    while length <= FRAME:
        half = length >> 1
        step = FRAME // length
        for base in range(0, FRAME, length):
            for k in range(half):
                wr, wi = _TWIDDLE[k * step]
                a = base + k
                b = a + half
                tr = wr * real[b] - wi * imag[b]
                ti = wr * imag[b] + wi * real[b]
                real[b] = real[a] - tr
                imag[b] = imag[a] - ti
                real[a] += tr
                imag[a] += ti
        length <<= 1


def _band_weights() -> list[list[float]]:
    weights = []
    for center in CENTERS_HZ:
        lower = center * 2.0 ** (-1.0 / 6.0)
        upper = center * 2.0 ** (1.0 / 6.0)
        row = []
        for k in range(BINS):
            frequency = k * RATE / FRAME
            if lower <= frequency <= upper:
                row.append(1.0)
            elif lower / 2.0 <= frequency < lower or upper < frequency <= upper * 2.0:
                row.append(0.5)
            else:
                row.append(0.0)
        weights.append(row)
    return weights


_BAND_WEIGHTS = _band_weights()


def _envelopes(samples: list[float]) -> list[list[float]]:
    result = []
    for start in range(0, len(samples) - FRAME + 1, HOP):
        real = [samples[start + n] * _WINDOW[n] for n in range(FRAME)]
        imag = [0.0] * FRAME
        _fft(real, imag)
        power = [real[k] * real[k] + imag[k] * imag[k] for k in range(BINS)]
        frame_envelope = [
            math.sqrt(sum(power[k] * _BAND_WEIGHTS[b][k] for k in range(BINS)))
            for b in range(BANDS)
        ]
        norm = math.sqrt(sum(value * value for value in frame_envelope))
        if norm > 0.0:
            frame_envelope = [value / norm for value in frame_envelope]
        result.append(frame_envelope)
    return result


def _correlation(left: list[float], right: list[float]) -> float:
    count = len(left)
    if count < 2:
        return 0.0
    mean_l = sum(left) / count
    mean_r = sum(right) / count
    cov = sum((left[i] - mean_l) * (right[i] - mean_r) for i in range(count))
    var_l = sum((value - mean_l) ** 2 for value in left)
    var_r = sum((value - mean_r) ** 2 for value in right)
    if var_l <= 0.0 or var_r <= 0.0:
        return 0.0
    return cov / math.sqrt(var_l * var_r)


def stoi_screen(reference: list[float], degraded: list[float]) -> float:
    if len(reference) != len(degraded):
        raise ValueError("reference and degraded lengths differ")
    clean = _envelopes(reference)
    test = _envelopes(degraded)
    if len(clean) != len(test) or not clean:
        raise ValueError("no complete frames to score")
    coefficients = []
    for band in range(BANDS):
        clean_values = [frame[band] for frame in clean]
        test_values = [min(test[i][band], (1.0 + CLIP_RELATIVE) * clean[i][band])
                       for i in range(len(clean))]
        coefficients.append(_correlation(clean_values, test_values))
    score = sum(coefficients) / BANDS
    return max(0.0, min(1.0, score))
