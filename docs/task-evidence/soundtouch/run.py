"""Regenerate the task-local report, digest sidecars, C header and crosscheck.

Every generated artifact is deterministic and byte-repeatable. Nothing here
registers a provider, changes installed behavior or qualifies a candidate.
"""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import sys
from typing import Any, Dict, List

import fixture
import reference
import scorer

ROOT = Path(__file__).resolve().parent
REPORT_PATH = ROOT / "report.json"
REPORT_DIGEST_PATH = ROOT / "report.json.sha256"
SOURCES_PATH = ROOT / "SOURCES.sha256"
HEADER_PATH = ROOT / "provider" / "expected_vectors.h"
CROSSCHECK_PATH = ROOT / "crosscheck.json"
CROSSCHECK_DIGEST_PATH = ROOT / "crosscheck.json.sha256"
CONSUMER_RESULT_PATH = ROOT / "provider" / "consumer_result.json"


def sha256_bytes(payload: bytes) -> str:
    return hashlib.sha256(payload).hexdigest()


def write_canonical(path: Path, digest_path: Path, value: Dict[str, Any]) -> str:
    text, digest = reference.canonical_report(value)
    path.write_bytes(text.encode("utf-8") + b"\n")
    digest_path.write_text(digest + "\n", encoding="ascii")
    return digest


def build_report(install_location: str | None = None) -> Dict[str, Any]:
    report = reference.build_report(install_location)
    catalog = fixture.catalog()
    report["fixture"] = catalog
    report["profile_scoring"] = scorer.score_profile(report, catalog)
    if not report["profile_scoring"]["passed"]:
        raise ValueError("missing_or_invalid_required_result:"
                         + ",".join(report["profile_scoring"]["failed_checks"]))
    return report


def generate_report(install_location: str | None = None) -> str:
    report = build_report(install_location)
    digest = write_canonical(REPORT_PATH, REPORT_DIGEST_PATH, report)
    HEADER_PATH.write_text(header_text(report["c_boundary_expected"]), encoding="utf-8")
    return digest


def header_text(expected: Dict[str, Any]) -> str:
    counts = ", ".join(str(value) for value in expected["valid_counts"])
    lines = [
        "/* SPDX-FileCopyrightText: 2026 Tsakanyan Hovhannes",
        " * SPDX" "-License-Identifier: Apache-2.0",
        " */",
        "/* Generated by run.py from the deterministic Python model. Do not edit. */",
        "#ifndef SOUNDTOUCH_REFERENCE_EXPECTED_VECTORS_H",
        "#define SOUNDTOUCH_REFERENCE_EXPECTED_VECTORS_H",
        "",
        f'#define EXPECTED_CONTENT_DIGEST "{expected["content_digest"]}"',
        f'#define EXPECTED_CONTENT_SAMPLES {expected["content_samples"]}',
        f'#define EXPECTED_FRAME_COUNT {expected["frames"]}',
        f'#define EXPECTED_DRAIN_NON_CONTENT_SAMPLES {expected["drain_non_content_samples"]}',
        f'#define EXPECTED_PROVIDER_SOURCE_DIGEST "{expected["provider_source_digest"]}"',
        f'#define EXPECTED_CONFIG_DIGEST "{expected["config_digest"]}"',
        "",
        f"static const unsigned short kExpectedValidCounts[EXPECTED_FRAME_COUNT] = {{{counts}}};",
        "",
        "#endif /* SOUNDTOUCH_REFERENCE_EXPECTED_VECTORS_H */",
        "",
    ]
    return "\n".join(lines)


def generate_header() -> str:
    expected = reference.c_boundary_evidence(fixture.c_vector())
    text = header_text(expected)
    HEADER_PATH.write_text(text, encoding="utf-8")
    return sha256_bytes(text.encode("utf-8"))


def sources_text() -> str:
    lines: List[str] = []
    for path in sorted(ROOT.rglob("*"), key=lambda item: item.relative_to(ROOT).as_posix()):
        if not path.is_file() or path.name == SOURCES_PATH.name:
            continue
        if "__pycache__" in path.parts:
            continue
        lines.append(sha256_bytes(path.read_bytes()) + "  "
                     + path.relative_to(ROOT).as_posix())
    for relative, expected in sorted(reference.SOURCE_PINS.items()):
        path = reference.AUDIO_ROOT / relative
        actual = reference.sha256_file(path)
        if actual != expected:
            raise ValueError("source_pin_mismatch:" + relative)
        lines.append("PIN  " + expected + "  " + relative)
    for relative, expected in sorted(reference.BOUNDARY_PINS.items()):
        path = reference.WORKTREE / relative
        actual = reference.sha256_file(path)
        if actual != expected:
            raise ValueError("boundary_pin_mismatch:" + relative)
        lines.append("PIN  " + expected + "  " + relative)
    return "\n".join(lines) + "\n"


def generate_sources() -> str:
    text = sources_text()
    SOURCES_PATH.write_text(text, encoding="ascii")
    return sha256_bytes(text.encode("utf-8"))


def generate_crosscheck() -> str:
    consumer = reference.read_strict_json(CONSUMER_RESULT_PATH)
    required = {"spdx", "kind", "task", "base_commit", "sdk_ctest",
                "consumer_off", "consumer_on", "commands", "test_summary",
                "non_claims"}
    if set(consumer) != required or consumer["task"] != reference.TASK:
        raise ValueError("invalid_consumer_result")
    if (consumer["sdk_ctest"] != "11/11" or consumer["consumer_off"] != "1/1"
            or consumer["consumer_on"] != "1/1"):
        raise ValueError("consumer_results_not_recorded")
    expected = reference.c_boundary_evidence(fixture.c_vector())
    payload = {
        "spdx": {
            "SPDX-FileCopyrightText": "2026 Tsakanyan Hovhannes",
            "SPDX" "-License-Identifier": "Apache-2.0",
        },
        "protocol": reference.CONTRACT_ID,
        "task": reference.TASK,
        "base_commit": reference.BASE_COMMIT,
        "kind": "exact Python/C sample-digest parity and consumer build evidence; not timing or listening",
        "expected_content_digest": expected["content_digest"],
        "expected_content_samples": expected["content_samples"],
        "expected_frame_count": expected["frames"],
        "expected_final_valid_count": expected["valid_counts"][-1],
        "consumer_result_sha256": reference.sha256_file(CONSUMER_RESULT_PATH),
        "consumer_result": consumer,
        "decision": {
            "expose_as_processor": False,
            "registered": False,
            "default_enabled": False,
            "production_exposure": "DEFER",
        },
        "note": ("The C ON consumer compares its float32 content digest, frame count, "
                 "valid counts, final partial window and drain behavior byte-exactly "
                 "with the Python model. No device, listening or timing result is claimed."),
    }
    return write_canonical(CROSSCHECK_PATH, CROSSCHECK_DIGEST_PATH, payload)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--report", action="store_true",
                        help="write report.json, report.json.sha256 and the C parity header")
    parser.add_argument("--sources", action="store_true",
                        help="write SOURCES.sha256 including source pins")
    parser.add_argument("--crosscheck", action="store_true",
                        help="write crosscheck.json and its digest from recorded consumer results")
    parser.add_argument("--emit-header", action="store_true",
                        help="write only the generated C parity header")
    parser.add_argument("--install-location", default=None,
                        help="override the recorded absolute install location")
    options = parser.parse_args()
    actions = (options.report, options.sources, options.crosscheck, options.emit_header)
    if sum(bool(action) for action in actions) != 1:
        parser.error("select exactly one action")
    try:
        if options.report:
            digest = generate_report(options.install_location)
        elif options.sources:
            digest = generate_sources()
        elif options.crosscheck:
            digest = generate_crosscheck()
        else:
            digest = generate_header()
    except (OSError, ValueError, KeyError, TypeError) as error:
        print("FAIL " + str(error), file=sys.stderr)
        return 2
    print(digest)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
