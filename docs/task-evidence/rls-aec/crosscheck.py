"""Regenerate the byte-identical C/Python parity vectors header."""

from __future__ import annotations

import pathlib
import struct
from typing import List, Sequence

import reference

ROOT = pathlib.Path(__file__).resolve().parent
HEADER = ROOT / "provider" / "crosscheck_vectors.h"
FRAMES = 4
COUNT = FRAMES * reference.FRAME_SAMPLES


def f32(value: float) -> float:
    return struct.unpack("<f", struct.pack("<f", value))[0]


def _array(name: str, values: Sequence[float], kind: str) -> str:
    lines = ["static const %s %s[%d] = {" % (kind, name, len(values))]
    row: List[str] = []
    for index, value in enumerate(values):
        row.append("%.9gf" % value if kind == "float" else "%.17g" % value)
        if len(row) == 6 or index == len(values) - 1:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    lines.append("};")
    return "\n".join(lines)


def generate() -> str:
    data = reference.fixture("double_talk")
    mic = [f32(value) for value in data["microphone"][:COUNT]]
    ref = [f32(value) for value in data["reference"][:COUNT]]
    engine = reference.RlsAec()
    output: List[float] = []
    weight_l1: List[float] = []
    skipped: List[float] = []
    for start in range(0, COUNT, reference.FRAME_SAMPLES):
        result = engine.process(tuple(mic[start:start + reference.FRAME_SAMPLES]),
                                tuple(ref[start:start + reference.FRAME_SAMPLES]))
        assert result.status == "ok"
        output.extend(f32(value) for value in result.samples)
        weight_l1.append(engine.weight_l1())
        skipped.append(float(engine.skipped_updates))
    text = "\n".join((
        "/* SPDX-FileCopyrightText: 2026 Tsakanyan Hovhannes",
        " * " "SPDX" "-License-Identifier: Apache-2.0",
        " */",
        "/* Generated by crosscheck.py from the pinned synthetic fixture.",
        " * Do not edit by hand.  Four 160-sample float32 frames. */",
        "#ifndef AUDIO_SDK_RLS_CROSSCHECK_H",
        "#define AUDIO_SDK_RLS_CROSSCHECK_H",
        "",
        "#define CROSSCHECK_FRAMES %d" % FRAMES,
        "#define CROSSCHECK_SAMPLES %d" % COUNT,
        "",
        _array("kCrosscheckMic", mic, "float"),
        "",
        _array("kCrosscheckRef", ref, "float"),
        "",
        _array("kCrosscheckOutput", output, "float"),
        "",
        _array("kCrosscheckWeightL1", weight_l1, "double"),
        "",
        _array("kCrosscheckSkippedUpdates", skipped, "double"),
        "",
        "#endif",
        "",
    ))
    HEADER.write_text(text, encoding="ascii")
    return text


if __name__ == "__main__":
    generate()
