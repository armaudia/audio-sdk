def measure_clean_speech_correlation() -> Dict[str, Any]:
    """No acoustic path: reference is the previous playback of the same speech.

    This is the AFC continuous-speech bias control. Any deviation from the
    nominal margin gain is adaptation acting on wanted speech, not feedback
    attenuation.
    """
    config = DEFAULT_CONFIG
    frames = 140
    speech = speech_like(frames * FRAME_SAMPLES, 31337,
                         always_active=True)
    gain = margin_gain(config)
    playback = [0.0] * FRAME_SAMPLES
    nlms = BlockNlms(config)
    adaptive_output: List[float] = []
    for frame, mic_block in enumerate(blocks(speech)):
        error = nlms.process(mic_block, playback, adapt=True)
        playback = saturate([gain * value for value in error], config)
        adaptive_output.extend(playback)
    fixed_output = [fixed_gain(config) * value for value in speech]
    nominal = [gain * value for value in speech]
    adaptive_ratio = ratio_db(power(adaptive_output), power(nominal))
    fixed_ratio = ratio_db(power(fixed_output), power(nominal))
    return {
        "status": "ok",
        "frames": frames,
        "nominal_gain_db": config["margin_db"],
        "afc_plus_margin_vs_nominal_db": adaptive_ratio,
        "fixed_gain_vs_nominal_db": fixed_ratio,
        "adaptive_speech_sdr_db": ratio_db(power(nominal),
                                          power([a - b for a, b in
                                                 zip(adaptive_output, nominal)])),
        "fixed_speech_sdr_db": ratio_db(power(nominal),
                                       power([a - b for a, b in
                                              zip(fixed_output, nominal)])),
        "adaptive_weight_stats": nlms.weight_stats(),
        "adaptive_output_digest": tensor_digest(adaptive_output),
        "fixed_output_digest": tensor_digest(fixed_output),
    }


def measure_fixed_attenuation() -> Dict[str, Any]:
    config = DEFAULT_CONFIG
    probe = tone(1000, 40 * FRAME_SAMPLES)
    adaptive = run_open_loop(probe, [0.0] * len(probe), "afc_plus_margin", config)
    fixed = run_open_loop(probe, [0.0] * len(probe), "fixed_gain", config)
    measured_adaptive = rms(adaptive["output"][-20 * FRAME_SAMPLES:]) / rms(
        probe[-20 * FRAME_SAMPLES:])
    measured_fixed = rms(fixed["output"][-20 * FRAME_SAMPLES:]) / rms(
        probe[-20 * FRAME_SAMPLES:])
    sweep_rows: List[Dict[str, Any]] = []
    for frequency in FREQUENCIES_HZ:
        values = tone(frequency, 20 * FRAME_SAMPLES)
        run = run_open_loop(values, [0.0] * len(values), "fixed_gain", config)
        measured = rms(run["output"][-FRAME_SAMPLES:]) / rms(
            values[-FRAME_SAMPLES:])
        sweep_rows.append({"frequency_hz": frequency,
                           "measured_linear_gain": measured})
    stress = [3.0 * value for value in speech_like(40 * FRAME_SAMPLES, 808)]
    hot = dict(config)
    hot["saturation"] = "tanh"
    hot_run = run_open_loop(stress, [0.0] * len(stress), "fixed_gain", hot)
    hot_run["output"] = saturate(hot_run["output"], hot)
    peak = max(abs(value) for value in hot_run["output"])
    return {
        "status": "ok",
        "gain_margin": {
            "adaptive_margin_db": config["margin_db"],
            "adaptive_configured_linear_gain": margin_gain(config),
            "adaptive_measured_linear_gain": measured_adaptive,
            "fixed_attenuation_db": config["fixed_gain_db"],
            "fixed_configured_linear_gain": fixed_gain(config),
            "fixed_measured_linear_gain": measured_fixed,
        },
        "fixed_gain_sweep": {
            "frequencies": len(sweep_rows),
            "min_measured_gain": min(row["measured_linear_gain"] for row in sweep_rows),
            "max_measured_gain": max(row["measured_linear_gain"] for row in sweep_rows),
            "per_frequency": sweep_rows,
        },
        "headroom_and_nonlinearity": {
            "input_peak": 3.0,
            "output_peak": peak,
            "headroom_db_to_input_peak": ratio_db(peak * peak, 3.0 * 3.0),
            "nonfinite_samples": sum(1 for value in hot_run["output"]
                                     if not math.isfinite(value)),
            "saturation": "tanh",
        },
        "control_is_level_only": True,
    }


def measure_adverse_controls() -> Dict[str, Any]:
    config = DEFAULT_CONFIG
    good_frame = {"count": FRAME_SAMPLES, "valid": FRAME_SAMPLES,
                  "samples": [0.0] * FRAME_SAMPLES, "flags": 0,
                  "epoch": 1, "position": 0}
    variants = {
        "missing": None,
        "wrong_type": "not-a-config",
        "unknown_key": config_with(unexpected=1),
        "nonfinite": config_with(mu=float("nan")),
        "out_of_range": config_with(mu=2.0),
        "wrong_taps": config_with(taps=32),
    }
    config_statuses = {name: validate_config(value).value
                       for name, value in variants.items()}
    frames = {
        "wrong_shape": dict(good_frame, count=159),
        "nonfinite_sample": dict(good_frame, samples=[float("nan")] + [0.0] * 159),
        "out_of_range_sample": dict(good_frame, samples=[9.0] + [0.0] * 159),
        "stale_epoch": dict(good_frame, epoch=0),
        "wrong_position": dict(good_frame, position=160),
    }
    frame_statuses = {name: validate_frame(value).value
                      for name, value in frames.items()}
    work = BlockNlms(config)
    work.process([0.1] * FRAME_SAMPLES, [0.05] * FRAME_SAMPLES, adapt=True)
    before = work.digest()
    for value in frames.values():
        if validate_frame(value) == Status.OK:
            raise AssertionError("adverse frame was admitted")
    unchanged = work.digest() == before
    reset = BlockNlms(config)
    reset.process([0.1] * FRAME_SAMPLES, [0.05] * FRAME_SAMPLES, adapt=True)
    reset.state = NlmsState([0.0] * config["taps"],
                            [0.0] * (config["taps"] - 1), 0, 0)
    fresh = BlockNlms(config)
    independent_a = BlockNlms(config)
    independent_b = BlockNlms(config)
    signal = [0.07] * FRAME_SAMPLES
    reference = [0.03] * FRAME_SAMPLES
    independent_a.process(signal, reference, adapt=True)
    independent_b.process(signal, reference, adapt=True)
    return {
        "status": "ok",
        "config_statuses": config_statuses,
        "frame_statuses": frame_statuses,
        "state_unchanged_on_rejection": unchanged,
        "reset_state_digest": reset.digest(),
        "fresh_state_digest": fresh.digest(),
        "reset_matches_fresh": reset.digest() == fresh.digest(),
        "independent_state_digest": independent_a.digest(),
        "independent_sessions_match":
            independent_a.digest() == independent_b.digest(),
        "closed_session_status": Status.CLOSED.value,
    }


