def measure_reference_latency() -> Dict[str, Any]:
    config = DEFAULT_CONFIG
    frames = 220
    # White noise, not tones: a tonal reference can be phase-shifted by an
    # adaptive FIR, which would hide genuine reference-latency sensitivity.
    rng = Lcg(24680)
    reference = [0.09 * rng.next() for _ in range(frames * FRAME_SAMPLES)]
    state = [0.0] * (len(path_a()) - 1)
    mic: List[float] = []
    for ref_block in blocks(reference):
        mic.extend(fir_block(ref_block, state, path_a()))
    mic = add_noise(mic, 6004, 0.0004)
    rows: List[Dict[str, Any]] = []
    for offset in LATENCY_OFFSETS:
        shifted = shift_samples(reference, offset)
        run = run_open_loop(mic, shifted, "afc_plus_margin", config)
        late = run["erle_db"][160:]
        rows.append({"offset_samples": offset,
                     "mean_erle_db": sum(late) / len(late)})
    best = max(rows, key=lambda row: row["mean_erle_db"])
    return {
        "status": "ok",
        "warmup_frames": 160,
        "measurement_frames": frames - 160,
        "offsets": rows,
        "best_offset_samples": best["offset_samples"],
        "aligned_erle_db": next(row["mean_erle_db"] for row in rows
                                if row["offset_samples"] == 0),
        "misaligned_max_erle_db": max(row["mean_erle_db"] for row in rows
                                      if row["offset_samples"] != 0),
    }


