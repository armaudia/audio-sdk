def run_open_loop(mic: Sequence[float], reference: Sequence[float],
                  profile: str, config: Dict[str, Any], adapt: bool = True,
                  warmup_frames: int = 0) -> Dict[str, Any]:
    if profile not in PROFILES:
        raise ValueError("unknown control profile")
    chunks = blocks(mic)
    ref_chunks = blocks(reference)
    if len(chunks) != len(ref_chunks):
        raise ValueError("mic/reference length mismatch")
    adaptive = profile in ("afc_only", "afc_plus_margin")
    nlms = BlockNlms(config) if adaptive else None
    gain = (margin_gain(config) if profile == "afc_plus_margin"
            else fixed_gain(config) if profile == "fixed_gain" else 1.0)
    outputs: List[float] = []
    errors: List[float] = []
    erle: List[float] = []
    for index, (mic_block, ref_block) in enumerate(zip(chunks, ref_chunks)):
        if nlms is not None:
            error = nlms.process(mic_block, ref_block,
                                 adapt=adapt and index >= warmup_frames)
            errors.extend(error)
        else:
            error = [float(value) for value in mic_block]
        outputs.extend(gain * value for value in error)
        input_power = power(mic_block)
        error_power = power(error)
        erle.append(ratio_db(input_power, error_power))
    result: Dict[str, Any] = {
        "profile": profile,
        "output": outputs,
        "output_digest": tensor_digest(outputs),
        "erle_db": erle,
        "frames": len(chunks),
        "nonfinite_samples": sum(1 for value in outputs
                                 if not math.isfinite(value)),
    }
    if nlms is not None:
        result["state_digest"] = nlms.digest()
        result["misalignment_db"] = nlms.misalignment_db(path_a())
    return result


def simulate_closed_loop(speech: Sequence[float], config: Dict[str, Any],
                         profile: str, loop_gain: float,
                         path: Sequence[float], seed: int,
                         reference_shift: int = 0,
                         pre_tanh: bool = False) -> Dict[str, Any]:
    """Recursive loop: playback is returned through a 160-sample-delayed path.

    The feedback path begins at the frame boundary, so reference block k-1 is
    the exact loudspeaker signal returning during microphone frame k.
    """
    frames = min(int(config["frames"]), len(speech) // FRAME_SAMPLES)
    rng = Lcg(seed ^ 0x1234567)
    nlms = BlockNlms(config) if profile in ("afc_only", "afc_plus_margin") else None
    gain = (margin_gain(config) if profile == "afc_plus_margin"
            else fixed_gain(config) if profile == "fixed_gain" else 1.0)
    playback_history: List[List[float]] = [[0.0] * FRAME_SAMPLES,
                                            [0.0] * FRAME_SAMPLES]
    feedback_state: List[float] = [0.0] * (len(path) - 1)
    previous_playback: List[float] = [0.0] * FRAME_SAMPLES
    outputs: List[float] = []
    reference: List[float] = []
    microphones: List[float] = []
    rejected_frames = 0
    nonfinite_frames = 0

    speech_end = int(config["speech_end_frame"]) * FRAME_SAMPLES
    for frame in range(frames):
        speech_block = (list(speech[frame * FRAME_SAMPLES:
                                   (frame + 1) * FRAME_SAMPLES])
                        if frame * FRAME_SAMPLES < speech_end
                        else [0.0] * FRAME_SAMPLES)
        feedback = [loop_gain * value for value in
                    fir_block(previous_playback, feedback_state, path)]
        noise = [0.0007 * rng.next() for _ in range(FRAME_SAMPLES)]
        mic = [speech_block[n] + feedback[n] + noise[n]
               for n in range(FRAME_SAMPLES)]
        if any(not math.isfinite(value) or abs(value) > float(config["max_abs_input"])
               for value in mic):
            nonfinite_frames += 1
            mic = [0.0] * FRAME_SAMPLES
        reference.extend(previous_playback)
        microphones.extend(mic)
        if nlms is not None:
            error = nlms.process(mic, previous_playback, adapt=True)
            pre_gain = error
        else:
            pre_gain = list(mic)
        driven = [gain * value for value in pre_gain]
        if pre_tanh:
            driven = saturate(driven, config)
        if any(not math.isfinite(value) or abs(value) > float(config["max_abs_input"])
               for value in driven):
            rejected_frames += 1
            driven = [0.0] * FRAME_SAMPLES
        outputs.extend(driven)
        playback = saturate(driven, config) if not pre_tanh else driven
        previous_playback = playback
        playback_history.append(playback)
        if len(playback_history) > 2:
            playback_history.pop(0)

    active_speech = list(speech[:speech_end])
    active_output = outputs[:speech_end]
    tail_output = outputs[speech_end:frames * FRAME_SAMPLES]
    nominal = gain
    distortion = [output - nominal * target
                  for output, target in zip(active_output, active_speech)]
    result: Dict[str, Any] = {
        "profile": profile,
        "control_family": CONTROL_FAMILY[profile],
        "loop_gain": loop_gain,
        "saturation": config["saturation"] + ("+pre" if pre_tanh else ""),
        "frames": frames,
        "program_sdr_db": ratio_db(power(active_speech), power(distortion)),
        "output_to_program_rms_db": ratio_db(power(active_output),
                                            power(active_speech)),
        "tail_db_relative_to_program": ratio_db(power(tail_output),
                                               power(active_speech)),
        "peak_abs_output": max((abs(value) for value in outputs), default=0.0),
        "nonfinite_frames": nonfinite_frames,
        "rejected_frames": rejected_frames,
        "output_digest": tensor_digest(outputs),
        "reference_digest": tensor_digest(reference),
        "mic_digest": tensor_digest(microphones),
    }
    if tail_output and ratio_db(power(tail_output), power(active_speech)) < -25.0 \
            and rejected_frames == 0:
        result["stability_class"] = "decayed"
    elif rejected_frames:
        result["stability_class"] = "rejected_frames_fail_closed"
    else:
        result["stability_class"] = "sustained_feedback"
    if nlms is not None:
        result["final_erle_db"] = erle_from(microphones, outputs, gain)[-1]
        result["misalignment_db"] = nlms.misalignment_db(path)
    return result


def erle_from(mic: Sequence[float], output: Sequence[float],
              gain: float) -> List[float]:
    chunks = blocks(mic)
    out_chunks = blocks(output)
    values: List[float] = []
    for mic_block, out_block in zip(chunks, out_chunks):
        error = [value / gain for value in out_block]
        values.append(ratio_db(power(mic_block), power(error)))
    return values


