def blocks(samples: Sequence[float]) -> List[List[float]]:
    return [list(samples[start:start + FRAME_SAMPLES])
            for start in range(0, len(samples), FRAME_SAMPLES)]


def flatten(chunks: Sequence[Sequence[float]]) -> List[float]:
    return [value for chunk in chunks for value in chunk]


def power(values: Sequence[float]) -> float:
    return sum(float(value) * float(value) for value in values)


def rms(values: Sequence[float]) -> float:
    return math.sqrt(power(values) / max(len(values), 1))


def db(value: float) -> float:
    return 10.0 * math.log10(max(value, 1.0e-30))


def ratio_db(numerator: float, denominator: float) -> float:
    return 10.0 * math.log10(max(numerator, 1.0e-30) /
                             max(denominator, 1.0e-30))


def add_noise(values: Sequence[float], seed: int,
              amplitude: float) -> List[float]:
    rng = Lcg(seed)
    return [value + amplitude * rng.next() for value in values]


def saturate(values: Sequence[float], config: Dict[str, Any]) -> List[float]:
    mode = config["saturation"]
    threshold = float(config["saturation_threshold"])
    if mode == "tanh":
        return [threshold * math.tanh(value / threshold) for value in values]
    if mode == "clip":
        return [max(-threshold, min(threshold, value)) for value in values]
    return [float(value) for value in values]


def shift_samples(values: Sequence[float], offset: int) -> List[float]:
    """Positive offset delays the reference; negative offset advances it."""
    out = [0.0] * len(values)
    for n in range(len(values)):
        source = n - offset
        if 0 <= source < len(values):
            out[n] = values[source]
    return out


def margin_gain(config: Dict[str, Any]) -> float:
    return 10.0 ** (float(config["margin_db"]) / 20.0)


def fixed_gain(config: Dict[str, Any]) -> float:
    return 10.0 ** (float(config["fixed_gain_db"]) / 20.0)


