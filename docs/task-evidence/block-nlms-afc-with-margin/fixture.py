@dataclass
class NlmsState:
    weights: List[float]
    history: List[float]
    frames: int
    updates: int


class BlockNlms:
    """Causal block NLMS with a per-frame normalized update."""

    def __init__(self, config: Dict[str, Any]) -> None:
        self.taps = int(config["taps"])
        self.mu = float(config["mu"])
        self.epsilon = float(config["epsilon"])
        self.state = NlmsState([0.0] * self.taps,
                               [0.0] * (self.taps - 1), 0, 0)

    def process(self, mic: Sequence[float], reference: Sequence[float],
                adapt: bool = True) -> List[float]:
        taps = self.taps
        w = self.state.weights
        history = self.state.history
        extended = history + list(reference)
        error: List[float] = []
        window: List[List[float]] = []
        for n in range(FRAME_SAMPLES):
            base = taps - 1 + n
            row = [extended[base - i] for i in range(taps)]
            window.append(row)
            estimate = sum(w[i] * row[i] for i in range(taps))
            value = float(mic[n]) - estimate
            error.append(value)
            if not math.isfinite(value):
                raise ValueError("nonfinite adaptive error")
        if adapt:
            # Block-NLMS normalization uses the energy of the current
            # reference block, not the energy of the full tapped window.
            energy = power(reference)
            if not math.isfinite(energy):
                raise ValueError("nonfinite reference energy")
            denominator = energy + self.epsilon
            for i in range(taps):
                correlation = sum(error[n] * window[n][i]
                                  for n in range(FRAME_SAMPLES))
                weight = w[i] + self.mu * correlation / denominator
                if not math.isfinite(weight):
                    raise ValueError("nonfinite adaptive weight")
                w[i] = max(-8.0, min(8.0, weight))
            self.state.updates += 1
        self.state.history = extended[FRAME_SAMPLES:]
        self.state.frames += 1
        return error

    def digest(self) -> str:
        return object_digest({"weights": self.state.weights,
                              "history": self.state.history,
                              "frames": self.state.frames,
                              "updates": self.state.updates})

    def misalignment_db(self, truth: Sequence[float]) -> float:
        expected = list(truth) + [0.0] * (self.taps - len(truth))
        error = sum((a - b) ** 2 for a, b in zip(self.state.weights, expected))
        reference = sum(value * value for value in expected)
        return ratio_db(error, reference)

    def weight_stats(self) -> Dict[str, float]:
        return {"max_abs_weight": max(abs(value)
                                      for value in self.state.weights),
                "weight_norm_db": db(power(self.state.weights))}


