def _loop_mic(speech: Sequence[float], config: Dict[str, Any],
              loop_gain: float, path: Sequence[float], seed: int) -> List[float]:
    """Replays the deterministic microphone stream of one closed-loop case."""
    rng = Lcg(seed ^ 0x1234567)
    playback = [0.0] * FRAME_SAMPLES
    state = [0.0] * (len(path) - 1)
    microphones: List[float] = []
    gain = margin_gain(config)
    nlms = BlockNlms(config)
    for frame in range(min(int(config["frames"]), len(speech) // FRAME_SAMPLES)):
        speech_block = list(speech[frame * FRAME_SAMPLES:
                                  (frame + 1) * FRAME_SAMPLES])
        feedback = [loop_gain * value for value in fir_block(playback, state, path)]
        noise = [0.0007 * rng.next() for _ in range(FRAME_SAMPLES)]
        mic = [speech_block[n] + feedback[n] + noise[n]
               for n in range(FRAME_SAMPLES)]
        microphones.extend(mic)
        error = nlms.process(mic, playback, adapt=True)
        playback = saturate([gain * value for value in error], config)
    return microphones[:30 * FRAME_SAMPLES]


def _loop_reference(speech: Sequence[float], config: Dict[str, Any],
                    loop_gain: float, path: Sequence[float],
                    seed: int) -> List[float]:
    # Rebuild the exact playback stream from the pinned loop conditions.
    rng = Lcg(seed ^ 0x1234567)
    playback = [0.0] * FRAME_SAMPLES
    state = [0.0] * (len(path) - 1)
    gain = margin_gain(config)
    nlms = BlockNlms(config)
    reference: List[float] = []
    for frame in range(min(int(config["frames"]), len(speech) // FRAME_SAMPLES)):
        speech_block = list(speech[frame * FRAME_SAMPLES:
                                  (frame + 1) * FRAME_SAMPLES])
        feedback = [loop_gain * value for value in fir_block(playback, state, path)]
        noise = [0.0007 * rng.next() for _ in range(FRAME_SAMPLES)]
        mic = [speech_block[n] + feedback[n] + noise[n]
               for n in range(FRAME_SAMPLES)]
        reference.extend(playback)
        error = nlms.process(mic, playback, adapt=True)
        playback = saturate([gain * value for value in error], config)
    return reference[:30 * FRAME_SAMPLES]


