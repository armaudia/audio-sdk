class Lcg:
    """32-bit LCG used only for deterministic synthetic noise."""

    def __init__(self, seed: int) -> None:
        self.state = int(seed) & 0xFFFFFFFF

    def next(self) -> float:
        self.state = (1664525 * self.state + 1013904223) & 0xFFFFFFFF
        return self.state / 2147483648.0 - 1.0


def tone(frequency_hz: float, count: int, amplitude: float = 0.2,
         phase: float = 0.0) -> List[float]:
    step = 2.0 * math.pi * float(frequency_hz) / SAMPLE_RATE_HZ
    return [amplitude * math.sin(step * n + phase) for n in range(count)]


def speech_like(count: int, seed: int, always_active: bool = False) -> List[float]:
    """Deterministic voiced/unvoiced speech-like probe; no real speech."""
    rng = Lcg(seed ^ 0x5A5A5A5A)
    phase = 0.0
    output: List[float] = []
    for n in range(count):
        t = n / SAMPLE_RATE_HZ
        pitch = 118.0 + 34.0 * math.sin(2.0 * math.pi * 0.43 * t)
        phase += 2.0 * math.pi * pitch / SAMPLE_RATE_HZ
        gate = 1 if always_active else (1 if (int(t * 10.0) % 9) < 6 else 0)
        syllable = 0.5 + 0.5 * math.sin(2.0 * math.pi * 2.1 * t)
        envelope = 0.34 * gate * (0.25 + 0.75 * syllable)
        voiced = (0.55 * math.sin(phase) + 0.27 * math.sin(2.0 * phase)
                  + 0.12 * math.sin(3.0 * phase))
        noise = 0.045 * rng.next()
        output.append(envelope * (voiced + noise))
    return output


def fir_block(block: Sequence[float], state: List[float],
              taps: Sequence[float]) -> List[float]:
    """Streaming FIR: state holds the last len(taps)-1 input samples."""
    order = len(taps)
    extended = state + list(block)
    output = [sum(taps[j] * extended[order - 1 + n - j]
                  for j in range(order)) for n in range(len(block))]
    state[:] = extended[len(block):]
    return output


def _scaled_path(entries: Sequence[Tuple[int, float]]) -> List[float]:
    # The 0.75 normalization keeps the unattenuated loop unstable while the
    # fixed -5 dB control remains below unity loop gain in the frozen cases.
    taps = [0.0] * 32
    for index, value in entries:
        taps[index] = 0.75 * value
    return taps


