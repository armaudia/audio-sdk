def validate_frame(frame: Optional[Dict[str, Any]], epoch: int = 1,
                   position: int = 0) -> Status:
    """Fail closed on wrong-shape, nonfinite, stale or misplaced frames."""
    if frame is None:
        return Status.REJECTED_MISSING
    if not isinstance(frame, dict):
        return Status.REJECTED_INVALID
    count = frame.get("count")
    valid = frame.get("valid")
    if count != FRAME_SAMPLES or not isinstance(valid, int) or not (1 <= valid <= count):
        return Status.REJECTED_TENSOR
    samples = frame.get("samples")
    if not isinstance(samples, (list, tuple)) or len(samples) != count:
        return Status.REJECTED_TENSOR
    if not all(isinstance(value, (int, float)) and math.isfinite(float(value))
               for value in samples):
        return Status.REJECTED_NONFINITE
    if any(abs(float(value)) > float(DEFAULT_CONFIG["max_abs_input"])
           for value in samples[:valid]):
        return Status.REJECTED_INVALID
    if frame.get("flags", 0) not in (0, 1):
        return Status.REJECTED_INVALID
    if valid != count and frame.get("flags", 0) != 1:
        return Status.REJECTED_INVALID
    if frame.get("epoch") != epoch:
        return Status.REJECTED_EPOCH
    if frame.get("position") != position:
        return Status.REJECTED_POSITION
    return Status.OK


