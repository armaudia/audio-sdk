def _identification_signal(frames: int, seed: int) -> Tuple[List[float], List[float]]:
    rng = Lcg(seed)
    reference: List[float] = []
    for n in range(frames * FRAME_SAMPLES):
        t = n / SAMPLE_RATE_HZ
        reference.append(0.18 * math.sin(2.0 * math.pi * 350.0 * t)
                         + 0.11 * math.sin(2.0 * math.pi * 1150.0 * t
                                           + 0.6)
                         + 0.035 * rng.next())
    return reference, reference


