def strict_json(path: Path) -> Any:
    return reference.load_strict_json(path)


def check_json_files(errors: List[str]) -> Dict[str, Any]:
    try:
        report = strict_json(REPORT)
        contract = strict_json(CONTRACT)
    except (OSError, ValueError) as error:
        errors.append("strict JSON failed: " + str(error))
        return {}
    if not isinstance(report, dict) or not isinstance(contract, dict):
        errors.append("report or contract root is not an object")
        return {}
    if REPORT.read_bytes() != (reference.canonical_text(report) + "\n").encode("utf-8"):
        errors.append("report.json is not canonical byte output")
    if CONTRACT.read_bytes() != (reference.canonical_text(contract) + "\n").encode("utf-8"):
        errors.append("contract.json is not canonical byte output")
    _, digest = reference.canonical_report(report)
    if SIDECAR.read_text(encoding="ascii") != digest + "\n":
        errors.append("report.json.sha256 is stale")
    return {"report": report, "contract": contract}


def check_pins(errors: List[str]) -> int:
    count = 0
    for raw in PINS.read_text(encoding="utf-8").splitlines():
        if not raw or raw.startswith("#"):
            continue
        count += 1
        parts = raw.split("  ", 1)
        if len(parts) != 2 or len(parts[0]) != 64:
            errors.append("malformed pin line: " + repr(raw))
            continue
        digest, raw_path = parts
        if raw_path.startswith("source:"):
            path = SOURCE_ROOT / raw_path.split(":", 1)[1]
        else:
            path = SDK_ROOT / raw_path
        if not path.is_file():
            errors.append("pinned file missing: " + raw_path)
        elif reference.sha256_bytes(path.read_bytes()) != digest:
            errors.append("pinned bytes changed: " + raw_path)
    if PINS.read_bytes() != reference.sources_bytes():
        errors.append("SOURCES.sha256 is not the deterministic generated bytes")
    return count


def check_artifact_pins(errors: List[str], contract: Dict[str, Any]) -> None:
    pins = contract.get("artifact_pins")
    if not isinstance(pins, dict):
        errors.append("contract artifact_pins is not an object")
        return
    expected_names = {reference.TASK_PREFIX + name
                      for name in reference.ARTIFACT_FILES}
    if set(pins) != expected_names:
        errors.append("artifact pin set mismatch")
    for path, digest in pins.items():
        full = SDK_ROOT / path
        if not full.is_file():
            errors.append("artifact pin missing: " + path)
        elif reference.file_digest(full) != digest:
            errors.append("artifact pin stale: " + path)
    for forbidden in ("contract.json", "SOURCES.sha256"):
        if reference.TASK_PREFIX + forbidden in pins:
            errors.append("self-referential artifact pin: " + forbidden)


def check_board(errors: List[str], report: Dict[str, Any],
                contract: Dict[str, Any]) -> None:
    live = reference.board_row()
    if report.get("board_row") != live:
        errors.append("report board identity is stale")
    if contract.get("board_row") != live:
        errors.append("contract board identity is stale")
    row = report.get("board_row", {})
    if row.get("full_tasks_json_hashed") is not False:
        errors.append("full task board is hashed")
    stable = row.get("stable_fields", {})
    if reference.object_digest(stable) != row.get("stable_sha256"):
        errors.append("stable board hash mismatch")
    if stable.get("id") != reference.TASK_ID:
        errors.append("stable board task id mismatch")
    if stable.get("component") != reference.COMPONENT:
        errors.append("stable board component mismatch")
    if stable.get("repository") != reference.REPOSITORY:
        errors.append("stable board repository mismatch")
    if stable.get("mode") != "feasibility":
        errors.append("stable board mode mismatch")
    if "status" in stable or "owner" in stable:
        errors.append("mutable board field leaked into the stable identity")
    for section in ("source_pins", "boundary_pins"):
        for path in report.get(section, {}):
            if path.endswith("TASKS.json"):
                errors.append("mutable task board is pinned in " + section)


def check_source_pins(errors: List[str], report: Dict[str, Any],
                      contract: Dict[str, Any]) -> None:
    if report.get("source_pins") != reference.SOURCE_PINS:
        errors.append("report source pins differ from the frozen table")
    if report.get("boundary_pins") != reference.BOUNDARY_PINS:
        errors.append("report boundary pins differ from the frozen table")
    if contract.get("source_pins") != reference.SOURCE_PINS:
        errors.append("contract source pins differ from the frozen table")
    if contract.get("boundary_pins") != reference.BOUNDARY_PINS:
        errors.append("contract boundary pins differ from the frozen table")


def strict_json_bytes(data: bytes) -> Any:
    return reference.parse_strict_json(data.decode("utf-8"))


def check_control(errors: List[str], label: str, block: Dict[str, Any],
                  fixture: Dict[str, Any]) -> None:
    if block.get("is_catalogued_candidate") is not False:
        errors.append(label + " control claims the catalogued candidate")
    if block.get("role") != "spatial_baseline_control_only":
        errors.append(label + " control role is promoted")
    body = block.get("control", {})
    if body.get("is_neural_beamformer") is not False:
        errors.append(label + " control claims to be a neural beamformer")
    if body.get("status") != "control_only_not_qualified":
        errors.append(label + " control status is promoted")
    if body.get("qualification_status") != "not_qualified":
        errors.append(label + " control is qualified")
    if body.get("model_weights") is not False:
        errors.append(label + " control claims model weights")
    if body.get("mask_applied") is not False:
        errors.append(label + " control claims mask use")
    if body.get("spatial_loss_used") is not False:
        errors.append(label + " control claims a spatial loss")
    if body.get("peak_index") != fixture["click_index"]:
        errors.append(label + " control does not recover the declared click")
    if len(body.get("output_exact", [])) != reference.FRAME_SAMPLES:
        errors.append(label + " control output length mismatch")
    if reference.object_digest(body.get("output_exact")) != body.get("output_digest"):
        errors.append(label + " control digest mismatch")


def check_report(errors: List[str], report: Dict[str, Any]) -> None:
    if not REQUIRED_REPORT_KEYS <= set(report):
        errors.append("report missing sections: "
                      + ", ".join(sorted(REQUIRED_REPORT_KEYS - set(report))))
        return
    if report["schema_id"] != reference.REPORT_SCHEMA:
        errors.append("unexpected report schema")
    if report["status"] != "proposal_only_incomplete":
        errors.append("report is not proposal-only/incomplete")
    if report["evidence_status"] != "incomplete" or report["decision"] != "DEFER":
        errors.append("missing incomplete/DEFER disposition")
    if report["defer_before"] != "opt_in_adapter_exposure":
        errors.append("unexpected defer point")
    if report["verification_profile"] != "spatial":
        errors.append("verification profile is not spatial")
    if report["task"] != reference.TASK_ID or report["component"] != reference.COMPONENT:
        errors.append("report task or component mismatch")
    if report["base_commit"] != reference.BASE_COMMIT:
        errors.append("report base commit mismatch")
    if report["branch"] != reference.BRANCH:
        errors.append("report branch mismatch")

    qualification = report["qualification"]
    if qualification.get("status") != "not_qualified":
        errors.append("qualification status is not not_qualified")
    for key in ("qualifies", "all_required_results_present",
                "missing_result_promoted", "catalogued_candidate_executed",
                "neural_output_present", "model_weights_loaded",
                "mask_quality_measured", "real_recording_evidence",
                "exact_runtime_parity", "device_timing", "heldout_scoring",
                "provider_intake"):
        if qualification.get(key) is not False:
            errors.append("qualification flag is not false: " + key)
    if qualification.get("decision") != "DEFER":
        errors.append("qualification decision is not DEFER")
    if qualification.get("evidence_status") != "incomplete":
        errors.append("qualification evidence is not incomplete")
    if qualification.get("proposal_only") is not True:
        errors.append("qualification is not proposal-only")

    candidate = report["candidate_execution"]
    if candidate.get("status") != "blocked":
        errors.append("candidate execution is not blocked")
    if candidate.get("present") is not False or candidate.get("executed") is not False:
        errors.append("candidate source/weights/runtime presence or execution is claimed")
    if candidate.get("result") is not None:
        errors.append("candidate result is promoted")

    ref = report["reference"]
    for key in ("concrete_model_selected", "neural_implemented", "neural_executed",
                "model_weights", "mask_applied", "spatial_loss_used",
                "training_data_used", "downloads", "licensed_runtime",
                "catalogued_candidate_executed", "device_or_timing_claim",
                "registered", "default_enabled"):
        if ref.get(key) is not False:
            errors.append("reference flag is not false: " + key)
    if ref.get("catalogued_category") != "CLN-07":
        errors.append("catalogued category is not CLN-07")
    if ref.get("catalogued_category_source_ids") != ["S24", "S25"]:
        errors.append("catalogued category source IDs are not S24/S25")
    if ref.get("candidate_family_leads") != ["SpatialNet",
                                             "Beam-TasNet / Beam-Guided TasNet"]:
        errors.append("candidate family leads are not the frozen pair")

    plan = report["neural_plan"]
    if plan.get("present") is not False or plan.get("executed") is not False:
        errors.append("neural plan presence or execution is claimed")
    if plan.get("status") != "blocked":
        errors.append("neural plan is not blocked")
    if plan.get("qualification_status") != "not_qualified":
        errors.append("neural plan is qualified")
    if not isinstance(plan.get("missing"), list) or not plan["missing"]:
        errors.append("neural plan missing list is empty")

    mask = report["mask_manifest"]
    if mask.get("status") != "structure_only_not_qualified":
        errors.append("mask manifest is promoted")
    if mask.get("qualification_status") != "not_qualified":
        errors.append("mask manifest is qualified")
    if mask.get("applied_to_beamformer") is not False:
        errors.append("mask is claimed as applied")
    if mask.get("quality_result") is not False:
        errors.append("mask quality is claimed")
    parsed_mask = reference.parse_mask_manifest(
        strict_json_bytes(reference.canonical_bytes(mask["manifest"])))
    if reference.object_digest(parsed_mask) != mask.get("manifest_digest"):
        errors.append("mask manifest digest mismatch")

    absence = report["absence_evidence"]
    if absence.get("fixed_probe_list_only") is not True:
        errors.append("absence probe is not a fixed list")
    if absence.get("present_count") != 0 or absence.get("all_absent") is not True:
        errors.append("absence probe did not report all artifacts absent")
    if absence.get("network_used") is not False:
        errors.append("absence probe used the network")
    if absence.get("download_attempted") is not False:
        errors.append("absence probe attempted a download")
    if absence.get("audio_read") is not False:
        errors.append("absence probe read audio")
    if absence.get("candidate_module_imported") is not False:
        errors.append("absence probe imported a candidate module")
    if absence.get("candidate_runtime_executed") is not False:
        errors.append("absence probe executed a candidate runtime")
    probes = absence.get("probes", [])
    if len(probes) != absence.get("probe_count"):
        errors.append("absence probe count mismatch")
    if any(probe.get("present") is not False for probe in probes):
        errors.append("an absence probe reports a present artifact")
    if absence != reference.absence_evidence():
        errors.append("absence evidence differs from the live fixed probe")

    fixture = report["fixture"]
    rebuilt_fixture = {
        "schema_id": fixture.get("schema_id"),
        "fixture_id": fixture.get("fixture_id"),
        "geometry": fixture.get("geometry"),
        "steering_delays": fixture.get("steering_delays"),
        "click_index": fixture.get("click_index"),
        "click_amplitude": fixture.get("click_amplitude"),
        "interference_rule": fixture.get("interference_rule"),
        "frame_samples": fixture.get("frame_samples"),
        "channels": fixture.get("channels"),
    }
    if fixture.get("schema_id") != reference.FIXTURE_SCHEMA:
        errors.append("fixture schema mismatch")
    if reference.object_digest(rebuilt_fixture) != fixture.get("fixture_digest"):
        errors.append("fixture digest is stale")
    if reference.object_digest(fixture.get("geometry")) != fixture.get("geometry_digest"):
        errors.append("geometry digest is stale")
    built_fixture = reference.build_fixture()
    if rebuilt_fixture != built_fixture["fixture"]:
        errors.append("fixture bytes differ from the deterministic builder")
    if fixture.get("status") != "synthetic_declared_not_measured":
        errors.append("fixture status is promoted")
    if fixture.get("qualification_status") != "not_qualified":
        errors.append("fixture is qualified")
    geometry = fixture["geometry"]
    if geometry.get("reference_mic_id") != "m0":
        errors.append("fixture reference channel is not m0")
    if len(geometry.get("microphones", [])) != 4:
        errors.append("fixture microphone count is not four")
    if len(fixture.get("channels", [])) != 4:
        errors.append("fixture channel count is not four")
    if fixture.get("click_index") != reference.fixture_click_index():
        errors.append("fixture click index mismatch")
    for delay in fixture["steering_delays"]:
        if delay.get("exact_integer_sample") is not True:
            errors.append("fixture steering is not exact: " + delay["mic_id"])
        if not isinstance(delay.get("relative_q16"), int):
            errors.append("fixture q16 delay is not an integer")
        if delay["relative_q16"] % reference.Q16 != 0:
            errors.append("fixture delay is fractional: " + delay["mic_id"])
    for row in fixture["channels"]:
        for sample in row:
            if not isinstance(sample, int) or isinstance(sample, bool):
                errors.append("fixture sample is not an integer")
                break

    controls = report["control_baselines"]
    if set(controls) != {"identity", "delay_and_sum"}:
        errors.append("control baseline set mismatch")
    else:
        check_control(errors, "identity", controls["identity"], fixture)
        check_control(errors, "delay_and_sum", controls["delay_and_sum"], fixture)
        identity_body = controls["identity"]["control"]
        delay_body = controls["delay_and_sum"]["control"]
        if identity_body.get("control_id") != "identity-reference-channel-control-v1":
            errors.append("identity control id mismatch")
        if identity_body.get("peak_value_exact") != "1548/1":
            errors.append("identity control peak changed")
        if delay_body.get("control_id") != "delay-and-sum-equal-weight-control-v1":
            errors.append("delay-and-sum control id mismatch")
        if delay_body.get("peak_value_exact") != "3049/2":
            errors.append("delay-and-sum control peak changed")

    comparison = report["distortion_comparison"]
    if comparison.get("status") != "blocked":
        errors.append("distortion comparison is not blocked")
    if comparison.get("neural_output_present") is not False:
        errors.append("distortion comparison claims neural output")
    if comparison.get("identity_control_present") is not True:
        errors.append("distortion comparison lost the identity control")
    if comparison.get("delay_and_sum_control_present") is not True:
        errors.append("distortion comparison lost the delay-and-sum control")
    if comparison.get("metric") is not None or comparison.get("value") is not None:
        errors.append("distortion comparison contains a result")
    if comparison.get("qualification_status") != "not_qualified":
        errors.append("distortion comparison is qualified")

    gates = report["release_gates"]
    if len(gates) != 8:
        errors.append("expected exactly eight release gates")
    gate_ids = [gate.get("id") for gate in gates]
    if gate_ids != [f"RG-{index:02d}" for index in range(1, 9)]:
        errors.append("release gate IDs are not RG-01..RG-08")
    if any(gate.get("status") != "blocked" for gate in gates):
        errors.append("a release gate is not blocked")

    profile = report["acceptance_profile"]
    if profile.get("profile") != "spatial":
        errors.append("spatial acceptance profile not recorded")
    items = profile.get("required_items", {})
    if len(items) != 6:
        errors.append("spatial profile item set mismatch")
    for name, item in items.items():
        if item.get("status") not in {"declared_synthetic_only", "blocked"}:
            errors.append("spatial item promoted: " + name)
    specific = profile.get("neural_specific_items", {})
    if set(specific) != {"model_identity_and_weights", "target_definition",
                         "mask_validity", "spatial_loss_and_training_rights",
                         "exact_runtime_parity",
                         "extraction_leakage_target_damage"}:
        errors.append("neural-specific item set mismatch")
    for name, item in specific.items():
        if item.get("status") not in {"declared_synthetic_only", "blocked"}:
            errors.append("neural-specific item promoted: " + name)
    if specific["model_identity_and_weights"]["status"] != "blocked":
        errors.append("model identity/weights is not blocked")
    if specific["exact_runtime_parity"]["status"] != "blocked":
        errors.append("exact runtime parity is not blocked")

    adverse = report["adverse_rejections"]
    if len(adverse) != report["adverse_case_count"]:
        errors.append("adverse count mismatch")
    if len(adverse) != len(reference.adverse_rejections()):
        errors.append("adverse cases differ from the deterministic set")
    if report.get("adverse_all_rejected") is not True:
        errors.append("adverse_all_rejected is not true")
    for item in adverse:
        if item.get("status") != "rejected" or item.get("state_unchanged") is not True:
            errors.append("adverse case not rejected immutably: " + item["case_id"])

    prerequisites = report.get("required_prerequisites")
    if not isinstance(prerequisites, list) or len(prerequisites) < 8:
        errors.append("required prerequisites are incomplete")
    else:
        for item in prerequisites:
            if not item.get("id") or not item.get("requirement") or not item.get("state"):
                errors.append("required prerequisite is not machine-readable")
                break
    blockers = report.get("exact_blockers")
    if not isinstance(blockers, list) or len(blockers) != 8:
        errors.append("expected exactly eight exact blockers")

    boundary = report["boundary"]
    if not boundary or any(value is not False for value in boundary.values()):
        errors.append("a boundary flag claims a change")

    repeat = report["repeatability"]
    digests = repeat.get("core_digests", [])
    if repeat.get("runs") != 3 or repeat.get("byte_identical") is not True:
        errors.append("repeatability is not three byte-identical runs")
    if len(digests) != 3 or len(set(digests)) != 1:
        errors.append("core repeat digests differ")
    if digests and digests[0] != repeat.get("core_digest"):
        errors.append("core digest does not match the repeat digest")

    text = reference.canonical_text(report)
    if '"qualifies":true' in text or '"status":"qualified"' in text:
        errors.append("canonical report contains a qualified claim")
    if "TASKS.json" in reference.canonical_text(report["source_pins"]):
        errors.append("mutable task board appears in source pins")
    if reference.file_digest(REPORT) not in README.read_text(encoding="utf-8"):
        errors.append("README.md does not pin the current report SHA-256")


def check_contract(errors: List[str], contract: Dict[str, Any],
                   report: Dict[str, Any]) -> None:
    if not REQUIRED_CONTRACT_KEYS <= set(contract):
        errors.append("contract missing sections: "
                      + ", ".join(sorted(REQUIRED_CONTRACT_KEYS - set(contract))))
        return
    if contract["schema_id"] != reference.CONTRACT_SCHEMA:
        errors.append("unexpected contract schema")
    if contract["task"] != reference.TASK_ID or contract["component"] != reference.COMPONENT:
        errors.append("contract task or component mismatch")
    if contract["base_commit"] != reference.BASE_COMMIT:
        errors.append("contract base commit mismatch")
    if contract["branch"] != reference.BRANCH:
        errors.append("contract branch mismatch")
    if contract["decision"] != "DEFER" or contract["evidence_status"] != "incomplete":
        errors.append("contract disposition is not DEFER/incomplete")
    if contract["status"] != "proposal_only_incomplete":
        errors.append("contract status is promoted")
    if contract["qualification_status"] != "not_qualified":
        errors.append("contract qualification is not not_qualified")
    if contract["verification_profile"] != "spatial":
        errors.append("contract verification profile mismatch")
    if contract.get("release_gates") != report.get("release_gates"):
        errors.append("contract/report release gates differ")
    if contract.get("exact_blockers") != report.get("exact_blockers"):
        errors.append("contract/report blockers differ")
    if contract.get("required_prerequisites") != report.get("required_prerequisites"):
        errors.append("contract/report prerequisites differ")
    boundary = contract.get("public_boundary", {})
    for key in ("c_provider_added", "public_api_abi_changed",
                "installed_v0_behavior_changed", "shared_build_or_ci_changed"):
        if boundary.get(key) is not False:
            errors.append("contract boundary flag is not false: " + key)
    scope = contract.get("scope", {})
    if scope.get("synthetic_only") is not True or scope.get("task_local_only") is not True:
        errors.append("contract scope must be synthetic-only and task-local")
    for key, value in scope.items():
        if key in {"synthetic_only", "task_local_only"}:
            continue
        if value is not False:
            errors.append("contract scope flag is not false: " + key)
    ref = contract.get("reference", {})
    for key in ("concrete_model_selected", "neural_implemented", "neural_executed",
                "model_weights", "mask_applied", "spatial_loss_used",
                "training_data_used", "downloads",
                "catalogued_candidate_executed"):
        if ref.get(key) is not False:
            errors.append("contract reference flag is not false: " + key)
    check_artifact_pins(errors, contract)


def check_repeats(errors: List[str], report: Dict[str, Any]) -> None:
    if not report:
        return
    texts = []
    for _ in range(3):
        built = reference.build_report()
        text, _ = reference.canonical_report(built)
        texts.append(text)
    if len(set(texts)) != 1:
        errors.append("three fresh report builds differ")
    if texts[0].encode("utf-8") != REPORT.read_bytes():
        errors.append("fresh build does not match report.json")


def check_licensing(errors: List[str]) -> None:
    for path in sorted(HERE.glob("*.py")):
        head = "\n".join(path.read_text(encoding="utf-8").splitlines()[:4])
        if SPDX_LICENSE not in head or SPDX_COPYRIGHT not in head:
            errors.append("missing SPDX header: " + path.name)
    readme_head = "\n".join(README.read_text(encoding="utf-8").splitlines()[:4])
    if SPDX_LICENSE not in readme_head or SPDX_COPYRIGHT not in readme_head:
        errors.append("README.md is missing its SPDX header")
    for name in LICENSE_SIDECARS:
        path = HERE / name
        if not path.is_file():
            errors.append("missing license sidecar: " + name)
            continue
        content = path.read_text(encoding="utf-8")
        if SPDX_LICENSE not in content or SPDX_COPYRIGHT not in content:
            errors.append("invalid license sidecar: " + name)
    reuse = (SDK_ROOT / "REUSE.toml").read_text(encoding="utf-8")
    if '"docs/**"' not in reuse or ('SPDX' "-License-Identifier = \"Apache-2.0\"") not in reuse:
        errors.append("REUSE.toml no longer covers docs/** as Apache-2.0")


def check_scope(errors: List[str]) -> List[str]:
    result = subprocess.run(
        ["git", "-C", str(SDK_ROOT), "status", "--porcelain=v1",
         "--untracked-files=all"],
        capture_output=True, text=True, check=True)
    changed: List[str] = []
    for line in result.stdout.splitlines():
        path = line[3:] if line[:2].strip() else line
        if " -> " in path:
            path = path.split(" -> ", 1)[1]
        changed.append(path)
        if not path.startswith(reference.TASK_PREFIX):
            errors.append("change outside task scope: " + path)
    diff_check = subprocess.run(
        ["git", "-C", str(SDK_ROOT), "diff", "--check"],
        capture_output=True, text=True)
    if diff_check.returncode != 0:
        errors.append("git diff --check failed: " + diff_check.stdout.strip())
    return changed


def main() -> int:
    errors: List[str] = []
    loaded = check_json_files(errors)
    report = loaded.get("report", {})
    contract = loaded.get("contract", {})
    pin_count = check_pins(errors)
    if report:
        check_report(errors, report)
        check_source_pins(errors, report, contract)
        check_board(errors, report, contract)
    if contract:
        check_contract(errors, contract, report)
    check_repeats(errors, report)
    check_licensing(errors)
    changed = check_scope(errors)
    if errors:
        for error in errors:
            print("FAIL: " + error)
        return 1
    print(f"pins_ok={pin_count} json_ok=2 report_sha256="
          f"{reference.file_digest(REPORT)} repeats_ok=3 "
          f"licensing_ok=1 scope_ok=1 changed_files={len(changed)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
