"""Read-only strict verifier for SDK-NEURAL-BEAMFORMING.

Usage::

    PYTHONDONTWRITEBYTECODE=1 python3 verify.py

Fails closed on non-canonical or duplicate-key/nonfinite JSON, stale digests,
stale pins, a non-spatial profile, a promoted missing neural result, a promoted
control baseline, a qualified claim, an unblocked release gate, license gaps,
out-of-scope worktree changes, whitespace damage or a dirty
``git diff --check``.  Never writes.
"""

