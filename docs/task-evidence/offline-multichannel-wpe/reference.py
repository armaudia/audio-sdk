@dataclass
class OfflineWpe:
    """Whole-clip, noncausal multichannel WPE at one STFT resolution."""

    config: Dict[str, Any]
    singular_solves: int = 0
    capped_frames: int = 0
    frames: int = 0
    bins: int = 0

    @classmethod
    def create(cls, config: Dict[str, Any]) -> "OfflineWpe":
        size = int(config["fft_size"])
        return cls(config=dict(config), bins=size // 2 + 1)

    def digest(self) -> str:
        return object_digest({
            "config": self.config, "singular_solves": self.singular_solves,
            "capped_frames": self.capped_frames, "frames": self.frames,
            "bins": self.bins,
        })

    def _stft(self, channels: Sequence[Sequence[float]]
              ) -> Tuple[Tuple[List[complex], ...], ...]:
        size = int(self.config["fft_size"])
        hop = int(self.config["hop_size"])
        window = _sqrt_hann(size)
        count = max(1, int(math.ceil((len(channels[0]) + BIAS_SAMPLES - size) / hop)) + 1)
        frames: List[Tuple[List[complex], ...]] = []
        for frame_index in range(count):
            start = frame_index * hop - BIAS_SAMPLES
            spectra: List[List[complex]] = []
            for channel in channels:
                block = [0.0] * size
                for offset in range(size):
                    position = start + offset
                    if 0 <= position < len(channel):
                        block[offset] = channel[position] * window[offset]
                spectra.append(scorer._fft([complex(value, 0.0) for value in block])[:self.bins])
            frames.append(tuple(spectra))
        return tuple(frames)

    @staticmethod
    def _one_sided_to_full(spectrum: Sequence[complex]) -> List[complex]:
        half = len(spectrum) - 1
        return list(spectrum) + [spectrum[half - 1 - index].conjugate()
                                 for index in range(half - 1)]

    def _delayed(self, frames: Sequence[Tuple[List[complex], ...]], frame_index: int,
                 bin_index: int, data: Sequence[Tuple[List[complex], ...]]
                 ) -> List[complex]:
        channels = int(self.config["channels"])
        taps = int(self.config["taps"])
        delay = int(self.config["wpe_delay_frames"])
        result: List[complex] = []
        for channel in range(channels):
            for tap in range(taps):
                source = frame_index - delay - tap
                if source < 0:
                    result.append(0j)
                else:
                    result.append(data[source][channel][bin_index])
        return result

    def process(self, channels: Sequence[Sequence[float]]
                ) -> Tuple[Tuple[float, ...], ...]:
        """Enhance a whole two-channel clip; uses all frames for every output."""
        config = self.config
        channels = tuple(tuple(float(value) for value in channel) for channel in channels)
        if len(channels) != int(config["channels"]):
            raise ValueError("channel_count_mismatch")
        if not channels[0] or any(len(channel) != len(channels[0]) for channel in channels):
            raise ValueError("shape_mismatch")
        if any(not math.isfinite(value) for channel in channels for value in channel):
            raise ArithmeticError("nonfinite_input")
        if any(abs(value) > float(config["max_abs_input"])
               for channel in channels for value in channel):
            raise ValueError("input_out_of_range")

        size = int(config["fft_size"])
        hop = int(config["hop_size"])
        taps = int(config["taps"])
        channels_count = int(config["channels"])
        predictors = channels_count * taps
        loading_base = float(config["regularization"])
        cap = float(config["prediction_energy_cap"])
        frames = self._stft(channels)
        enhanced = frames
        count = len(frames)
        bins = self.bins
        self.frames = count
        window = _sqrt_hann(size)

        input_energies = [
            [math.fsum(abs(value) ** 2 for value in frames[frame_index][channel])
             for channel in range(channels_count)]
            for frame_index in range(count)]
        scale = 1.0 / count
        for _ in range(int(config["iterations"])):
            # Accumulate one covariance matrix and one cross vector per frequency
            # bin over the *whole clip*. This is the offline/noncausal step: every
            # frame's statistics contribute to every frame's predictor.
            statistics: List[Tuple[List[List[complex]], List[List[complex]]]] = []
            for bin_index in range(bins):
                matrix = [[0j] * predictors for _ in range(predictors)]
                cross = [[0j] * predictors for _ in range(channels_count)]
                for frame_index in range(count):
                    delayed = self._delayed(frames, frame_index, bin_index, enhanced)
                    for left in range(predictors):
                        value = delayed[left]
                        for right in range(left, predictors):
                            product = value * delayed[right].conjugate()
                            matrix[left][right] += product
                            if right != left:
                                matrix[right][left] += product.conjugate()
                        for channel in range(channels_count):
                            cross[channel][left] += (
                                value * enhanced[frame_index][channel][bin_index].conjugate())
                for left in range(predictors):
                    for right in range(predictors):
                        matrix[left][right] *= scale
                    for channel in range(channels_count):
                        cross[channel][left] *= scale
                trace = math.fsum(matrix[index][index].real
                                  for index in range(predictors))
                loading = loading_base * (trace / predictors + 1e-10)
                for index in range(predictors):
                    matrix[index][index] += complex(loading, 0.0)
                statistics.append((matrix, cross))

            gains_per_bin: List[List[List[complex]]] = []
            for matrix, cross in statistics:
                solved: List[List[complex]] = []
                for channel in range(channels_count):
                    gain = _solve_complex(matrix, cross[channel])
                    if gain is None:
                        self.singular_solves += 1
                        gain = [0j] * predictors
                    solved.append(gain)
                gains_per_bin.append(solved)

            updated: List[Tuple[Tuple[complex, ...], ...]] = []
            for frame_index in range(count):
                predictions: List[List[complex]] = [[] for _ in range(channels_count)]
                for bin_index in range(bins):
                    delayed = self._delayed(frames, frame_index, bin_index, enhanced)
                    solved = gains_per_bin[bin_index]
                    for channel in range(channels_count):
                        predictions[channel].append(_csum(
                            solved[channel][index].conjugate() * delayed[index]
                            for index in range(predictors)))
                beta = [1.0] * channels_count
                if cap < 1.0:
                    for channel in range(channels_count):
                        predicted_time = scorer._fft(
                            self._one_sided_to_full(predictions[channel]), inverse=True)
                        predicted_energy = math.fsum(
                            (predicted_time[index].real * window[index]) ** 2
                            for index in range(size))
                        input_energy = input_energies[frame_index][channel]
                        if predicted_energy > cap * input_energy and predicted_energy > 1e-20:
                            beta[channel] = math.sqrt(cap * input_energy / predicted_energy)
                            self.capped_frames += 1
                updated.append(tuple(
                    tuple(frames[frame_index][channel][bin_index]
                          - beta[channel] * predictions[channel][bin_index]
                          for bin_index in range(bins))
                    for channel in range(channels_count)))
            enhanced = tuple(updated)

        ola_length = count * hop + size + 1
        accumulators = [[0.0] * ola_length for _ in range(channels_count)]
        weights = [[0.0] * ola_length for _ in range(channels_count)]
        for frame_index in range(count):
            for channel in range(channels_count):
                reconstructed = scorer._fft(
                    self._one_sided_to_full(enhanced[frame_index][channel]), inverse=True)
                offset = frame_index * hop
                for index in range(size):
                    contribution = reconstructed[index].real * window[index]
                    accumulators[channel][offset + index] += contribution
                    weights[channel][offset + index] += window[index] * window[index]
        outputs: List[Tuple[float, ...]] = []
        limit = float(config["max_abs_input"])
        for channel in range(channels_count):
            values: List[float] = []
            for position in range(len(channels[channel])):
                index = position + BIAS_SAMPLES
                denominator = weights[channel][index]
                if denominator <= 1e-15:
                    raise ArithmeticError("missing_ola_weight")
                value = accumulators[channel][index] / denominator
                if not math.isfinite(value):
                    raise ArithmeticError("nonfinite_ola_output")
                values.append(max(-limit, min(limit, value)))
            outputs.append(tuple(values))
        return tuple(outputs)


def process_whole_clip(channels: Sequence[Sequence[float]], config: Optional[Dict[str, Any]] = None
                       ) -> Tuple[Status, Tuple[Tuple[float, ...], ...]]:
    status, controller = OfflineController.create(config)
    if status is not Status.OK or controller is None:
        return status, tuple()
    fed = controller.process(channels, final=True)
    if fed.status is not Status.OK:
        return fed.status, tuple()
    finished = controller.finish()
    return finished.status, finished.samples


def process_chunked(chunks: Sequence[Sequence[Sequence[float]]],
                    config: Optional[Dict[str, Any]] = None
                    ) -> Tuple[Status, Tuple[Tuple[float, ...], ...]]:
    """Buffer multiple opt-in chunks, then run one whole-clip estimate."""
    status, controller = OfflineController.create(config)
    if status is not Status.OK or controller is None:
        return status, tuple()
    fed = _feed(controller, chunks)
    if fed is not Status.OK:
        return fed, tuple()
    finished = controller.finish()
    return finished.status, finished.samples


def no_reference_suppressor(channels: Sequence[Sequence[float]]
                            ) -> Tuple[Tuple[float, ...], ...]:
    """Deterministic reference-free magnitude-floor suppressor control.

    Unlike the WPE candidate, this control never receives a clean/early
    reference, RIR or WPE coefficient. It derives one low-quantile magnitude
    floor per frequency bin and channel from the observed waveform alone, then
    applies a bounded multiplicative gain (``gate`` when the bin sits at the
    floor, approaching unity for strong bins). Whole-clip estimation makes it
    noncausal; no real-time or quality claim is made.
    """
    tensors = tuple(tuple(float(value) for value in channel) for channel in channels)
    if len(tensors) != CHANNELS:
        raise ValueError("channel_count_mismatch")
    if not tensors[0] or any(len(channel) != len(tensors[0]) for channel in tensors):
        raise ValueError("shape_mismatch")
    if any(not math.isfinite(value) for channel in tensors for value in channel):
        raise ArithmeticError("nonfinite_input")
    if any(abs(value) > float(DEFAULT_CONFIG["max_abs_input"])
           for channel in tensors for value in channel):
        raise ValueError("input_out_of_range")

    engine = OfflineWpe.create(DEFAULT_CONFIG)
    frames = engine._stft(tensors)
    size = int(DEFAULT_CONFIG["fft_size"])
    window = _sqrt_hann(size)
    bins = engine.bins
    floors: List[List[float]] = []
    for channel in range(CHANNELS):
        channel_floors: List[float] = []
        for bin_index in range(bins):
            magnitudes = sorted(abs(frame[channel][bin_index]) for frame in frames)
            position = min(len(magnitudes) - 1,
                           max(0, int(NO_REF_SUPPRESSOR_QUANTILE * (len(magnitudes) - 1))))
            channel_floors.append(magnitudes[position])
        floors.append(channel_floors)

    shaped: List[Tuple[List[complex], ...]] = []
    for frame in frames:
        row: List[List[complex]] = []
        for channel in range(CHANNELS):
            bins_out: List[complex] = []
            for bin_index in range(bins):
                value = frame[channel][bin_index]
                magnitude = abs(value)
                ratio = (NO_REF_SUPPRESSOR_ALPHA * floors[channel][bin_index]
                         / (magnitude + 1e-12))
                gain = max(NO_REF_SUPPRESSOR_GATE, 1.0 - ratio)
                bins_out.append(value * gain)
            row.append(bins_out)
        shaped.append(tuple(row))

    ola_length = len(frames) * HOP_SAMPLES + size + 1
    accumulators = [[0.0] * ola_length for _ in range(CHANNELS)]
    weights = [0.0] * ola_length
    for frame_index, frame in enumerate(shaped):
        for channel in range(CHANNELS):
            reconstructed = scorer._fft(
                OfflineWpe._one_sided_to_full(frame[channel]), inverse=True)
            offset = frame_index * HOP_SAMPLES
            for index in range(size):
                accumulators[channel][offset + index] += (
                    reconstructed[index].real * window[index])
                weights[offset + index] += window[index] * window[index]

    limit = float(DEFAULT_CONFIG["max_abs_input"])
    output: List[Tuple[float, ...]] = []
    for channel in range(CHANNELS):
        values: List[float] = []
        for position in range(len(tensors[channel])):
            index = position + BIAS_SAMPLES
            denominator = weights[index]
            if denominator <= 1e-15:
                raise ArithmeticError("missing_ola_weight")
            value = accumulators[channel][index] / denominator
            if not math.isfinite(value):
                raise ArithmeticError("nonfinite_ola_output")
            values.append(max(-limit, min(limit, value)))
        output.append(tuple(values))
    return tuple(output)


@dataclass
class ControllerState:
    first_input_sample: int = 0
    input_samples: int = 0
    epoch: int = 1
    invalid_count: int = 0
    chunks: int = 0
    finished: bool = False
    closed: bool = False
    final_frame_received: bool = False
    final_sample_count: Optional[int] = None
    buffer: Tuple[Tuple[float, ...], ...] = ()


@dataclass
class ProcessResult:
    status: Status
    samples: Tuple[Tuple[float, ...], ...] = ()
    valid_count: int = 0
    state_digest: str = ""


class OfflineController:
    """Buffers opt-in whole-clip requests; all DSP happens at ``finish``."""

    def __init__(self, config: Optional[Dict[str, Any]] = None, epoch: int = 1,
                 first_input_sample: int = 0) -> None:
        settings = dict(DEFAULT_CONFIG if config is None else config)
        status = validate_config(settings)
        if status is not Status.OK:
            raise ValueError(status.value)
        self.config = settings
        self.state = ControllerState(epoch=epoch,
                                     first_input_sample=first_input_sample)

    @classmethod
    def create(cls, config: Optional[Dict[str, Any]], epoch: int = 1,
               first_input_sample: int = 0) -> Tuple[Status, Optional["OfflineController"]]:
        settings = DEFAULT_CONFIG if config is None else config
        status = validate_config(settings)
        if status is not Status.OK:
            return status, None
        return Status.OK, cls(settings, epoch, first_input_sample)

    def reset(self, epoch: int, first_input_sample: int) -> Status:
        if self.state.closed:
            return Status.CLOSED
        if epoch <= self.state.epoch:
            return Status.REJECTED_EPOCH
        self.state = ControllerState(epoch=epoch,
                                     first_input_sample=first_input_sample)
        return Status.OK

    def close(self) -> None:
        self.state.closed = True

    def dsp_digest(self) -> str:
        return object_digest({
            "buffer": channels_digest(self.state.buffer),
            "input_samples": self.state.input_samples,
            "first_input_sample": self.state.first_input_sample,
            "epoch": self.state.epoch,
            "chunks": self.state.chunks,
            "finished": self.state.finished,
        })

    def digest(self) -> str:
        return object_digest({"dsp_state": self.dsp_digest(),
                              "invalid_count": self.state.invalid_count,
                              "closed": self.state.closed})

    def process(self, chunk: Sequence[Sequence[float]], *, session: Optional[int] = None,
                epoch: Optional[int] = None, first_input_sample: Optional[int] = None,
                final: bool = False) -> ProcessResult:
        state = self.state
        if state.closed:
            return ProcessResult(Status.CLOSED)
        if state.finished or state.final_frame_received:
            state.invalid_count += 1
            return ProcessResult(Status.REJECTED_SESSION)
        if session is not None and session != RESET_SCHEDULE["session_id"]:
            state.invalid_count += 1
            return ProcessResult(Status.REJECTED_SESSION)
        if epoch is not None and epoch != state.epoch:
            state.invalid_count += 1
            return ProcessResult(Status.REJECTED_EPOCH)
        expected = state.first_input_sample + state.input_samples
        if first_input_sample is not None and first_input_sample != expected:
            state.invalid_count += 1
            return ProcessResult(Status.REJECTED_POSITION)
        if (not isinstance(chunk, Sequence) or isinstance(chunk, (str, bytes))
                or len(chunk) != int(self.config["channels"])):
            state.invalid_count += 1
            return ProcessResult(Status.REJECTED_TENSOR)
        lengths = [len(channel) for channel in chunk]
        if (any(length <= 0 or length > MAX_CHUNK_SAMPLES for length in lengths)
                or len(set(lengths)) != 1
                or (lengths[0] != FRAME_SAMPLES and not final)):
            state.invalid_count += 1
            return ProcessResult(Status.REJECTED_TENSOR)
        try:
            values = tuple(tuple(float(value) for value in channel) for channel in chunk)
        except (TypeError, ValueError, OverflowError):
            state.invalid_count += 1
            return ProcessResult(Status.REJECTED_NONFINITE)
        limit = float(self.config["max_abs_input"])
        if any(not math.isfinite(value) for channel in values for value in channel):
            state.invalid_count += 1
            return ProcessResult(Status.REJECTED_NONFINITE)
        if any(abs(value) > limit for channel in values for value in channel):
            state.invalid_count += 1
            return ProcessResult(Status.REJECTED_INVALID)
        buffered = values if not state.buffer else tuple(
            state.buffer[channel] + values[channel]
            for channel in range(int(self.config["channels"])))
        self.state = ControllerState(
            first_input_sample=state.first_input_sample,
            input_samples=state.input_samples + lengths[0],
            epoch=state.epoch, invalid_count=state.invalid_count,
            chunks=state.chunks + 1, final_frame_received=final,
            final_sample_count=lengths[0] if final else None,
            buffer=buffered)
        return ProcessResult(Status.OK, (), lengths[0], self.digest())

    def finish(self, *, session: Optional[int] = None,
               epoch: Optional[int] = None) -> ProcessResult:
        state = self.state
        if state.closed:
            return ProcessResult(Status.CLOSED)
        if state.finished:
            state.invalid_count += 1
            return ProcessResult(Status.REJECTED_SESSION)
        if session is not None and session != RESET_SCHEDULE["session_id"]:
            state.invalid_count += 1
            return ProcessResult(Status.REJECTED_SESSION)
        if epoch is not None and epoch != state.epoch:
            state.invalid_count += 1
            return ProcessResult(Status.REJECTED_EPOCH)
        if not state.buffer or not state.final_frame_received:
            state.invalid_count += 1
            return ProcessResult(Status.REJECTED_SESSION)
        engine = OfflineWpe.create(self.config)
        try:
            output = engine.process(state.buffer)
        except (ArithmeticError, ValueError):
            state.invalid_count += 1
            return ProcessResult(Status.REJECTED_NONFINITE)
        self.state = ControllerState(
            first_input_sample=state.first_input_sample,
            input_samples=state.input_samples,
            epoch=state.epoch, invalid_count=state.invalid_count,
            chunks=state.chunks, finished=True,
            final_frame_received=state.final_frame_received,
            final_sample_count=state.final_sample_count,
            buffer=state.buffer)
        return ProcessResult(Status.OK, output, state.input_samples, self.digest())


