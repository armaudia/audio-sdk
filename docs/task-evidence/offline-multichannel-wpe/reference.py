def _round(value: Optional[float]) -> Optional[float]:
    return None if value is None else round(value, 6)


def _min_defined(values: Sequence[Optional[float]]) -> Optional[float]:
    defined = [value for value in values if value is not None]
    return min(defined) if defined else None


def _metrics(reference: Optional[Sequence[Sequence[float]]],
             output: Optional[Sequence[Sequence[float]]],
             raw: Optional[Sequence[Sequence[float]]],
             paired_baseline: bool = True) -> Dict[str, Any]:
    """Paired per-channel scores; a missing score is never a candidate result.

    ``paired_baseline=False`` is used only for the clean near-end control where
    the raw input is already the clean reference, making a paired identity
    delta undefined by construction (not a missing candidate result).
    """
    blocked = {"status": "blocked", "metrics": None,
               "excluded_from_qualification": True}
    if reference is None:
        return {**blocked, "reason": "missing_reference"}
    if output is None:
        return {**blocked, "reason": "missing_output"}
    reference = tuple(tuple(channel) for channel in reference)
    output = tuple(tuple(channel) for channel in output)
    raw_values = tuple(tuple(channel) for channel in raw) if raw is not None else output
    if (len(reference) != CHANNELS or len(output) != CHANNELS
            or len(raw_values) != CHANNELS
            or any(len(channel) != len(reference[0]) for channel in (*output, *raw_values))):
        return {**blocked, "status": "failed", "reason": "shape_mismatch"}
    if any(not math.isfinite(value) for channel in output for value in channel):
        return {**blocked, "status": "failed", "reason": "nonfinite_output"}
    if any(not math.isfinite(value) for channel in reference for value in channel):
        return {**blocked, "reason": "nonfinite_reference"}
    per_channel: List[Dict[str, Any]] = []
    reasons: List[Optional[str]] = []
    for channel in range(CHANNELS):
        si, si_reason = scorer.si_sdr(reference[channel], output[channel])
        stoi_value, stoi_reason = scorer.stoi(reference[channel], output[channel])
        if paired_baseline:
            si_raw, si_raw_reason = scorer.si_sdr(reference[channel], raw_values[channel])
            stoi_raw, stoi_raw_reason = scorer.stoi(reference[channel], raw_values[channel])
            reasons.extend((si_raw_reason, stoi_raw_reason))
        else:
            si_raw = stoi_raw = si_raw_reason = stoi_raw_reason = None
        reasons.extend((si_reason, stoi_reason))
        delta_si = None if (si_reason or si_raw_reason or si is None or si_raw is None) else si - si_raw
        delta_stoi = None if (stoi_reason or stoi_raw_reason or stoi_value is None
                              or stoi_raw is None) else stoi_value - stoi_raw
        per_channel.append({
            "channel": channel,
            "si_sdr_db": _round(si),
            "stoi": _round(stoi_value),
            "identity_si_sdr_db": _round(si_raw),
            "identity_stoi": _round(stoi_raw),
            "delta_si_sdr_db": _round(delta_si),
            "delta_stoi": _round(delta_stoi),
        })
    if any(reasons):
        return {**blocked, "reason": next(reason for reason in reasons if reason)}
    primary = per_channel[0]
    metrics = {
        "aggregation": "primary_channel_0_with_worst_channel_reported",
        "si_sdr_db": primary["si_sdr_db"],
        "stoi": primary["stoi"],
        "identity_si_sdr_db": primary["identity_si_sdr_db"],
        "identity_stoi": primary["identity_stoi"],
        "delta_si_sdr_db": primary["delta_si_sdr_db"],
        "delta_stoi": primary["delta_stoi"],
        "worst_channel_si_sdr_db": _round(_min_defined(
            [row["si_sdr_db"] for row in per_channel])),
        "worst_channel_stoi": _round(_min_defined(
            [row["stoi"] for row in per_channel])),
        "worst_channel_delta_si_sdr_db": _round(_min_defined(
            [row["delta_si_sdr_db"] for row in per_channel])),
        "worst_channel_delta_stoi": _round(_min_defined(
            [row["delta_stoi"] for row in per_channel])),
        "per_channel": per_channel,
        "baseline_note": ("paired identity baseline included"
                          if paired_baseline else
                          "clean reference is the raw input; identity delta is undefined"),
    }
    return {
        "status": "scored", "reason": None,
        "excluded_from_qualification": False, "metrics": metrics,
        "peak_abs": _round(max(abs(value) for channel in output for value in channel)),
        "nonfinite_count": sum(1 for channel in output for value in channel
                               if not math.isfinite(value)),
        "clipping_count": sum(1 for channel in output for value in channel if abs(value) > 1.0),
        "output_digest": channels_digest(output),
    }


