def probe_channels() -> Tuple[Tuple[float, ...], ...]:
    """Short pinned two-channel reverberant probe for OFF/ON and repeats."""
    rirs = room_rirs("short_rt60")
    unscaled = convolve_channels(clean_source(), rirs)
    peak = max(abs(value) for channel in unscaled for value in channel)
    gain = min(1.0, 0.9 / peak) if peak > 0 else 1.0
    limit = FRAME_SAMPLES * 6
    return tuple(tuple(value * gain for value in channel[:limit]) for channel in unscaled)


def _feed(controller: OfflineController, chunks: Sequence[Sequence[Sequence[float]]],
          **kwargs: Any) -> Status:
    status = Status.OK
    for index, chunk in enumerate(chunks):
        status = controller.process(chunk, final=index == len(chunks) - 1, **kwargs).status
        if status is not Status.OK:
            break
    return status


def _chunks_of(channels: Sequence[Sequence[float]], sizes: Sequence[int]
               ) -> List[Tuple[Tuple[float, ...], ...]]:
    result: List[Tuple[Tuple[float, ...], ...]] = []
    cursor = 0
    for size in sizes:
        result.append(tuple(tuple(channel[cursor:cursor + size]) for channel in channels))
        cursor += size
    if cursor != len(channels[0]):
        raise ValueError("chunk schedule does not cover the clip")
    return result


