"""Regenerate the canonical report, digest sidecar and C parity header."""

from __future__ import annotations

import argparse
from pathlib import Path

import reference

TASK_DIR = Path(__file__).resolve().parent
REPORT_FILE = TASK_DIR / "report.json"
SIDECAR_FILE = TASK_DIR / "report.json.sha256"
HEADER_FILE = TASK_DIR / "provider" / "expected_vectors.h"


def header_text(expected: dict) -> str:
    lines = [
        "/* SPDX-FileCopyrightText: 2026 Tsakanyan Hovhannes",
        " * SPDX" "-License-Identifier: Apache-2.0",
        " */",
        "/* Generated by run.py from the deterministic Python model. Do not edit. */",
        '#ifndef SPEEX_NS_ADVISORY_EXPECTED_VECTORS_H',
        '#define SPEEX_NS_ADVISORY_EXPECTED_VECTORS_H',
        '',
        f'#define EXPECTED_PROVIDER_ID "{reference.PROVIDER_ID}"',
        f'#define EXPECTED_STIMULUS_LENGTH {expected["stimulus_length"]}u',
        f'#define EXPECTED_FRAME_COUNT {expected["frame_count"]}u',
        f'#define EXPECTED_WINDOW_SAMPLES {expected["window_samples"]}u',
        f'#define EXPECTED_EVENT_COUNT {expected["event_count"]}u',
        f'#define EXPECTED_REPEATS {expected["repeats"]}u',
        f'#define EXPECTED_PCM_BYTE_COUNT {expected["pcm_byte_count"]}u',
        f'#define EXPECTED_PCM_DIGEST "{expected["pcm_digest"]}"',
        f'#define EXPECTED_EVENT_HOP0_DIGEST "{expected["event_hop0_digest"]}"',
        f'#define EXPECTED_EVENT_HOP1_DIGEST "{expected["event_hop1_digest"]}"',
        f'#define EXPECTED_EVENT_HOP0_BINARY_DIGEST "{expected["event_hop0_binary_digest"]}"',
        f'#define EXPECTED_EVENT_HOP1_BINARY_DIGEST "{expected["event_hop1_binary_digest"]}"',
        f'#define EXPECTED_PROVIDER_SOURCE_DIGEST "{expected["provider_source_digest"]}"',
        f'#define EXPECTED_CONFIG_DIGEST "{expected["config_digest"]}"',
        f'#define EXPECTED_NOISE_FLOOR {reference.NOISE_FLOOR}ull',
        f'#define EXPECTED_PROBABILITY_SPAN {reference.PROBABILITY_SPAN}ull',
        f'#define ADVISORY_THRESHOLD_MILLI {reference.THRESHOLD_MILLI}u',
        '',
        '#endif /* SPEEX_NS_ADVISORY_EXPECTED_VECTORS_H */',
        '',
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--report", action="store_true",
                        help="write report.json, its digest sidecar and the C parity header")
    options = parser.parse_args()

    report = reference.build_report()
    text, digest = reference.canonical_report(report)
    if options.report:
        REPORT_FILE.write_bytes((text + "\n").encode("utf-8"))
        SIDECAR_FILE.write_text(digest + "\n", encoding="ascii")
        HEADER_FILE.write_text(header_text(report["c_boundary_expected"]), encoding="utf-8")
    print(f"report_digest={digest}")
    print(f"report_file_digest={reference.sha256_hex((text + chr(10)).encode('utf-8'))}")
    print(f"pcm_digest={report['c_boundary_expected']['pcm_digest']}")
    print(f"event_hop0_digest={report['c_boundary_expected']['event_hop0_digest']}")
    print(f"all_controls_pass={report['all_controls_pass']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
