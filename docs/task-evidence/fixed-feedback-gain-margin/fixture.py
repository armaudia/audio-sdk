def feedback_trial(config: Dict[str, Any], program: Sequence[float],
                   path: Dict[str, Any], loop_gain: float,
                   nonlinearity: str) -> Dict[str, Any]:
    """Frame-causal recursive trial on an explicit synthetic FIR feedback path."""
    ir = path["ir"]
    delay_frames = int(path["delay_frames"])
    fine = int(path["fine_delay_samples"])
    delay = int(path["delay_samples"])
    # Frame-causal history: only completed output frames feed the next input.
    history_size = delay_frames + len(ir) + 2
    history: List[Tuple[float, ...]] = [
        (0.0,) * FRAME_SAMPLES for _ in range(history_size)]
    feedback_blocks: List[Tuple[float, float]] = []
    output: List[float] = []
    pre_threshold = 0.8
    post_ceiling = 0.8
    rejected = 0
    nonfinite = 0
    clipped = 0
    controller = FixedMarginController(config)
    seed_frames = 40
    speech_frames = 200
    total_frames = len(program) // FRAME_SAMPLES

    for frame_index, source in enumerate(frames_of(program)):
        mic: List[float] = []
        feedback_rms_square = 0.0
        for offset, sample in enumerate(source):
            total = 0.0
            for tap, coefficient in enumerate(ir):
                delayed = history[len(history) - 1 - delay_frames - tap]
                position = offset - fine
                if position >= 0:
                    returned = delayed[position]
                else:
                    older = history[len(history) - 2 - delay_frames - tap]
                    returned = older[position + FRAME_SAMPLES]
                total += coefficient * returned
            feedback = loop_gain * total
            feedback_rms_square += feedback * feedback
            value = sample + feedback
            if nonlinearity == "pre_tanh":
                value = pre_threshold * math.tanh(value / pre_threshold)
            mic.append(value)
        feedback_blocks.append((feedback_rms_square / FRAME_SAMPLES,
                                frame_index))

        result = controller.process(
            tuple(mic), epoch=7, first_input_sample=frame_index * FRAME_SAMPLES)
        if result.status is not Status.OK:
            rejected += 1
            playback = (0.0,) * FRAME_SAMPLES
        else:
            playback = result.samples
        if nonlinearity == "post_clip":
            playback = tuple(max(-post_ceiling, min(post_ceiling, value))
                             for value in playback)
            clipped += sum(1 for value in playback if abs(value) >= post_ceiling)
        output.extend(playback)
        history = history[1:] + [tuple(playback)]
        nonfinite += sum(1 for value in playback if not math.isfinite(value))

    def block_rms(start: int, end: int) -> float:
        total = sum(power for power, index in feedback_blocks if start <= index < end)
        return math.sqrt(total / max(end - start, 1))

    speech_start = seed_frames * FRAME_SAMPLES
    speech_end = (seed_frames + speech_frames) * FRAME_SAMPLES
    speech_rms = rms(program[speech_start:speech_end])
    tail = output[speech_end:]
    tail_db = db(rms(tail) / max(speech_rms, 1e-30))
    tail_early = rms(output[(seed_frames + speech_frames) * FRAME_SAMPLES:
                            (seed_frames + speech_frames + 50) * FRAME_SAMPLES])
    tail_late = rms(output[-50 * FRAME_SAMPLES:])
    tail_decay_db = db(tail_late / max(tail_early, 1e-30))
    growth_db = db(block_rms(seed_frames + speech_frames, total_frames)
                   / max(block_rms(0, seed_frames), 1e-30))
    if rejected:
        stability_class = "rejected_frames_fail_closed"
    elif nonfinite:
        stability_class = "nonfinite_failure"
    elif tail_decay_db > -3.0:
        stability_class = "sustained_feedback_proxy"
    elif tail_decay_db > -12.0:
        stability_class = "decaying_proxy"
    else:
        stability_class = "decayed_proxy"

    row: Dict[str, Any] = {
        "status": "ok" if rejected == 0 and nonfinite == 0 else "fail_closed",
        "gain_db": float(config["gain_db"]),
        "path": path["id"],
        "loop_gain": loop_gain,
        "nonlinearity": nonlinearity,
        "delay_samples": delay,
        "tail_db_relative_to_program": round(tail_db, 3),
        "tail_decay_db": round(tail_decay_db, 3),
        "tail_mean": round(sum(tail) / max(len(tail), 1), 6),
        "feedback_growth_db": round(growth_db, 3),
        "program_sdr_db": round(
            sdr_db(program[speech_start:speech_end], output[speech_start:speech_end]), 3),
        "peak_abs_output": round(peak(output), 6),
        "nonfinite_samples": nonfinite,
        "rejected_frames": rejected,
        "clipped_samples": clipped,
        "stability_class": stability_class,
        "output_digest": tensor_digest(output),
    }
    row["missing_results"] = sorted(
        key for key in REQUIRED_LOOP_METRICS
        if key not in row or not _present(row[key]))
    return row


def _present(value: Any) -> bool:
    if value is None:
        return False
    if isinstance(value, str):
        return bool(value)
    if isinstance(value, (int, float)) and not isinstance(value, bool):
        return math.isfinite(float(value))
    return True


def candidate_eligible(rows: Sequence[Dict[str, Any]], release_gates: Sequence[str]
                       ) -> Dict[str, Any]:
    """No missing result may qualify a candidate; release gates are separate."""
    missing = sorted({
        "%s/%s" % (row.get("case", "?"), key)
        for row in rows
        for key in (row["missing_results"] if "missing_results" in row
                    else REQUIRED_LOOP_METRICS)
    })
    return {
        "all_results_present": not missing,
        "missing_results": missing,
        "release_gates_open": list(release_gates),
        "eligible_for_selection": not missing and not release_gates,
    }


