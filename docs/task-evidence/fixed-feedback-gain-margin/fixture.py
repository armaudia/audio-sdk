def target_aligned_ir(frequency_hz: int) -> Tuple[float, ...]:
    """Three-tap symmetric FIR with unity real gain at ``frequency_hz``.

    The symmetric FIR has one sample of group delay. The path bulk delay is
    chosen so bulk delay + group delay is a whole number of target periods;
    that makes the target frequency a positive-feedback phase point.
    """
    omega = 2.0 * math.pi * frequency_hz / SAMPLE_RATE_HZ
    raw = (0.5, 1.0, 0.5)
    at_target = sum(raw[k] * math.cos(omega * k) for k in range(len(raw)))
    return tuple(value / at_target for value in raw)


