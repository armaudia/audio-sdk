"""Reproduce the canonical sanitizer/fuzz qualification matrix report.

Usage from this directory with the pinned interpreter:

    PYTHONDONTWRITEBYTECODE=1 python3 run.py report.json

The report is regenerated byte-for-byte from frozen inputs and a SHA-256
sidecar is written beside it. No network, SDK build or instrumented run occurs.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from fixture import build_report, canonical_report_bytes, file_digest


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("report", type=Path, help="path of report.json to write")
    options = parser.parse_args()

    report = build_report()
    options.report.write_bytes(canonical_report_bytes(report))
    sidecar = options.report.parent / f"{options.report.name}.sha256"
    sidecar.write_text(
        f"{file_digest(options.report)}  {options.report.name}\n",
        encoding="utf-8")
    print(f"report_sha256={file_digest(options.report)}")
    print(
        f"qualification_status={report['qualification_status']} "
        f"status={report['status']} "
        f"controls_all_pass={report['controls']['controls_all_pass']} "
        f"qualified_rows={len(report['qualification_matrix']['qualified_rows'])}"
    )


if __name__ == "__main__":
    main()
