"""Strict read-only verifier for the FastEnhancer Medium reference package.

Checks canonical bytes, duplicate-key-free/finite JSON, exact pins, the stable
linked-row identity (never the mutable full board), three cold-start
regenerations, fail-closed admission, licensing, task-local git scope and the
eight blocked release gates. It never writes package evidence.
"""

from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path
from typing import Any, Dict, List

import reference

HERE = Path(__file__).resolve().parent
REPORT = HERE / "report.json"
SIDECAR = HERE / "report.json.sha256"
PIN_MANIFEST = HERE / "SOURCES.sha256"
CONTRACT = HERE / "contract.json"
LICENSE_SIDECARS = (
    "contract.json.license",
    "report.json.license",
    "report.json.sha256.license",
    "SOURCES.sha256.license",
)
REQUIRED_KEYS = {
    "schema_id", "task", "title", "component", "reference_family", "repository",
    "base_commit", "branch", "profile", "status", "evidence_status",
    "qualification_status", "decision", "defer_before",
    "no_missing_result_qualifies_candidate", "qualification", "boundary",
    "format", "task_geometry", "source_pins", "boundary_pins", "artifact_pins",
    "board_link_fields", "board_links", "board_link_projection_sha256",
    "board_mutable_fields_excluded", "acceptance_profile", "required_results",
    "asset", "asset_identity", "asset_admission", "sdk_worktree_asset_probe",
    "runtime", "feasibility", "reference", "candidates", "controls", "harness",
    "adverse", "missing_result", "repeatability", "regressions", "gates",
    "remaining_gates", "independent_timing_evidence", "rights_gap",
    "missing_evidence", "non_claims", "negative_claims", "evidence_classes",
}
GATE_IDS = ["RG-0" + str(number) for number in range(1, 9)]
PROHIBITED_SUFFIXES = {
    ".wav", ".flac", ".mp3", ".ogg", ".opus", ".onnx", ".q8", ".pt", ".pth",
    ".ckpt", ".safetensors", ".bin", ".so", ".dylib", ".a", ".o", ".zip",
    ".tar", ".gz", ".whl",
}


def fail(errors: List[str], message: str) -> None:
    errors.append(message)


def check_file_set(errors: List[str]) -> None:
    actual = sorted(path.name for path in HERE.iterdir() if path.is_file())
    expected = sorted(reference.EXPECTED_FILES)
    if actual != expected:
        missing = sorted(set(expected) - set(actual))
        extra = sorted(set(actual) - set(expected))
        fail(errors, f"unexpected package file set missing={missing} extra={extra}")
    for path in sorted(HERE.iterdir()):
        if path.is_file() and path.suffix.lower() in PROHIBITED_SUFFIXES:
            fail(errors, "prohibited binary/artifact file present: " + path.name)


def check_pins(errors: List[str]) -> int:
    try:
        text = PIN_MANIFEST.read_text(encoding="utf-8")
    except OSError as error:
        fail(errors, "pin manifest unreadable: " + str(error))
        return 0
    try:
        pins = reference.parse_pin_lines(text)
    except ValueError as error:
        fail(errors, "strict pin rejection: " + str(error))
        return 0
    if PIN_MANIFEST.read_bytes() != reference.sources_bytes():
        fail(errors, "SOURCES.sha256 is not deterministic generated bytes")
    for digest, raw in pins:
        path = reference.pin_path(raw)
        if not path.is_file():
            fail(errors, "pinned file missing: " + raw)
            continue
        if reference.sha256(path.read_bytes()) != digest:
            fail(errors, "pinned bytes changed: " + raw)
    if any("TASKS.json" in raw for _, raw in pins):
        fail(errors, "the mutable full TASKS.json must not be pinned")
    return len(pins)


def check_json(errors: List[str]) -> Dict[str, Any]:
    payloads: Dict[str, Any] = {}
    for name, path in (("report", REPORT), ("contract", CONTRACT)):
        try:
            payloads[name] = reference.strict_json(path)
        except (OSError, ValueError) as error:
            fail(errors, f"strict JSON failed for {name}: {error}")
            return {}
    report = payloads["report"]
    if not REQUIRED_KEYS <= set(report):
        fail(errors, "report missing keys: " + ", ".join(sorted(REQUIRED_KEYS - set(report))))
        return payloads
    if REPORT.read_bytes() != reference.canonical_report_bytes(report):
        fail(errors, "report.json is not canonical byte output")
    expected_sidecar = reference.sha256(REPORT.read_bytes()) + "  report.json\n"
    if SIDECAR.read_text(encoding="utf-8") != expected_sidecar:
        fail(errors, "report.json.sha256 is stale")
    if CONTRACT.read_bytes() != reference.contract_bytes():
        fail(errors, "contract.json is not current canonical bytes")
    return payloads


def check_report_content(errors: List[str], report: Dict[str, Any],
                         contract: Dict[str, Any]) -> None:
    if report.get("task") != reference.TASK:
        fail(errors, "task identity mismatch")
    if report.get("base_commit") != reference.BASE_COMMIT:
        fail(errors, "base_commit mismatch")
    if report.get("branch") != reference.BRANCH:
        fail(errors, "branch mismatch")
    if report.get("profile") != reference.PROFILE:
        fail(errors, "enhancement profile not recorded")
    if contract.get("verification_profile") != "enhancement":
        fail(errors, "contract does not record the enhancement profile")
    if report.get("status") != reference.STATUS or report.get("evidence_status") != "incomplete":
        fail(errors, "status is not proposal-only/incomplete")
    if report.get("qualification_status") != "not_qualified":
        fail(errors, "top-level qualification_status is not not_qualified")
    if report.get("decision") != "DEFER" or contract.get("decision") != "DEFER":
        fail(errors, "decision is not DEFER")
    if report.get("defer_before") != "processor_exposure":
        fail(errors, "defer_before is not processor_exposure")
    qualification = report.get("qualification", {})
    if qualification.get("status") != "not_qualified":
        fail(errors, "qualification.status is not not_qualified")
    if qualification.get("qualifies_candidate") is not False:
        fail(errors, "qualification qualifies a candidate")
    if qualification.get("missing_result_promoted") is not False:
        fail(errors, "missing result was promoted")
    if report.get("no_missing_result_qualifies_candidate") is not True:
        fail(errors, "missing-result invariant missing")

    boundary = report.get("boundary", {})
    for key in (
        "registered", "enabled_by_default", "default_selected", "public_api_abi_change",
        "provider_registration", "processor_exposure", "c_public_boundary",
        "installed_v0_behavior_changed", "descriptor_or_registry_change",
        "shared_build_or_ci_change", "task_board_or_handoff_change",
        "real_corpus_or_weights_included",
    ):
        if boundary.get(key) is not False:
            fail(errors, "boundary is not fail-closed: " + key)
    if boundary.get("descriptor_settings") != {}:
        fail(errors, "descriptor_settings is not empty")
    if boundary.get("installed_v0_geometry_preserved") is not True:
        fail(errors, "installed v0 geometry preservation missing")

    fmt = report.get("format", {})
    expected_format = {
        "sample_rate_hz": 16000,
        "channels": 1,
        "sample_format": "f32",
        "frame_samples": 160,
        "hop_samples": 160,
        "content_delay_samples": 0,
    }
    for key, value in expected_format.items():
        if fmt.get(key) != value:
            fail(errors, "v0 geometry mismatch: " + key)
    if fmt.get("installed_v0_geometry_preserved") is not True:
        fail(errors, "format does not preserve installed v0 geometry")

    geometry = report.get("task_geometry", {})
    if geometry.get("native", {}).get("sample_rate_hz") != 48000:
        fail(errors, "native geometry rate is not 48000")
    if geometry.get("native", {}).get("analysis_chunk_samples") != 480:
        fail(errors, "native analysis chunk is not 480")
    if geometry.get("delay", {}).get("sdk_declared_samples") != 235:
        fail(errors, "declared SDK delay is not 235")
    if geometry.get("delay", {}).get("native_samples") != 704:
        fail(errors, "native delay is not 704")
    if geometry.get("execution_modes") != [2, 3]:
        fail(errors, "execution modes are not [2, 3]")
    if geometry.get("callback_safe") is not False:
        fail(errors, "callback_safe is not false")

    asset = report.get("asset", {})
    expected_asset = {
        "asset_id": "fe.q8",
        "byte_count": 565108,
        "sha256": "d6f98e186bee6ed655b52a2edf5f707ccf761c755bb69de8de7f68cad42d7837",
        "git_blob": "ab6f8c711d3e23ace911c5e1e11203fadd43ca19",
        "source_revision": "3e2446fc58886fc02b099b54651adc9a10a65454",
    }
    for key, value in expected_asset.items():
        if asset.get(key) != value:
            fail(errors, "asset identity mismatch: " + key)
    if asset.get("present_in_sdk_worktree") is not False:
        fail(errors, "asset is claimed present in the SDK worktree")
    if asset.get("bytes_read_by_this_package") is not False:
        fail(errors, "asset bytes are claimed read")
    if asset.get("download_attempted") is not False:
        fail(errors, "download was attempted")
    if asset.get("redistribution") != "unknown":
        fail(errors, "asset redistribution is not recorded as unknown")

    admission = report.get("asset_admission", {})
    if admission.get("status") != "blocked" or admission.get("all_rejections_fail_closed") is not True:
        fail(errors, "asset admission is not blocked/fail-closed")
    if admission.get("admission_mechanism_verified_with_synthetic_spec") is not True:
        fail(errors, "asset admission mechanism was not verified")

    probe = report.get("sdk_worktree_asset_probe", {})
    if probe.get("present") is not False or probe.get("found") != []:
        fail(errors, "an exact weight asset is present in the SDK worktree")

    runtime = report.get("runtime", {})
    for key in (
        "present_in_sdk_worktree", "sdk_consumable_runtime_present",
        "onnx_medium_model_present", "native_simd_backend_present_in_sdk_worktree",
        "scalar_runtime_tier_available", "vendor_runtime_invoked",
    ):
        if runtime.get(key) is not False:
            fail(errors, "runtime state is not absent/fail-closed: " + key)

    feasibility = report.get("feasibility", {})
    if feasibility.get("verdict") != "blocked" or feasibility.get("decision") != "DEFER":
        fail(errors, "feasibility is not blocked/DEFER")
    if feasibility.get("can_produce_exact_sdk_reference") is not False:
        fail(errors, "feasibility claims an exact SDK reference is possible")
    conjuncts = feasibility.get("conjuncts", {})
    for key in ("weights_redistribution_cleared", "runtime_present_for_sdk",
                "runtime_pinned_for_sdk", "rights_cleared_for_redistribution"):
        if conjuncts.get(key) is not False:
            fail(errors, "feasibility conjunct is not blocked: " + key)

    reference_record = report.get("reference", {})
    for key in ("model_weights", "real_model_inference", "upstream_parity",
                "runtime_invoked", "candidate_output_produced", "downloads"):
        if reference_record.get(key) is not False:
            fail(errors, "reference claims a prohibited capability: " + key)
    if reference_record.get("deterministic") is not True:
        fail(errors, "reference is not deterministic")

    candidate = report.get("candidates", {}).get("fastenhancer_medium", {})
    if candidate.get("status") != "blocked_assets_and_runtime_absent":
        fail(errors, "candidate is not blocked")
    if candidate.get("metrics") is not None or candidate.get("qualifies_candidate") is not False:
        fail(errors, "candidate produced metrics or qualifies")
    if candidate.get("candidate_output") is not False:
        fail(errors, "candidate claims an output")

    missing = report.get("missing_result", {})
    if missing.get("status") != "blocked" or missing.get("metrics") is not None:
        fail(errors, "missing result is not blocked/null")
    if missing.get("qualifies_candidate") is not False:
        fail(errors, "missing result qualifies the candidate")

    adverse = report.get("adverse", {})
    requests = adverse.get("invalid_requests", {})
    if requests.get("accepted_count") != 0 or requests.get("all_rejected") is not True:
        fail(errors, "invalid requests were accepted")
    for item in requests.get("cases", []):
        if item.get("accepted") is not False or item.get("matches") is not True:
            fail(errors, "invalid request case did not fail closed: " + str(item.get("id")))
    json_cases = adverse.get("invalid_json", {})
    if json_cases.get("accepted_count") != 0 or json_cases.get("all_rejected") is not True:
        fail(errors, "invalid JSON was accepted")
    lifecycle = adverse.get("lifecycle", {})
    for key in ("closed_process", "finished_process", "stale_reset_epoch", "stale_reset_position"):
        if not str(lifecycle.get(key, "")).startswith("rejected"):
            fail(errors, "lifecycle case did not fail closed: " + key)
    if lifecycle.get("valid_reset") != "ok":
        fail(errors, "valid reset was rejected")
    if lifecycle.get("invalid_never_advances_state") is not True:
        fail(errors, "invalid lifecycle advanced state")

    harness = report.get("harness", {})
    if len(harness.get("stimuli", {})) != len(reference.STIMULUS_NAMES):
        fail(errors, "harness stimulus set is incomplete")
    identity = harness.get("identity_control", {})
    if identity.get("all_byte_identical") is not True or identity.get("candidate_processing") is not False:
        fail(errors, "harness identity control is not bit-exact/passive")

    if report.get("regressions") != []:
        fail(errors, "regressions must be an empty explicit list")

    gates = report.get("gates", [])
    if len(gates) != 8:
        fail(errors, f"expected exactly eight release gates, found {len(gates)}")
    if [gate.get("id") for gate in gates] != GATE_IDS:
        fail(errors, "release gate IDs are not RG-01..RG-08")
    if any(gate.get("status") != "blocked" for gate in gates):
        fail(errors, "a remaining gate is not blocked")
    if report.get("remaining_gates") != GATE_IDS:
        fail(errors, "remaining_gates does not list RG-01..RG-08")

    if report.get("rights_gap", {}).get("blocked") is not True:
        fail(errors, "rights gap is not explicitly blocked")
    if report.get("rights_gap", {}).get("redistribution_cleared") is not False:
        fail(errors, "rights gap claims redistribution clearance")

    timing = report.get("independent_timing_evidence", {})
    if (timing.get("used_for_qualification") is not False
            or timing.get("measured_here") is not False
            or timing.get("target_device") is not False):
        fail(errors, "independent timing evidence is claimed as qualifying")

    negatives = report.get("negative_claims", {})
    for key in (
        "real_model_weights", "real_media", "real_model_inference", "device_timing",
        "listening_result", "quality_metric", "benchmark_claim", "release_claim",
        "provider_registration", "public_default_selection", "vendor_runtime_invoked",
        "download_attempted",
    ):
        if negatives.get(key) is not False:
            fail(errors, "a prohibited claim is asserted: " + key)

    if report.get("repeatability", {}).get("byte_identical") is not True:
        fail(errors, "three reported repeats are not byte-identical")

    contract_pins = contract.get("artifact_pins", {})
    if not contract_pins:
        fail(errors, "contract artifact pins are empty")
    for path, digest in contract_pins.items():
        if not path.endswith(tuple(reference.STATIC_ARTIFACTS)):
            fail(errors, "contract artifact pin is out of scope: " + path)
        if reference.sha256((HERE / Path(path).name).read_bytes()) != digest:
            fail(errors, "contract artifact pin stale: " + path)
    for path, digest in report.get("artifact_pins", {}).items():
        if not path.endswith(tuple(reference.REPORT_ARTIFACTS)):
            fail(errors, "report artifact pin is out of scope: " + path)
        if reference.sha256((HERE / Path(path).name).read_bytes()) != digest:
            fail(errors, "report artifact pin stale: " + path)


def check_board(errors: List[str], report: Dict[str, Any], contract: Dict[str, Any]) -> None:
    try:
        links, digest = reference.board_link_projection()
    except ValueError as error:
        fail(errors, "board projection failed: " + str(error))
        return
    if report.get("board_links") != links:
        fail(errors, "report board link projection mismatch")
    if report.get("board_link_projection_sha256") != digest:
        fail(errors, "report board link digest mismatch")
    if contract.get("board_links") != links:
        fail(errors, "contract board link projection mismatch")
    if contract.get("board_link_projection_sha256") != digest:
        fail(errors, "contract board link digest mismatch")
    if report.get("board_link_fields") != list(reference.LINK_FIELDS):
        fail(errors, "board link fields changed")
    if report.get("board_mutable_fields_excluded") != list(reference.MUTABLE_FIELDS_EXCLUDED):
        fail(errors, "board mutable-field exclusions changed")
    if "board_sha256" in report or "board_file_sha256" in report:
        fail(errors, "the mutable full board is hashed")


def check_invalid_cases(errors: List[str]) -> None:
    for bad in (
        "not-a-line",
        "Z" * 64 + "  docs/task-evidence/fastenhancer-medium-reference/x",
        "a" * 64 + "  source:../escape",
        "a" * 64 + "  worktree:../escape",
        "a" * 64 + "  unknown/x",
        "a" * 64 + "  audio-benchmark-platform/plan/swarm/TASKS.json",
    ):
        try:
            reference.parse_pin_lines(bad)
            fail(errors, "invalid pin line accepted: " + repr(bad))
        except ValueError:
            pass
    duplicate = "\n".join([
        f"{'a' * 64}  docs/task-evidence/fastenhancer-medium-reference/x",
        f"{'a' * 64}  docs/task-evidence/fastenhancer-medium-reference/x",
    ])
    try:
        reference.parse_pin_lines(duplicate)
        fail(errors, "duplicate pin accepted")
    except ValueError:
        pass
    for payload in ('{"a":1,"a":2}', '{"a":NaN}', '{"a":Infinity}', '[1,]'):
        try:
            reference.strict_json_loads(payload)
            fail(errors, "invalid JSON accepted: " + payload)
        except ValueError:
            pass
    for request in ([], {}, {"task": reference.TASK, "component": reference.COMPONENT}):
        if reference.admit_request(request)["accepted"]:
            fail(errors, "invalid request accepted")
    for payload, expected in (
        (None, "ASSET_MISSING"),
        ("fe.q8", "ASSET_INVALID"),
        (b"", "ASSET_SIZE_MISMATCH"),
        (b"\x00" * reference.ASSET["byte_count"], "ASSET_DIGEST_MISMATCH"),
    ):
        if reference.admit_asset(payload) != expected:
            fail(errors, "asset rejection mismatch: " + expected)


def check_reproduction(errors: List[str]) -> str:
    code = (
        "import sys; sys.path.insert(0, " + repr(str(HERE)) + "); "
        "import reference; sys.stdout.write(reference.sha256("
        "reference.canonical_report_bytes(reference.build_report())))"
    )
    env = dict(os.environ, PYTHONDONTWRITEBYTECODE="1")
    digests = []
    for _ in range(3):
        result = subprocess.run(
            [sys.executable, "-c", code], cwd=HERE, env=env,
            capture_output=True, text=True, check=False,
        )
        if result.returncode != 0:
            fail(errors, "cold-start regeneration failed: " + result.stderr.strip())
            return ""
        digests.append(result.stdout.strip())
    if len(set(digests)) != 1:
        fail(errors, "three cold-start regenerations are not byte-identical")
    actual = reference.sha256(REPORT.read_bytes())
    if digests and digests[0] != actual:
        fail(errors, "cold-start digest differs from report.json")
    return actual


def check_licensing(errors: List[str]) -> None:
    for path in sorted(HERE.glob("*.py")):
        head = "\n".join(path.read_text(encoding="utf-8").splitlines()[:4])
        if reference.SPDX_LICENSE_LINE not in head or reference.SPDX_COPYRIGHT_LINE not in head:
            fail(errors, "missing SPDX header: " + path.name)
    readme = (HERE / "README.md").read_text(encoding="utf-8")
    if (f"<!-- {reference.SPDX_COPYRIGHT_LINE} -->" not in readme
            or f"<!-- {reference.SPDX_LICENSE_LINE} -->" not in readme):
        fail(errors, "README.md lacks SPDX provenance")
    for name in LICENSE_SIDECARS:
        if (HERE / name).read_text(encoding="utf-8") != reference.LICENSE_TEXT:
            fail(errors, "license sidecar content mismatch: " + name)
    reuse = (reference.SDK_ROOT / "REUSE.toml").read_text(encoding="utf-8")
    if '"docs/**"' not in reuse or 'SPDX-License-Identifier = "Apache-2.0"' not in reuse:
        fail(errors, "REUSE.toml no longer covers docs/** as Apache-2.0")


def check_scope(errors: List[str]) -> int:
    result = subprocess.run(
        ["git", "-C", str(reference.SDK_ROOT), "status", "--porcelain=v1",
         "--untracked-files=all"],
        capture_output=True, text=True, check=True,
    )
    changed = []
    for line in result.stdout.splitlines():
        path = line[3:] if len(line) > 3 else line
        if " -> " in path:
            path = path.split(" -> ", 1)[1]
        changed.append(path)
        if path and not path.startswith(reference.TASK_PREFIX + "/"):
            fail(errors, "change outside task scope: " + path)
    diff_check = subprocess.run(
        ["git", "-C", str(reference.SDK_ROOT), "diff", "--check"],
        capture_output=True, text=True, check=False,
    )
    if diff_check.returncode != 0:
        fail(errors, "git diff --check failed: " + diff_check.stdout.strip())
    for path in sorted(HERE.iterdir()):
        if path.is_file() and path.suffix in {".py", ".json", ".md", ".sha256", ".license"}:
            for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
                if line != line.rstrip():
                    fail(errors, f"trailing whitespace: {path.name}:{number}")
    return len(changed)


def main() -> int:
    errors: List[str] = []
    check_file_set(errors)
    pins = check_pins(errors)
    payloads = check_json(errors)
    if payloads:
        check_report_content(errors, payloads["report"], payloads["contract"])
        check_board(errors, payloads["report"], payloads["contract"])
    check_invalid_cases(errors)
    digest = check_reproduction(errors)
    check_licensing(errors)
    changed = check_scope(errors)
    if errors:
        print("\n".join("FAIL: " + error for error in errors))
        print(f"pins_ok={bool(pins)} reproduction_ok={bool(digest)} report_sha256={digest}")
        return 1
    print(
        f"pins_ok={pins} json_ok=2 strict_reproduction_ok=3 invalid_cases_ok=1 "
        f"board_identity_ok=1 gates_blocked=8 licensing_ok=1 scope_ok=1 "
        f"changed_files={changed} report_sha256={digest}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
