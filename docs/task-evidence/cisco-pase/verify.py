"""Read-only strict verifier for SDK-CISCO-PASE.

Usage::

    PYTHONDONTWRITEBYTECODE=1 python3 verify.py

Fails closed on non-canonical or duplicate-key/nonfinite JSON, stale digests,
stale pins, a non-enhancement profile, a promoted missing result, a qualified
claim, an admitted candidate manifest, an unblocked release gate, a license
gap, out-of-scope worktree changes, whitespace damage or a dirty
``git diff --check``.  Never writes.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path
from typing import Any, Dict, List

sys.dont_write_bytecode = True

import reference  # noqa: E402

HERE = Path(__file__).resolve().parent
SDK_ROOT = HERE.parents[2]
SOURCE_ROOT = SDK_ROOT.parents[2]
REPORT = HERE / "report.json"
SIDECAR = HERE / "report.json.sha256"
CONTRACT = HERE / "contract.json"
PINS = HERE / "SOURCES.sha256"
README = HERE / "README.md"

SPDX_LICENSE = "SPDX" "-License-Identifier: Apache-2.0"
SPDX_COPYRIGHT = "SPDX" "-FileCopyrightText: 2026 Tsakanyan Hovhannes"
LICENSE_SIDECARS = (
    "SOURCES.sha256.license",
    "contract.json.license",
    "report.json.license",
    "report.json.sha256.license",
)
REQUIRED_REPORT_KEYS = {
    "schema_id", "task", "title", "component", "repository", "branch",
    "base_commit", "status", "evidence_status", "decision", "defer_before",
    "scope", "acceptance_profile", "format", "reference", "asset_admission",
    "stream_geometry", "conservation_cases", "coverage_sweep",
    "identity_control", "dual_stream_control", "clean_preservation_control",
    "adverse_rejections", "adverse_all_rejected", "exact_blockers",
    "release_gates", "qualification", "boundary", "board_row", "source_pins",
    "boundary_pins", "repeatability", "negative_claims", "reopen_condition",
}
REQUIRED_CONTRACT_KEYS = {
    "schema_id", "task", "title", "component", "repository", "branch",
    "base_commit", "status", "evidence_status", "decision", "defer_before",
    "qualification_status", "verification_profile", "scope", "format",
    "public_boundary", "reference", "asset_admission", "board_row",
    "exact_blockers", "release_gates", "source_pins", "boundary_pins",
    "artifact_pins", "negative_claims", "reopen_condition",
}
PROFILE_ITEMS = {
    "identity_and_noisy_control",
    "established_task_matched_baseline",
    "paired_si_sdr",
    "paired_stoi",
    "clean_speech_preservation",
    "peaks_and_invalid_outputs",
    "unpaired_screen_or_authorized_listening",
    "alignment_state_memory",
    "content_and_availability_timing",
}


def strict_json(path: Path) -> Any:
    return reference.load_strict_json(path)


def check_json_files(errors: List[str]) -> Dict[str, Any]:
    try:
        report = strict_json(REPORT)
        contract = strict_json(CONTRACT)
    except (OSError, ValueError) as error:
        errors.append("strict JSON failed: " + str(error))
        return {}
    if not isinstance(report, dict) or not isinstance(contract, dict):
        errors.append("report or contract root is not an object")
        return {}
    if REPORT.read_bytes() != (reference.canonical_text(report) + "\n").encode("utf-8"):
        errors.append("report.json is not canonical byte output")
    if CONTRACT.read_bytes() != (reference.canonical_text(contract) + "\n").encode("utf-8"):
        errors.append("contract.json is not canonical byte output")
    _, digest = reference.canonical_report(report)
    if SIDECAR.read_text(encoding="ascii") != digest + "\n":
        errors.append("report.json.sha256 is stale")
    return {"report": report, "contract": contract}


def check_pins(errors: List[str]) -> int:
    count = 0
    for raw in PINS.read_text(encoding="utf-8").splitlines():
        if not raw or raw.startswith("#"):
            continue
        count += 1
        parts = raw.split("  ", 1)
        if len(parts) != 2 or len(parts[0]) != 64:
            errors.append("malformed pin line: " + repr(raw))
            continue
        digest, raw_path = parts
        if raw_path.startswith("source:"):
            path = SOURCE_ROOT / raw_path.split(":", 1)[1]
        else:
            path = SDK_ROOT / raw_path
        if not path.is_file():
            errors.append("pinned file missing: " + raw_path)
        elif reference.sha256_bytes(path.read_bytes()) != digest:
            errors.append("pinned bytes changed: " + raw_path)
    if PINS.read_bytes() != reference.sources_bytes():
        errors.append("SOURCES.sha256 is not the deterministic generated bytes")
    return count


def check_artifact_pins(errors: List[str], contract: Dict[str, Any]) -> None:
    pins = contract.get("artifact_pins")
    if not isinstance(pins, dict):
        errors.append("contract artifact_pins is not an object")
        return
    expected_names = {reference.TASK_PREFIX + name
                      for name in reference.ARTIFACT_FILES}
    if set(pins) != expected_names:
        errors.append("artifact pin set mismatch")
    for path, digest in pins.items():
        full = SDK_ROOT / path
        if not full.is_file():
            errors.append("artifact pin missing: " + path)
        elif reference.file_digest(full) != digest:
            errors.append("artifact pin stale: " + path)
    for forbidden in ("contract.json", "SOURCES.sha256"):
        if reference.TASK_PREFIX + forbidden in pins:
            errors.append("self-referential artifact pin: " + forbidden)


def check_board(errors: List[str], report: Dict[str, Any],
                contract: Dict[str, Any]) -> None:
    live = reference.board_row()
    if report.get("board_row") != live:
        errors.append("report board identity is stale")
    if contract.get("board_row") != live:
        errors.append("contract board identity is stale")
    row = report.get("board_row", {})
    if row.get("full_tasks_json_hashed") is not False:
        errors.append("full task board is hashed")
    stable = row.get("stable_fields", {})
    if reference.object_digest(stable) != row.get("stable_sha256"):
        errors.append("stable board hash mismatch")
    if stable.get("id") != reference.TASK_ID:
        errors.append("stable board task id mismatch")
    for section in ("source_pins", "boundary_pins"):
        for path in report.get(section, {}):
            if path.endswith("TASKS.json"):
                errors.append("mutable task board is pinned in " + section)


def check_source_pins(errors: List[str], report: Dict[str, Any],
                      contract: Dict[str, Any]) -> None:
    if report.get("source_pins") != reference.SOURCE_PINS:
        errors.append("report source pins differ from the frozen table")
    if report.get("boundary_pins") != reference.BOUNDARY_PINS:
        errors.append("report boundary pins differ from the frozen table")
    if contract.get("source_pins") != reference.SOURCE_PINS:
        errors.append("contract source pins differ from the frozen table")
    if contract.get("boundary_pins") != reference.BOUNDARY_PINS:
        errors.append("contract boundary pins differ from the frozen table")


def check_report(errors: List[str], report: Dict[str, Any]) -> None:
    if not REQUIRED_REPORT_KEYS <= set(report):
        errors.append("report missing sections: "
                      + ", ".join(sorted(REQUIRED_REPORT_KEYS - set(report))))
        return
    if report["schema_id"] != reference.REPORT_SCHEMA:
        errors.append("unexpected report schema")
    if report["status"] != "proposal_only_synthetic_incomplete":
        errors.append("report is not proposal-only synthetic")
    if report["evidence_status"] != "incomplete" or report["decision"] != "DEFER":
        errors.append("missing incomplete/DEFER disposition")
    if report["defer_before"] != "opt_in_adapter_exposure":
        errors.append("unexpected defer point")
    if report["task"] != reference.TASK_ID or report["component"] != reference.COMPONENT:
        errors.append("report task or component mismatch")
    if report["base_commit"] != reference.BASE_COMMIT:
        errors.append("report base commit mismatch")

    qualification = report["qualification"]
    if qualification.get("status") != "not_qualified":
        errors.append("qualification status is not not_qualified")
    for flag in ("qualifies", "all_required_results_present",
                 "missing_result_promoted", "candidate_source_present",
                 "candidate_weights_present", "candidate_runtime_present",
                 "asset_manifest_admitted", "real_recording_evidence",
                 "exact_runtime_parity", "paired_scoring", "device_timing",
                 "listening", "provider_intake"):
        if qualification.get(flag) is not False:
            errors.append("qualification flag promoted: " + flag)

    gates = report["release_gates"]
    if len(gates) != 8:
        errors.append("expected exactly eight release gates")
    if [gate.get("id") for gate in gates] != [
            "RG-%02d" % index for index in range(1, 9)]:
        errors.append("release gate IDs are not RG-01..RG-08")
    if any(gate.get("status") != "blocked" for gate in gates):
        errors.append("a release gate is not blocked")

    profile = report["acceptance_profile"]
    if profile.get("profile") != "enhancement":
        errors.append("enhancement acceptance profile not recorded")
    items = profile.get("required_items", {})
    if set(items) != PROFILE_ITEMS:
        errors.append("enhancement profile item set mismatch")
    for name, item in items.items():
        if item.get("status") not in {"synthetic_only", "blocked"}:
            errors.append("profile item promoted: " + name)

    cases = report["conservation_cases"]
    if len(cases) != 11:
        errors.append("expected eleven frozen conservation cases")
    for case in cases:
        if not case["overlap_free"] or not case["union_equals_content"]:
            errors.append("conservation case does not conserve: "
                          + case["case_id"])
        if not case["drain_within_budget"]:
            errors.append("conservation case exceeds drain budget: "
                          + case["case_id"])
        if case["valid_samples"] != (case["content_interval"][1]
                                     - case["content_interval"][0]):
            errors.append("conservation case valid total mismatch: "
                          + case["case_id"])

    sweep = report["coverage_sweep"]
    if sweep.get("all_conserved") is not True or sweep.get("checks") != 4105:
        errors.append("coverage sweep is not the frozen 4105-check sweep")

    identity = report["identity_control"]
    if identity.get("bit_identical") is not True:
        errors.append("identity control is not bit-exact")
    if identity.get("input_digest") != identity.get("output_digest"):
        errors.append("identity control digests differ")

    dual = report["dual_stream_control"]
    if dual.get("exact") is not True:
        errors.append("dual-stream control is not exact")
    if dual.get("status") != "synthetic_only_not_qualified":
        errors.append("dual-stream control is promoted")
    if dual.get("hop_samples") is None or (
            dual["hop_samples"] % reference.FRAME_SAMPLES != 0):
        errors.append("dual-stream hop is not frame aligned")
    if dual.get("vocoder_invoked") is not False:
        errors.append("dual-stream control claims a vocoder")

    preservation = report["clean_preservation_control"]
    if preservation.get("status") != "surrogate_only_not_qualified":
        errors.append("preservation control is promoted")
    if preservation.get("bit_identical") is not False:
        errors.append("preservation control claims exact preservation")
    if preservation.get("clean_speech_preserved") is not False:
        errors.append("preservation control claims clean preservation")
    if not preservation.get("si_sdr_db", 0.0) < 0.0:
        errors.append("preservation control is not a damage control")

    adverse = report["adverse_rejections"]
    if len(adverse) != 52 or report.get("adverse_all_rejected") is not True:
        errors.append("adverse rejection count/flag mismatch")
    for item in adverse:
        if item.get("status") != "rejected" or item.get("state_unchanged") is not True:
            errors.append("adverse case not rejected immutably: " + item["case_id"])

    admission = report["asset_admission"]
    if admission.get("asset_readiness") != "blocked":
        errors.append("asset admission is not blocked")
    if admission.get("required_assets") != []:
        errors.append("an upstream required asset is claimed")
    if admission.get("candidate_artifact_pins") != []:
        errors.append("a candidate artifact pin is claimed")
    if admission.get("upstream_artifact_names_known") is not False:
        errors.append("upstream artifact names are claimed known")
    if admission.get("bytes_read") != 0 or admission.get("downloads_attempted") != 0:
        errors.append("an asset byte was read or downloaded")

    boundary = report["boundary"]
    if not boundary or any(value is not False for value in boundary.values()):
        errors.append("a boundary flag claims a change")

    repeat = report["repeatability"]
    digests = repeat.get("case_matrix_digests", [])
    if repeat.get("runs") != 3 or repeat.get("byte_identical") is not True:
        errors.append("repeatability is not three byte-identical runs")
    if len(digests) != 3 or len(set(digests)) != 1:
        errors.append("case-matrix repeat digests differ")

    text = reference.canonical_text(report)
    if '"qualifies":true' in text or '"status":"qualified"' in text:
        errors.append("canonical report contains a qualified claim")
    if '"vocoder_invoked":true' in text:
        errors.append("report claims a vocoder invocation")
    if "TASKS.json" in reference.canonical_text(report["source_pins"]):
        errors.append("mutable task board appears in source pins")


def check_contract(errors: List[str], contract: Dict[str, Any],
                   report: Dict[str, Any]) -> None:
    if not REQUIRED_CONTRACT_KEYS <= set(contract):
        errors.append("contract missing sections: "
                      + ", ".join(sorted(REQUIRED_CONTRACT_KEYS - set(contract))))
        return
    if contract["schema_id"] != reference.CONTRACT_SCHEMA:
        errors.append("unexpected contract schema")
    if contract["task"] != reference.TASK_ID or contract["component"] != reference.COMPONENT:
        errors.append("contract task or component mismatch")
    if contract["base_commit"] != reference.BASE_COMMIT:
        errors.append("contract base commit mismatch")
    if contract["branch"] != reference.BRANCH:
        errors.append("contract branch mismatch")
    if contract["decision"] != "DEFER" or contract["evidence_status"] != "incomplete":
        errors.append("contract disposition is not DEFER/incomplete")
    if contract["qualification_status"] != "not_qualified":
        errors.append("contract qualification is not not_qualified")
    if contract["verification_profile"] != "enhancement":
        errors.append("contract verification profile mismatch")
    if contract.get("release_gates") != report.get("release_gates"):
        errors.append("contract/report release gates differ")
    if contract.get("exact_blockers") != report.get("exact_blockers"):
        errors.append("contract/report blockers differ")
    boundary = contract.get("public_boundary", {})
    for key in ("c_provider_added", "public_api_abi_changed",
                "installed_v0_behavior_changed", "shared_build_or_ci_changed",
                "processor_exposure"):
        if boundary.get(key) is not False:
            errors.append("contract boundary flag is not false: " + key)
    scope = contract.get("scope", {})
    if scope.get("synthetic_only") is not True or scope.get("task_local_only") is not True:
        errors.append("contract scope must be synthetic-only and task-local")
    for key, value in scope.items():
        if key in {"synthetic_only", "task_local_only"}:
            continue
        if value is not False:
            errors.append("contract scope flag is not false: " + key)
    admission = contract.get("asset_admission", {})
    if admission.get("asset_readiness") != "blocked":
        errors.append("contract asset admission is not blocked")
    if admission.get("required_assets") != []:
        errors.append("contract claims upstream required assets")
    check_artifact_pins(errors, contract)


def check_repeats(errors: List[str], report: Dict[str, Any]) -> None:
    if not report:
        return
    texts = []
    for _ in range(3):
        built = reference.build_report()
        text, _ = reference.canonical_report(built)
        texts.append(text)
    if len(set(texts)) != 1:
        errors.append("three fresh report builds differ")
    if texts[0].encode("utf-8") != REPORT.read_bytes():
        errors.append("fresh build does not match report.json")


def check_licensing(errors: List[str]) -> None:
    for path in sorted(HERE.glob("*.py")):
        head = "\n".join(path.read_text(encoding="utf-8").splitlines()[:4])
        if SPDX_LICENSE not in head or SPDX_COPYRIGHT not in head:
            errors.append("missing SPDX header: " + path.name)
    readme_head = "\n".join(README.read_text(encoding="utf-8").splitlines()[:4])
    if SPDX_LICENSE not in readme_head or SPDX_COPYRIGHT not in readme_head:
        errors.append("README.md is missing its SPDX header")
    for name in LICENSE_SIDECARS:
        path = HERE / name
        if not path.is_file():
            errors.append("missing license sidecar: " + name)
            continue
        content = path.read_text(encoding="utf-8")
        if SPDX_LICENSE not in content or SPDX_COPYRIGHT not in content:
            errors.append("invalid license sidecar: " + name)
    reuse = (SDK_ROOT / "REUSE.toml").read_text(encoding="utf-8")
    if '"docs/**"' not in reuse or (
            'SPDX' "-License-Identifier = \"Apache-2.0\"") not in reuse:
        errors.append("REUSE.toml no longer covers docs/** as Apache-2.0")


def check_scope(errors: List[str]) -> List[str]:
    result = subprocess.run(
        ["git", "-C", str(SDK_ROOT), "status", "--porcelain=v1",
         "--untracked-files=all"],
        capture_output=True, text=True, check=True)
    changed: List[str] = []
    for line in result.stdout.splitlines():
        path = line[3:] if line[:2].strip() else line
        if " -> " in path:
            path = path.split(" -> ", 1)[1]
        changed.append(path)
        if not path.startswith(reference.TASK_PREFIX):
            errors.append("change outside task scope: " + path)
    diff_check = subprocess.run(
        ["git", "-C", str(SDK_ROOT), "diff", "--check"],
        capture_output=True, text=True)
    if diff_check.returncode != 0:
        errors.append("git diff --check failed: " + diff_check.stdout.strip())
    return changed


def main() -> int:
    errors: List[str] = []
    loaded = check_json_files(errors)
    report = loaded.get("report", {})
    contract = loaded.get("contract", {})
    pin_count = check_pins(errors)
    if report:
        check_report(errors, report)
        check_source_pins(errors, report, contract)
        check_board(errors, report, contract)
    if contract:
        check_contract(errors, contract, report)
    check_repeats(errors, report)
    check_licensing(errors)
    changed = check_scope(errors)
    if errors:
        for error in errors:
            print("FAIL: " + error)
        return 1
    print(f"pins_ok={pin_count} json_ok=2 report_sha256="
          f"{reference.file_digest(REPORT)} repeats_ok=3 "
          f"licensing_ok=1 scope_ok=1 changed_files={len(changed)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
