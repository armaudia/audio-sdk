"""Read-only verification of the task-local Rate-profile evidence package.

Run with the pinned interpreter from this directory. The verifier never rewrites
evidence. It fails closed on stale or malformed pins, non-canonical JSON,
non-finite or duplicate JSON keys, missing invalid-case rejections, unpinned
files, licensing gaps and any worktree change outside the task directory.
"""

from __future__ import annotations

import json
from pathlib import Path
import subprocess
import sys
from typing import Any, Dict, List, Tuple

import reference

HERE = Path(__file__).resolve().parent
SDK_ROOT = HERE.parents[2]
PINS = HERE / "SOURCES.sha256"
REPORT = HERE / "report.json"
SIDECAR = HERE / "report.json.sha256"
CONTRACT = HERE / "contract.json"
SPDX_LICENSE = "SPDX" "-License-Identifier: Apache-2.0"
SPDX_COPYRIGHT = "SPDX" "-FileCopyrightText: 2026 Tsakanyan Hovhannes"
REQUIRED_REPORT_KEYS = {
    "schema_id", "task_id", "title", "base_commit", "profile", "status",
    "qualification_status", "no_missing_result_qualifies_candidate", "decision",
    "scope", "boundary", "format", "deliverable", "contract_id",
    "contract_sha256", "source_pins", "boundary_pins", "tool_provenance",
    "rate_profile", "conditions", "controls", "adverse", "playback_buffering",
    "regressions", "gates", "missing_evidence", "evidence_classes",
    "repeatability",
}


def _reject_duplicate(items: List[Tuple[str, Any]]) -> Dict[str, Any]:
    result: Dict[str, Any] = {}
    for key, value in items:
        if key in result:
            raise ValueError("duplicate_json_key:" + key)
        result[key] = value
    return result


def _reject_constant(token: str) -> None:
    raise ValueError("nonfinite_json_constant:" + token)


def strict_json(path: Path) -> Dict[str, Any]:
    payload = json.loads(path.read_text(encoding="utf-8"),
                         object_pairs_hook=_reject_duplicate,
                         parse_constant=_reject_constant)
    if not isinstance(payload, dict):
        raise ValueError("root_not_object:" + str(path))
    return payload


def check_pins(errors: List[str]) -> int:
    if not PINS.is_file():
        errors.append("SOURCES.sha256 missing")
        return 0
    allowed = dict(reference.SOURCE_PINS)
    allowed.update(reference.BOUNDARY_PINS)
    for name in reference.LOCAL_PIN_PATHS:
        allowed[reference.TASK_PREFIX + name] = ""
    seen = set()
    count = 0
    for line in PINS.read_text(encoding="ascii").splitlines():
        if not line or line.startswith("#"):
            continue
        count += 1
        parts = line.split("  ", 1)
        if len(parts) != 2 or len(parts[0]) != 64 or any(c not in "0123456789abcdef" for c in parts[0]):
            errors.append("malformed_pin:" + repr(line))
            continue
        digest, raw = parts
        key = raw.split(":", 1)[1] if raw.startswith("source:") else raw
        if key in seen:
            errors.append("duplicate_pin:" + raw)
            continue
        seen.add(key)
        if raw.startswith("source:"):
            relative = raw.split(":", 1)[1]
            path = reference.SOURCE_ROOT / relative
            expected = reference.SOURCE_PINS.get(relative)
        elif raw.startswith(reference.TASK_PREFIX):
            relative = raw
            path = SDK_ROOT / raw
            expected = "" if relative in allowed else None
        else:
            path = SDK_ROOT / raw
            expected = reference.BOUNDARY_PINS.get(raw)
        if expected is None:
            errors.append("unexpected_pin:" + raw)
            continue
        if expected and expected != digest:
            errors.append("pinned_digest_mismatch:" + raw)
        if not path.is_file():
            errors.append("pin_target_missing:" + raw)
        elif reference.sha256(path.read_bytes()) != digest:
            errors.append("pinned_bytes_changed:" + raw)
    missing = sorted(set(allowed) - seen)
    for raw in missing:
        errors.append("pin_absent:" + raw)
    if PINS.read_bytes() != reference.sources_bytes():
        errors.append("SOURCES.sha256 is not deterministic generated bytes")
    return count


def check_report(errors: List[str]) -> Dict[str, Any]:
    try:
        report = strict_json(REPORT)
        contract = strict_json(CONTRACT)
    except (OSError, ValueError, UnicodeError) as error:
        errors.append("strict_json_failed:" + str(error))
        return {}
    missing = sorted(REQUIRED_REPORT_KEYS - set(report))
    if missing:
        errors.append("report_missing_keys:" + ",".join(missing))
        return report
    if REPORT.read_bytes() != reference.canonical_report_bytes(report):
        errors.append("report_not_canonical_bytes")
    digest = reference.sha256(REPORT.read_bytes())
    expected_sidecar = f"{digest}  report.json\n".encode("ascii")
    if not SIDECAR.is_file() or SIDECAR.read_bytes() != expected_sidecar:
        errors.append("report_digest_sidecar_stale")
    if report["base_commit"] != reference.BASE_COMMIT:
        errors.append("base_commit_mismatch")
    if report["profile"] != "rate" or reference.PROFILE != "rate":
        errors.append("rate_profile_not_applied")
    if report["status"] != reference.STATUS or report["qualification_status"] != reference.QUALIFICATION:
        errors.append("proposal_status_mismatch")
    if report["decision"] != "DEFER" or not report["no_missing_result_qualifies_candidate"]:
        errors.append("missing_DEFER_disposition")
    for key, value in report["boundary"].items():
        if key in {"registered", "enabled_by_default", "default_selected",
                   "public_api_abi_change", "provider_registration",
                   "descriptor_registry_change", "shared_cmakelists_change",
                   "installed_v0_behavior_change", "processor_exposure"} and value is not False:
            errors.append("boundary_claim_not_false:" + key)
    if report["boundary"]["descriptor_settings"] != {}:
        errors.append("descriptor_settings_not_empty")
    fmt = report["format"]
    if (fmt["sample_rate_hz"], fmt["channels"], fmt["sample_format"], fmt["frame_samples"]) != (
            16000, 1, "f32", 160):
        errors.append("public_v0_geometry_changed")
    if fmt["sdk_callback_invoked"] is not False:
        errors.append("sdk_callback_claimed")
    for key in ("real_audio", "real_silero_model", "silero_runtime_or_weights",
                "vendor_model_invoked", "device_timing", "listening",
                "rendered_playback", "public_benchmark", "release_claim",
                "registered_provider"):
        if report["scope"].get(key) is not False:
            errors.append("forbidden_claim:" + key)
    if report["source_pins"] != reference.SOURCE_PINS:
        errors.append("report_source_pins_mismatch")
    if report["boundary_pins"] != reference.BOUNDARY_PINS:
        errors.append("report_boundary_pins_mismatch")
    if report["contract_sha256"] != reference.sha256(CONTRACT.read_bytes()):
        errors.append("contract_digest_mismatch")
    if contract.get("profile") != "rate" or contract.get("task") != reference.TASK:
        errors.append("contract_profile_or_task_mismatch")
    if contract.get("source_pins") != reference.SOURCE_PINS:
        errors.append("contract_source_pins_mismatch")
    if contract.get("boundary_pins") != reference.BOUNDARY_PINS:
        errors.append("contract_boundary_pins_mismatch")
    if contract.get("boundary", {}).get("registered") is not False:
        errors.append("contract_registered_true")
    if contract.get("boundary", {}).get("enabled_by_default") is not False:
        errors.append("contract_enabled_by_default_true")
    if any(contract.get("scope", {}).get(key) is not False for key in
           ("real_audio", "real_silero_model", "silero_runtime_or_weights",
            "vendor_model_invoked", "device_timing", "listening", "release_claim")):
        errors.append("contract_forbidden_claim")
    profile = report["rate_profile"]
    if profile["profile"] != "rate" or profile["rate_stretcher_executed"] is not False:
        errors.append("rate_profile_claim_invalid")
    if profile["rate_cases"] != {name: str(value) for name, value in reference.RATE_CASES.items()}:
        errors.append("rate_cases_mismatch")
    if profile["pitch"] != "not_measured_no_rendered_audio" or profile["transient_audibility"] != (
            "not_measured_no_listening"):
        errors.append("unmeasured_rate_metrics_promoted")
    if set(report["conditions"]) != set(reference.CONDITIONS):
        errors.append("condition_set_mismatch")
    for condition, cases in report["conditions"].items():
        if set(cases) != set(reference.RATE_CASES):
            errors.append("rate_case_set_mismatch:" + condition)
        for case_name, case in cases.items():
            prefix = f"{condition}:{case_name}"
            stop = reference.total_samples(condition)
            if case["source_interval"] != [0, stop]:
                errors.append("source_interval_wrong:" + prefix)
            boundaries = [item[0] for item in case["event_intervals"]]
            if boundaries != list(range(0, stop, 160)) or case["event_intervals"][-1][1] != stop:
                errors.append("event_intervals_not_exact:" + prefix)
            mapping = case["mapping"]
            if not mapping or mapping[0]["source"][0] != 0 or mapping[0]["output"][0] != 0:
                errors.append("mapping_start_wrong:" + prefix)
            trims = sorted(tuple(row["trim"]) for row in case["pause_decisions"]
                           if row["trim"] is not None)
            gaps = []
            if mapping[0]["source"][0] != 0:
                gaps.append((0, mapping[0]["source"][0]))
            for index in range(len(mapping) - 1):
                if mapping[index]["source"][1] != mapping[index + 1]["source"][0]:
                    gaps.append((mapping[index]["source"][1], mapping[index + 1]["source"][0]))
            if mapping[-1]["source"][1] != stop:
                gaps.append((mapping[-1]["source"][1], stop))
            if gaps != trims:
                errors.append("mapping_source_gap_not_declared:" + prefix)
            if any(mapping[i]["output"][1] != mapping[i + 1]["output"][0]
                   for i in range(len(mapping) - 1)):
                errors.append("mapping_output_gap:" + prefix)
            if mapping[-1]["output"][1] != case["output_interval"][1]:
                errors.append("mapping_output_end_wrong:" + prefix)
            if case["final_partial"]["source"] != [stop - 37, stop] or not case[
                    "final_partial"]["final_flag"]:
                errors.append("final_partial_wrong:" + prefix)
            if case["available_ns_last"] != 1767225600000000000 + stop * 62500:
                errors.append("fixture_clock_wrong:" + prefix)
            if case["pitch_proxy_hz"] is not None or case["pitch_status"] != (
                    "not_measured_no_rendered_audio"):
                errors.append("pitch_claimed:" + prefix)
            if case["transient_audibility"] != "not_measured_no_listening":
                errors.append("transient_audibility_claimed:" + prefix)
            if case["accepted_frame_count"] != len(case["event_intervals"]) or case["rejections"]:
                errors.append("frame_acceptance_inconsistent:" + prefix)
    controls = report["controls"]
    if not controls["all_present"]:
        errors.append("controls_not_all_present")
    if controls["identity"]["word_span_overlap_samples"] != 0:
        errors.append("identity_control_overlap")
    if controls["named_baseline"]["word_span_overlap_samples"] <= 0:
        errors.append("baseline_overlap_hidden")
    if controls["named_baseline"]["published_source_report"]["status"] != (
            "source_reported_not_reproduced"):
        errors.append("published_reference_promoted")
    if "candidate" not in controls or "word_span_overlap_samples" not in controls["candidate"]:
        errors.append("candidate_control_missing")
    adverse = report["adverse"]
    if not adverse["all_rejected"]:
        errors.append("invalid_case_not_rejected")
    for section in ("config_rejections", "frame_rejections", "lifecycle"):
        for name, value in adverse[section].items():
            if name == "dsp_state_unchanged":
                continue
            if value["status"] != "rejected":
                errors.append("invalid_case_not_rejected:" + section + ":" + name)
    for name, value in adverse["frame_rejections"].items():
        if name != "dsp_state_unchanged" and not value["state_unchanged"]:
            errors.append("state_changed_on_rejection:" + name)
    if (adverse["validity"]["unknown_segments"] <= 0
            or adverse["validity"]["unknown_never_counted_as_nonspeech"] is not True):
        errors.append("unknown_validity_not_retained")
    for condition, model in report["playback_buffering"].items():
        if model["clock_id"] != "fixture-monotonic-not-device" or model["deadline_measured"] is not False:
            errors.append("device_timing_claimed:" + condition)
    if not report["regressions"]:
        errors.append("regressions_not_recorded")
    if len(report["gates"]) != len(reference.GATE_NAMES) or any(
            gate["status"] != "blocked" or not gate["reopen_condition"]
            for gate in report["gates"]):
        errors.append("release_gates_not_blocked")
    repeat = report["repeatability"]
    if repeat["count"] != 3 or not repeat["byte_identical"]:
        errors.append("repeatability_not_byte_identical")
    else:
        fresh = reference.repeatability()
        if fresh["digests"] != repeat["digests"]:
            errors.append("cold_start_repeat_mismatch")
    if b"-0.0" in REPORT.read_bytes():
        errors.append("negative_zero_in_report")
    return report


def check_licensing(errors: List[str]) -> None:
    for path in sorted(HERE.glob("*.py")):
        head = "\n".join(path.read_text(encoding="utf-8").splitlines()[:4])
        if SPDX_LICENSE not in head or SPDX_COPYRIGHT not in head:
            errors.append("missing_python_spdx:" + path.name)
    for name in ("SOURCES.sha256.license", "contract.json.license",
                 "report.json.license", "report.json.sha256.license"):
        text = (HERE / name).read_text(encoding="utf-8") if (HERE / name).is_file() else ""
        if SPDX_LICENSE not in text or SPDX_COPYRIGHT not in text:
            errors.append("missing_license_sidecar:" + name)
    reuse = (SDK_ROOT / "REUSE.toml").read_text(encoding="utf-8")
    if '"docs/**"' not in reuse or 'SPDX-License-Identifier = "Apache-2.0"' not in reuse:
        errors.append("REUSE.toml_docs_coverage_missing")


def check_scope(errors: List[str]) -> List[str]:
    result = subprocess.run(["git", "-C", str(SDK_ROOT), "status", "--porcelain=v1",
                             "--untracked-files=all"], capture_output=True, text=True)
    if result.returncode != 0:
        errors.append("git_status_failed:" + result.stderr.strip())
        return []
    changed = []
    for line in result.stdout.splitlines():
        path = line[3:] if len(line) > 3 else ""
        if " -> " in path:
            path = path.split(" -> ", 1)[1]
        if path:
            changed.append(path)
            if not path.startswith(reference.TASK_PREFIX):
                errors.append("out_of_scope_change:" + path)
    diff = subprocess.run(["git", "-C", str(SDK_ROOT), "diff", "--check"],
                          capture_output=True, text=True)
    if diff.returncode != 0:
        errors.append("git_diff_check_failed:" + diff.stdout.strip())
    pinned = {reference.TASK_PREFIX + name for name in reference.LOCAL_PIN_PATHS}
    pinned.add(reference.TASK_PREFIX + "SOURCES.sha256")
    for path in sorted(HERE.iterdir()):
        if path.is_file() and reference.TASK_PREFIX + path.name not in pinned:
            errors.append("unpinned_task_file:" + path.name)
    return changed


def main() -> int:
    errors: List[str] = []
    pins = check_pins(errors)
    report = check_report(errors)
    check_licensing(errors)
    changed = check_scope(errors)
    digest = reference.sha256(REPORT.read_bytes()) if REPORT.is_file() else "unavailable"
    if errors:
        for error in errors:
            print("FAIL: " + error)
        print(f"pins_ok={pins == len(reference.SOURCE_PINS) + len(reference.BOUNDARY_PINS) + len(reference.LOCAL_PIN_PATHS) and not any(e.startswith(('malformed_pin', 'duplicate_pin', 'unexpected_pin', 'pin_', 'pinned_', 'SOURCES')) for e in errors)} "
              f"json_ok={bool(report)} reproduction_ok={not any('canonical' in e or 'sidecar' in e or 'repeat' in e for e in errors)} "
              f"report_sha256={digest} changed_files={len(changed)} failures={len(errors)}")
        return 1
    print(f"PASS pins={pins} files={len(changed)} profile=rate status={report['status']} "
          f"report_sha256={digest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
